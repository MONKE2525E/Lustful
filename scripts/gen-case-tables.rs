// Prints src/runtime/case_tables.h: Rust's Unicode case maps and the
// two properties str::to_lowercase's final-sigma rule reads, derived
// from rustc's own behavior so the Unicode version matches the
// toolchain (W-STD-B). Run:
//   rustc --edition 2024 -O -o /tmp/gen scripts/gen-case-tables.rs && /tmp/gen > src/runtime/case_tables.h
fn is_final(s: &str) -> bool {
    s.to_lowercase().ends_with('ς')
}

fn main() {
    let mut upper = Vec::new();
    let mut lower = Vec::new();
    let mut ci = Vec::new();
    let mut cased = Vec::new();
    for u in 0u32..=0x10FFFF {
        let Some(c) = char::from_u32(u) else { continue };
        let up: Vec<char> = c.to_uppercase().collect();
        if up != [c] {
            upper.push((u, up));
        }
        let lo: Vec<char> = c.to_lowercase().collect();
        if lo != [c] {
            lower.push((u, lo));
        }
        if c == 'Σ' {
            // An uppercase letter: cased, not case-ignorable.
            cased.push(u);
            continue;
        }
        // "{c}Σ" is word-final iff !CI(c) && Cased(c); "A{c}Σ" iff CI(c) || Cased(c).
        let t1 = is_final(&format!("{c}Σ"));
        let t2 = is_final(&format!("A{c}Σ"));
        if t2 && !t1 {
            ci.push(u);
        } else if t1 {
            cased.push(u);
        }
    }
    let map = |name: &str, v: &[(u32, Vec<char>)]| {
        println!("static const uint32_t {name}[][4] = {{");
        for (u, m) in v {
            let mut cs: Vec<u32> = m.iter().map(|&c| c as u32).collect();
            while cs.len() < 3 {
                cs.push(0);
            }
            println!("  {{0x{u:X}, 0x{:X}, 0x{:X}, 0x{:X}}},", cs[0], cs[1], cs[2]);
        }
        println!("}};");
    };
    let ranges = |name: &str, v: &[u32]| {
        // Sorted code points as [lo, hi] ranges.
        let mut rs: Vec<(u32, u32)> = Vec::new();
        for &u in v {
            match rs.last_mut() {
                Some(r) if r.1 + 1 == u => r.1 = u,
                _ => rs.push((u, u)),
            }
        }
        println!("static const uint32_t {name}[][2] = {{");
        for (a, b) in &rs {
            println!("  {{0x{a:X}, 0x{b:X}}},");
        }
        println!("}};");
    };
    println!("// Generated by scripts/gen-case-tables.rs from char::to_uppercase,");
    println!("// char::to_lowercase, and str::to_lowercase's final sigma (W-STD-B).");
    println!("// Do not edit.");
    map("lust_upper_map", &upper);
    map("lust_lower_map", &lower);
    ranges("lust_case_ignorable", &ci);
    ranges("lust_cased", &cased);
    eprintln!("upper {} lower {} ci {} cased {}", upper.len(), lower.len(), ci.len(), cased.len());
}
