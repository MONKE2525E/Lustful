#!/usr/bin/env python3
"""Generates src/rt/ryu_tables.h from the ryu-js 1.0.2 crate tables.

The tables are the DOUBLE_POW5_SPLIT and DOUBLE_POW5_INV_SPLIT constants
from Ulf Adams' Ryu (Apache-2.0 or Boost-1.0), as shipped in ryu-js.
Run from the repo root:  python3 tests/float/gen_ryu_tables.py
"""
import glob
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[2]
candidates = sorted(glob.glob(str(Path.home() / ".cargo/registry/src/*/ryu-js-1.0.2/src/d2s_full_table.rs")))
if not candidates:
    sys.exit("ryu-js 1.0.2 sources not found under ~/.cargo/registry/src")
src = Path(candidates[0]).read_text()


def table(name: str) -> list[tuple[int, int]]:
    m = re.search(rf"pub static {name}[^=]*= \[(.*?)\];", src, re.S)
    if not m:
        sys.exit(f"table {name} not found")
    return [(int(a), int(b)) for a, b in re.findall(r"\((\d+), (\d+)\)", m.group(1))]


inv = table("DOUBLE_POW5_INV_SPLIT")
fwd = table("DOUBLE_POW5_SPLIT")
assert len(inv) == 342 and len(fwd) == 326, (len(inv), len(fwd))
for a, b in inv + fwd:
    assert 0 <= a < 2**64 and 0 <= b < 2**64

out = """/* Ryu pow5 split tables, generated by tests/float/gen_ryu_tables.py from
   ryu-js 1.0.2 (Ulf Adams' Ryu, Apache-2.0 or Boost-1.0). Do not edit.
   Each pair is (low, high) 64-bit halves of a 128-bit table entry. */
static const uint64_t lust_ryu_pow5_inv[342][2] = {
"""
for i in range(0, len(inv), 2):
    row = ", ".join("{%dull, %dull}" % t for t in inv[i : i + 2])
    out += f"    {row},\n"
out += "};\nstatic const uint64_t lust_ryu_pow5[326][2] = {\n"
for i in range(0, len(fwd), 2):
    row = ", ".join("{%dull, %dull}" % t for t in fwd[i : i + 2])
    out += f"    {row},\n"
out += "};\n"

Path(root / "src/rt/ryu_tables.h").write_text(out)
print(f"wrote src/rt/ryu_tables.h ({len(inv)} + {len(fwd)} entries) from {candidates[0]}")
