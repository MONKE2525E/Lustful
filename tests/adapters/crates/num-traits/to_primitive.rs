// num-traits 0.2.19 ToPrimitive on f64: every integer target at and
// around its range edges, fractions, signed zero, NaN, and infinities.
use num_traits::ToPrimitive;

fn main() {
    let xs = [
        0.0, -0.0, 0.9, -0.9, 1.5, -1.5, 127.9, 128.0, -128.9, -129.0, 255.9, 256.0, 32767.5, 32768.0, -32768.9,
        -32769.0, 65535.9, 65536.0, 2147483647.9, 2147483648.0, -2147483648.9, -2147483649.0, 4294967295.9,
        4294967296.0, 9007199254740993.0, 9223372036854775807.0, -9223372036854775808.0, 18446744073709551615.0,
        1.8446744073709552e19, 1.7014118346046923e38, -1.7014118346046923e38, 3.402823669209385e38, -1.0, 1e300,
        -1e300, f64::NAN, f64::INFINITY, f64::NEG_INFINITY, 5e-324,
    ];
    for x in xs {
        println!(
            "{:?}: {:?} {:?} {:?} {:?} {:?} {:?}",
            x,
            x.to_i8(),
            x.to_i16(),
            x.to_i32(),
            x.to_i64(),
            x.to_i128(),
            x.to_isize()
        );
        println!("  {:?} {:?} {:?} {:?} {:?} {:?} {:?}", x.to_u8(), x.to_u16(), x.to_u32(), x.to_u64(), x.to_u128(), x.to_usize(), x.to_f64());
    }
}
