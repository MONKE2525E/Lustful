// Every format flag is accepted for every type, as in Rust; each impl
// reads only the ones it uses (str and bool pad with spaces under `0`).
fn main() {
    println!("[{:+}] [{:#}] [{:05}] [{:.3}] [{:+}] [{:#?}]", "a", "b", "ab", 5, 'c', 5);
    println!("[{:05}] [{:<5}] [{:^5}] [{:>5}] [{:5}]", true, false, true, 'x', "é");
    println!("[{:.0}] [{:.0}] [{:.1}] [{:.0}] [{:.2}]", "abc", 'x', "é€", 2.5, "xyz");
    println!("[{:05}] [{:<05}] [{:^05}] [{:x<5}] [{:*^9}]", -3, -3, 7, 1, "mid");
    println!("[{:05?}] [{:+05}] [{:#06x}] [{:^#7b}]", -3, 3, 255, 5);
    println!("[{:05}] [{:+}] [{:08.2}] [{:+.1e}] [{:>+9.2?}] [{:<09?}]", 1.5, 2.0f32, -3.14159, 12345.0, 1.0, -2.5);
    println!("[{:>8}] [{:08}] [{:+}] [{:+}]", u128::MAX, i128::MIN, 0u8, -0.0);
    println!("[{:e}] [{:E}] [{:.2e}] [{:+e}] [{:010.3e}]", 1500.0, 0.00012f32, 9.999, 1.0, -2.5);
}
