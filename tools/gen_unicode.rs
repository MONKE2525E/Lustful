// Generates src/runtime/unicode_table.h from the rustc that compiles this
// program. Run through scripts/gen-unicode.sh; do not run by hand into the
// tree (the script passes the rustc version so the table records its source).
//
// Data collected, over every Unicode scalar value: range tables for the
// Unicode char predicates lust supports: is_alphabetic, is_numeric,
// is_lowercase, is_uppercase, is_whitespace, is_control. is_alphanumeric
// has no table: this generator asserts it is exactly
// is_alphabetic || is_numeric for every scalar, and the runtime uses that.
// Case mapping (to_uppercase and friends) is not here; W-STD-B owns it.

use std::io::Write as _;

/// One maximal run of consecutive scalars.
fn ranges(mut f: impl FnMut(char) -> bool) -> Vec<(u32, u32)> {
    let mut out = Vec::new();
    let mut start: Option<u32> = None;
    for cp in 0..=0x10FFFFu32 {
        let on = char::from_u32(cp).is_some_and(&mut f);
        match (start, on) {
            (None, true) => start = Some(cp),
            (Some(s), false) => {
                out.push((s, cp - 1));
                start = None;
            }
            _ => {}
        }
    }
    if let Some(s) = start {
        out.push((s, 0x10FFFF));
    }
    out
}

fn emit_ranges(out: &mut String, name: &str, rs: &[(u32, u32)]) {
    out.push_str(&format!("static const uint32_t lust_uni_{name}_ranges[][2] = {{\n"));
    // Several entries per line: tcc reads this header for every program.
    for (i, chunk) in rs.chunks(6).enumerate() {
        if i > 0 {
            out.push('\n');
        }
        out.push_str("    ");
        for (lo, hi) in chunk {
            out.push_str(&format!("{{0x{lo:x}, 0x{hi:x}}}, "));
        }
    }
    out.push_str("\n};\n");
}

fn main() {
    let rustc = std::env::args().nth(1).unwrap_or_else(|| "unknown rustc".into());
    let (maj, min, pat) = char::UNICODE_VERSION;

    // is_alphanumeric == is_alphabetic || is_numeric, for every scalar.
    for cp in 0..=0x10FFFFu32 {
        if let Some(c) = char::from_u32(cp) {
            assert_eq!(c.is_alphanumeric(), c.is_alphabetic() || c.is_numeric(), "U+{cp:04X}");
        }
    }

    let pred: Vec<(&str, Vec<(u32, u32)>)> = vec![
        ("alphabetic", ranges(|c| c.is_alphabetic())),
        ("numeric", ranges(|c| c.is_numeric())),
        ("lowercase", ranges(|c| c.is_lowercase())),
        ("uppercase", ranges(|c| c.is_uppercase())),
        ("whitespace", ranges(|c| c.is_whitespace())),
        ("control", ranges(|c| c.is_control())),
    ];

    let mut out = String::new();
    out.push_str(&format!(
        "/* Unicode char predicate ranges, generated by tools/gen_unicode.rs as\n   compiled by {rustc} (Unicode {maj}.{min}.{pat}, char::UNICODE_VERSION).\n   Regenerate with scripts/gen-unicode.sh. Do not edit. */\n"
    ));
    for (name, rs) in &pred {
        emit_ranges(&mut out, name, rs);
        eprintln!("{name}: {} ranges", rs.len());
    }

    std::io::stdout().write_all(out.as_bytes()).unwrap();
}
