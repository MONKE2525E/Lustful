# Builds a fmt-heavy crate: N modules, each with user Display/Debug impls, a derived Debug, a
# generic Display wrapper used with integer literals, and a run fn that formats them all.
# perfcheck.py times it so fmt checking stays fast at ts-rust's scale (hundreds of impls).
# Usage: python3 make_fmt.py <modules> > crate.rs
import sys

n = int(sys.argv[1])
MODULE = """
struct Cat{k}(u8);

impl fmt::Display for Cat{k} {{
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {{
        match self.0 {{
            0 => f.write_str("none"),
            n => write!(f, "Cat({{n}})"),
        }}
    }}
}}

impl fmt::Debug for Cat{k} {{
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {{
        self.0.fmt(f)
    }}
}}

struct Padded{k}(&'static str);

impl fmt::Display for Padded{k} {{
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {{
        f.pad(self.0)
    }}
}}

#[derive(Debug)]
struct Holder{k} {{
    cat: Cat{k},
    cats: Vec<Cat{k}>,
    maybe: Option<Cat{k}>,
}}

struct Wrap{k}<T>(T);

impl<T: fmt::Display> fmt::Display for Wrap{k}<T> {{
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {{
        write!(f, "[{{}}]", self.0)
    }}
}}

fn run{k}() -> usize {{
    let c = Cat{k}({k} as u8 % 7);
    let a = format!("{{}} {{}} [{{:>8}}] [{{:<8?}}] [{{:08?}}]", c, Cat{k}(0), c, c, Cat{k}(7));
    let b = format!("[{{:>6}}] [{{:^6.2}}] [{{}}]", Padded{k}("ab"), Padded{k}("xyz"), Padded{k}("plain"));
    let h = Holder{k} {{ cat: Cat{k}(1), cats: vec![Cat{k}(2), Cat{k}(0)], maybe: Some(Cat{k}(9)) }};
    let d = format!("{{:?}} {{:#?}} {{:5?}}", h, h, h.cats);
    let w = format!("{{}} {{}} {{}}", Wrap{k}(5), Wrap{k}(Cat{k}(4)), Wrap{k}(Wrap{k}("nested")));
    a.len() + b.len() + d.len() + w.len() + c.to_string().len()
}}
"""

print("// Generated by bench/realish/make_fmt.py. Do not edit.")
print("use std::fmt;")
for k in range(n):
    print(MODULE.format(k=k))
print("fn main() {")
print("    let mut total = 0;")
for k in range(n):
    print(f"    total += run{k}();")
print('    println!("fmt checksum {}", total);')
print("}")
