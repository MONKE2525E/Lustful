# Builds a crate of N warehouse modules: warehouse.rs cloned N times, each copy's types and
# functions renamed with a `_m<k>` suffix, plus a main that runs every module.
# Usage: python3 make.py <modules> > crate.rs
import re
import sys

n = int(sys.argv[1])
src = open(__file__.replace("make.py", "warehouse.rs")).read()
items = re.findall(r"^(?:struct|enum|fn) (\w+)", src, flags=re.M)
pattern = re.compile(r"\b(" + "|".join(sorted(set(items), key=len, reverse=True)) + r")\b")

print("// Generated by bench/realish/make.py. Do not edit.")
for k in range(n):
    module = pattern.sub(lambda m: f"{m.group(1)}_m{k}", src)
    module = module.replace("simulate_m%d(42, 300)" % k, "simulate_m%d(%d, 300)" % (k, 42 + k))
    print(f"\n// ==================== module {k} ====================\n")
    print(module)
print("fn main() {")
print("    let mut total: i64 = 0;")
for k in range(n):
    print(f"    total += run_module_m{k}();")
print('    println!("checksum {}", total);')
print("}")
