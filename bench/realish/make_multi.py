# Builds the multi-file form of the realish crate: the same N warehouse
# copies as make.py, one module file each (m0.rs .. m<N-1>.rs), plus a
# crate root that declares the modules and runs every one. The program
# output (checksum) matches the single-file form for the same N, so the
# two forms cross-check each other in the scale gate.
# Usage: python3 make_multi.py <modules> <outdir>
import os
import re
import sys

n = int(sys.argv[1])
outdir = sys.argv[2]
os.makedirs(outdir, exist_ok=True)
src = open(__file__.replace("make_multi.py", "warehouse.rs")).read()
items = re.findall(r"^(?:struct|enum|fn) (\w+)", src, flags=re.M)
pattern = re.compile(r"\b(" + "|".join(sorted(set(items), key=len, reverse=True)) + r")\b")


def module_text(k):
    module = pattern.sub(lambda m: f"{m.group(1)}_m{k}", src)
    module = module.replace("simulate_m%d(42, 300)" % k, "simulate_m%d(%d, 300)" % (k, 42 + k))
    # The crate root calls each module's entry point.
    module = module.replace(f"fn run_module_m{k}()", f"pub fn run_module_m{k}()", 1)
    return module


for k in range(n):
    with open(os.path.join(outdir, f"m{k}.rs"), "w") as f:
        f.write(f"// Generated by bench/realish/make_multi.py. Do not edit.\n\n")
        f.write(module_text(k))

with open(os.path.join(outdir, "main.rs"), "w") as f:
    f.write("// Generated by bench/realish/make_multi.py. Do not edit.\n\n")
    for k in range(n):
        f.write(f"mod m{k};\n")
    # One imported entry point, so the scale gate has an import to edit.
    f.write("\nuse crate::m3::run_module_m3 as run3;\n")
    f.write("\nfn main() {\n    let mut total: i64 = 0;\n")
    for k in range(n):
        if k == 3:
            f.write("    total += run3();\n")
        else:
            f.write(f"    total += crate::m{k}::run_module_m{k}();\n")
    f.write('    println!("checksum {}", total);\n}\n')
