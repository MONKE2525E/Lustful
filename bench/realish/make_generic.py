# Builds the generic multi-file realish crate: N modules (m0.rs ..
# m<N-1>.rs), each one warehouse copy (warehouse.rs, as make_multi.py)
# plus one copy of the generic half (generic.rs), items renamed per
# module, and a crate root that runs both halves of every module.
#
# Density per module, against ts-rust's handwritten code
# (/tmp/lust-ts/inventory/INVENTORY.md): 61 fns with bodies; generic
# fns and methods 9 (15%; ts-rust 3%), trait impl methods 4 (7%;
# ts-rust 11%), closures 12, 4 of them capturing (0.2 per fn; ts-rust
# 0.33), 2 traits, 2 generic structs. So the crate is denser than
# ts-rust in generic fns and thinner in closures; every module has both.
# Usage: python3 make_generic.py <modules> <outdir>
import os
import re
import sys

n = int(sys.argv[1])
outdir = sys.argv[2]
os.makedirs(outdir, exist_ok=True)
here = os.path.dirname(os.path.abspath(__file__))
warehouse = open(os.path.join(here, "warehouse.rs")).read()
generic = open(os.path.join(here, "generic.rs")).read()
src = warehouse + "\n" + generic
items = re.findall(r"^(?:struct|enum|fn|trait) (\w+)", src, flags=re.M)
assert len(items) == len(set(items)), "warehouse.rs and generic.rs share an item name"
pattern = re.compile(r"\b(" + "|".join(sorted(set(items), key=len, reverse=True)) + r")\b")


def module_text(k):
    module = pattern.sub(lambda m: f"{m.group(1)}_m{k}", src)
    module = module.replace("simulate_m%d(42, 300)" % k, "simulate_m%d(%d, 300)" % (k, 42 + k))
    module = module.replace(f"fn run_module_m{k}()", f"pub fn run_module_m{k}()", 1)
    module = module.replace(f"fn run_generic_m{k}()", f"pub fn run_generic_m{k}()", 1)
    return module


for k in range(n):
    with open(os.path.join(outdir, f"m{k}.rs"), "w") as f:
        f.write("// Generated by bench/realish/make_generic.py. Do not edit.\n\n")
        f.write(module_text(k))

with open(os.path.join(outdir, "main.rs"), "w") as f:
    f.write("// Generated by bench/realish/make_generic.py. Do not edit.\n\n")
    for k in range(n):
        f.write(f"mod m{k};\n")
    f.write("\nfn main() {\n    let mut total: i64 = 0;\n")
    for k in range(n):
        f.write(f"    total += crate::m{k}::run_module_m{k}();\n")
        f.write(f"    total += crate::m{k}::run_generic_m{k}();\n")
    f.write('    println!("checksum {}", total);\n}\n')
