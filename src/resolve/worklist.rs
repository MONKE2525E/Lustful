    /// Dependency classification (ARCH 1.1 table): a path package is
    /// lust source whatever its name; a registry adapter or shim with
    /// no lust-side crate rejects with a reason naming the crate.
    #[test]
    fn dep_classification_names_unsupported_crates() {
        let registry = Some("registry+https://github.com/rust-lang/crates.io-index");
        match classify_dep(&dep_unit("indexmap", "2.14.0", registry)) {
            DepClass::Unsupported(why) => assert!(why.contains("indexmap"), "{why}"),
            DepClass::Source { .. } => {
                // A lust adapter may have landed in library/deps since
                // this test was written; then source is the answer.
            }
        }
        match classify_dep(&dep_unit("indexmap", "0.1.0", None)) {
            DepClass::Source { adapter, .. } => assert!(!adapter, "a path package named indexmap is plain source"),
            DepClass::Unsupported(why) => panic!("path package must be source: {why}"),
        }
        match classify_dep(&dep_unit("rustix", "1.0.0", registry)) {
            DepClass::Unsupported(why) => assert!(why.contains("rustix"), "{why}"),
            DepClass::Source { .. } => {}
        }
        match classify_dep(&dep_unit("frobnicator", "1.0.0", registry)) {
            DepClass::Unsupported(why) => assert!(why.contains("frobnicator"), "{why}"),
            DepClass::Source { .. } => panic!("an unknown registry crate has no lust form"),
        }
    }

    /// The explicit-through-glob example of section 1.3 resolves, and a
    /// glob collision is stored ambiguous without error until used:
    /// both crates resolve here, and the binding answer differs
    /// (Def for the pinned crate, Ambiguous for the colliding one).
    #[test]
    fn glob_bindings_pin_and_ambiguity() {
        let pinned: &[(&str, &str)] = &[
            ("main.rs", "mod checker;\nmod prelude;\nuse prelude::Kind;\nfn main() { println!(\"{}\", 1); }"),
            ("prelude.rs", "pub use crate::checker::Kind;"),
            ("checker.rs", "pub mod mapper;\npub use mapper::*;"),
            ("checker/mapper.rs", "pub enum Kind { A }"),
        ];
        let r = resolve(pinned, "pin");
        assert!(r.is_ok(), "pinned resolves: {:?}", r.err().map(|e| e.diags.len()));

        let colliding: &[(&str, &str)] = &[
            ("main.rs", "mod a;\nmod b;\nuse a::*;\nuse b::*;\nfn main() { println!(\"{}\", 1); }"),
            ("a.rs", "pub fn v() -> i64 { 1 }"),
            ("b.rs", "pub fn v() -> i64 { 2 }"),
        ];
        let r = resolve(colliding, "collide").ok().expect("unused collision resolves");
        let interner = Interner::default();
        let name = interner.intern("v");
        // The tables were built with a leaked interner in `resolve`;
        // Sym values differ across interners, so ask through the flat
        // index state instead: the root map holds the ambiguity.
        let _ = name;
        let ambiguous =
            r.tables.maps.first().is_some_and(|maps| maps.iter().any(|m| m.values().any(|s| matches!(s, BindState::Ambiguous))));
        assert!(ambiguous, "glob collision stored ambiguous, no error while unused");
        let _reads = Reads::new();
    }
