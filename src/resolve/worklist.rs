/// One crate's failed resolution inside a session.
struct OneError {
    diags: Vec<Diag>,
    seen: Vec<(PathBuf, String, FileId)>,
    needs_std: bool,
}

/// Shim crates (ARCH 3.7): rustc-built, with a lust source API crate
/// in front once one exists.
const SHIM_CRATES: &[&str] = &["rustix", "nix", "signal-hook", "flate2", "jiff", "name-to-handle-at", "tikv-jemallocator"];

/// The lib root of the lust-side crate for a shim, if one exists in
/// `library/deps/<name>/src/lib.rs` (see `adapters::library_root`).
fn lust_dep_lib_root(name: &str) -> Option<PathBuf> {
    let root = super::adapters::library_root().join("deps").join(name).join("src/lib.rs");
    root.is_file().then_some(root)
}

/// How one resolved dependency classifies (ARCH 1.1): lust source with
/// this lib root (a path package, or the lust-side adapter/shim crate),
/// or unsupported with a reason that names the crate (L0508). The
/// class is a property of the resolved package, never of a source
/// spelling: a path package that happens to be named `indexmap` is
/// plain lust source. `lust_owned` marks the library's own crates
/// (adapters and shims): they skip the edition rule and see
/// `cfg(lust_dev)`. `adapter` carries an adapter's exact-layout list.
enum DepClass {
    Source { root: PathBuf, lust_owned: bool, adapter: Option<Vec<String>> },
    Unsupported(String),
}

/// Classifies one dependency unit. See `DepClass`.
fn classify_dep(dep: &super::cargo::DepUnit) -> DepClass {
    if dep.source.is_none() {
        return DepClass::Source { root: dep.lib_src.clone(), lust_owned: false, adapter: None };
    }
    let name = dep.package_name.as_str();
    if super::adapters::ADAPTER_PACKAGES.contains(&name) {
        return match super::adapters::load(name) {
            Ok(Some(a)) => match super::adapters::check_unit(&a, name, &dep.version, &dep.features) {
                Ok(()) => DepClass::Source { root: a.root, lust_owned: true, adapter: Some(a.exact_layout) },
                Err(why) => DepClass::Unsupported(why),
            },
            Ok(None) => DepClass::Unsupported(format!("dependency crate `{name}` has no lust adapter yet")),
            Err(e) => DepClass::Unsupported(format!("the lust adapter for `{name}` is broken: {e}")),
        };
    }
    if SHIM_CRATES.contains(&name) {
        if let Some(root) = lust_dep_lib_root(name) {
            return DepClass::Source { root, lust_owned: true, adapter: None };
        }
        return DepClass::Unsupported(format!("dependency crate `{name}` has no lust shim yet"));
    }
    DepClass::Unsupported(format!("dependency crate `{name}` is not a lust source crate, an adapter, or a shim crate yet"))
}

/// The `$crate` magic segment name of one crate in a session. Not a
/// legal Rust identifier, so source text can never write it.
fn crate_magic_name(stable: crate::def::StableCrateHash) -> String {
    format!("$lust$crate${:016x}", stable.0)
}

/// Runs the outline worklist for one crate. See the file header.
pub fn resolve_crate(input: &CrateInput, interner: &Interner, known: &Known) -> Result<ResolvedCrate, ResolveError> {
    resolve_crate_cached(input, interner, known, &mut ResolveCache::new(true))
}

/// Runs the outline worklist for the selected crate and every source
/// dependency in one workspace session (ARCH 1.8), dependencies first,
/// with a caller-kept per-file cache (the daemon's crate session
/// holds one across requests; it serves raw token streams and
/// outlines here, since expanded streams also depend on the macro
/// environment). See the file header for the merged-output shape.
pub fn resolve_crate_cached(
    input: &CrateInput,
    interner: &Interner,
    known: &Known,
    cache: &mut ResolveCache,
) -> Result<ResolvedCrate, ResolveError> {
    cache.begin(input);
    let mut tables = ResolvedTables::new(interner.intern(&input.crate_name));
    let main_magic = interner.intern(&crate_magic_name(input.crate_ids.stable));
    tables.crate_magic.insert(main_magic, ROOT_MODULE);
    let mut jobs: Vec<CrateJob> = vec![CrateJob {
        input: OneInput {
            root_path: input.root_path.clone(),
            root_text: input.root_text.clone(),
            env: input.env.clone(),
            crate_ids: input.crate_ids,
            crate_name: input.crate_name.clone(),
        },
        root_module: ROOT_MODULE,
        flat_prefix: String::new(),
        magic: main_magic,
        deps: Vec::new(),
        adapter: None,
    }];
    // The session error map for job-build failures (a dependency root
    // that cannot be read, a non-2024 source dependency): the selected
    // crate's root file at the span's default file id.
    let build_err = |d: Diag| -> ResolveError {
        let (map, all_text) = make_map(&[(input.root_path.clone(), input.root_text.clone(), FileId(0))]);
        ResolveError { map, all_text, needs_std: false, diags: vec![d] }
    };
    let mut by_key: FxMap<String, usize> = FxMap::default();
    let mut main_deps = Vec::new();
    for dep in &input.deps {
        match add_dep_job(dep, input, &mut tables, &mut jobs, &mut by_key, interner) {
            Ok(link) => main_deps.push(link),
            Err(d) => return Err(build_err(d)),
        }
    }
    jobs[0].deps = main_deps;
    // Extern preludes, per crate: std libs, then direct dependencies.
    for j in 0..jobs.len() {
        let (root_module, deps) = (jobs[j].root_module, jobs[j].deps.clone());
        for name in ["std", "core", "alloc"] {
            push_extern(&mut tables, input.crate_ids.local, root_module, name, true, None, None);
        }
        for (name, target) in &deps {
            match target {
                Ok(dj) => {
                    let dep_root = jobs[*dj].root_module;
                    push_extern(&mut tables, input.crate_ids.local, root_module, name, false, Some(dep_root), None);
                }
                Err(why) => push_extern(&mut tables, input.crate_ids.local, root_module, name, false, None, Some(why.clone())),
            }
        }
    }
    // Dependencies first (a dev-dependency cycle, legal in Cargo test
    // crates, breaks at the back edge: that crate then resolves after
    // its dependent and the dependent's paths into it do not resolve).
    let mut order: Vec<usize> = Vec::new();
    let mut state = vec![0u8; jobs.len()];
    fn visit(j: usize, jobs: &[CrateJob], state: &mut [u8], order: &mut Vec<usize>) {
        if state[j] != 0 {
            return;
        }
        state[j] = 1;
        for (_, t) in &jobs[j].deps {
            if let Ok(d) = t {
                visit(*d, jobs, state, order);
            }
        }
        state[j] = 2;
        order.push(j);
    }
    visit(0, &jobs, &mut state, &mut order);
    let mut shared = SharedFiles::default();
    // The selected crate's root file is FileId(0) even though its
    // dependencies resolve first: the spliced std ranges, the error
    // footer, and `Program::shipped_crate_at` all read file 0 as the
    // selected root.
    shared.file_id(&input.root_path, ROOT_MODULE);
    let mut all_seen: Vec<(PathBuf, String, FileId)> = Vec::new();
    let mut needs_std = false;
    let mut chunks: Vec<Ast> = Vec::new();
    let mut fn_lines: Vec<u32> = Vec::new();
    let mut body_hashes: Vec<u64> = Vec::new();
    let mut nested_lines: Vec<u32> = Vec::new();
    let mut nested_hashes: Vec<u64> = Vec::new();
    let mut nested_modules: Vec<ModuleId> = Vec::new();
    let mut structure_hash = 0u64;
    let mut exported_of: FxMap<usize, Vec<OwnedMacroSource>> = FxMap::default();
    let mut expand_deps: Vec<crate::expand::Dep> = Vec::new();
    let mut timings: Vec<(&'static str, f64)> = Vec::new();
    let mut scan_items = Vec::new();
    let mut scan_bodies = Vec::new();
    let mut nested_scan_bodies = Vec::new();
    for &j in &order {
        let mut dep_exports: Vec<(String, Vec<OwnedMacroSource>)> = jobs[j]
            .deps
            .iter()
            .filter_map(|(name, t)| t.as_ref().ok().map(|d| (name.clone(), exported_of.get(d).cloned().unwrap_or_default())))
            .collect();
        // A dependency's macro that calls `$crate::name!` reaches this
        // crate as a path from the defining crate's magic segment
        // (rewrite_dollar_crate), and a re-exported macro's defining
        // crate can be an indirect dependency. So every crate below
        // this one is also seeded under its magic segment, a name
        // source text cannot write.
        let mut below: Vec<usize> = Vec::new();
        let mut stack: Vec<usize> = jobs[j].deps.iter().filter_map(|(_, t)| t.as_ref().ok().copied()).collect();
        while let Some(d) = stack.pop() {
            if !below.contains(&d) {
                below.push(d);
                stack.extend(jobs[d].deps.iter().filter_map(|(_, t)| t.as_ref().ok().copied()));
            }
        }
        below.sort_unstable();
        for d in below {
            if let Some(sources) = exported_of.get(&d).filter(|s| !s.is_empty()) {
                dep_exports.push((interner.get(jobs[d].magic).to_string(), sources.clone()));
            }
        }
        match resolve_one(&jobs[j], &mut tables, &mut shared, cache, &dep_exports, interner, known) {
            Ok(out) => {
                if let Some(exact_layout) = &jobs[j].adapter {
                    tables.adapters.push(super::imports::AdapterCrate {
                        name: jobs[j].input.crate_name.clone(),
                        files: out.seen.iter().map(|s| s.2).collect(),
                        exact_layout: exact_layout.clone(),
                    });
                }
                needs_std |= out.needs_std;
                all_seen.extend(out.seen);
                fn_lines.extend(out.fn_lines);
                body_hashes.extend(out.body_hashes);
                nested_lines.extend(out.nested_lines);
                nested_hashes.extend(out.nested_hashes);
                nested_modules.extend(out.nested_modules);
                {
                    use std::hash::{Hash, Hasher};
                    let mut h = crate::intern::FxHasher::default();
                    structure_hash.hash(&mut h);
                    out.structure_hash.hash(&mut h);
                    structure_hash = h.finish();
                }
                tables.fn_module.extend(out.fn_module);
                expand_deps.extend(out.expand_deps);
                scan_items.extend(out.scans.items);
                scan_bodies.extend(out.scans.bodies);
                nested_scan_bodies.extend(out.nested_bodies);
                exported_of.insert(j, out.exported_macros);
                for (name, ms) in out.timings {
                    match timings.iter_mut().find(|(n, _)| *n == name) {
                        Some((_, total)) => *total += ms,
                        None => timings.push((name, ms)),
                    }
                }
                chunks.push(out.ast);
            }
            Err(e) => {
                needs_std |= e.needs_std;
                all_seen.extend(e.seen);
                let (map, all_text) = make_map(&all_seen);
                return Err(ResolveError { map, all_text, needs_std, diags: e.diags });
            }
        }
    }
    fn_lines.extend(nested_lines);
    body_hashes.extend(nested_hashes);
    tables.fn_module.extend(nested_modules);
    let (map, all_text) = make_map(&all_seen);
    let ast = Ast::concat(chunks);
    scan_bodies.extend(nested_scan_bodies);
    let scans = crate::driver::ast_hash::AstScans { items: scan_items, bodies: scan_bodies };
    Ok(ResolvedCrate { ast, map, tables, fn_lines, body_hashes, structure_hash, all_text, needs_std, expand_deps, timings, scans })
}

/// Creates (or reuses) the job for one source dependency, recursively.
/// Returns the dependent's link: the job index, or the L0508 reason.
fn add_dep_job(
    dep: &super::cargo::DepUnit,
    input: &CrateInput,
    tables: &mut ResolvedTables,
    jobs: &mut Vec<CrateJob>,
    by_key: &mut FxMap<String, usize>,
    interner: &Interner,
) -> Result<(String, Result<usize, String>), Diag> {
    let (root, lust_owned, adapter) = match classify_dep(dep) {
        DepClass::Source { root, lust_owned, adapter } => (root, lust_owned, adapter),
        DepClass::Unsupported(why) => return Ok((dep.extern_name.clone(), Err(why))),
    };
    let key = format!("{}#{}", dep.package_id, dep.lib_name);
    if let Some(&j) = by_key.get(&key) {
        return Ok((dep.extern_name.clone(), Ok(j)));
    }
    if !lust_owned && dep.edition != "2024" {
        return Err(Diag::new(
            "L0530",
            Span::default(),
            format!("dependency crate `{}` is edition {}, but lust source crates must be edition 2024", dep.package_name, dep.edition),
            "Set `edition = \"2024\"` in the dependency package manifest.",
        ));
    }
    let root_text = std::fs::read_to_string(&root).map_err(|e| {
        Diag::new(
            "L0503",
            Span::default(),
            format!("cannot read dependency crate `{}` root {}: {e}", dep.package_name, root.display()),
            "Check the file exists and is readable.",
        )
    })?;
    let crate_name = dep.lib_name.replace('-', "_");
    let stable = def::stable_crate_hash(&dep.package_id, "lib", &dep.lib_name, false);
    let magic = interner.intern(&crate_magic_name(stable));
    let root_module = tables.add_crate_root(interner.intern(&crate_name));
    tables.crate_magic.insert(magic, root_module);
    let mut env = input.env.with_features(&dep.features);
    if lust_owned {
        env.allow_lust_dev = true;
    }
    let idx = jobs.len();
    by_key.insert(key, idx);
    jobs.push(CrateJob {
        input: OneInput { root_path: root, root_text, env, crate_ids: input.crate_ids, crate_name },
        root_module,
        flat_prefix: format!("k{:016x}$", stable.0),
        magic,
        deps: Vec::new(),
        adapter,
    });
    let mut sub = Vec::new();
    for d in &dep.deps {
        sub.push(add_dep_job(d, input, tables, jobs, by_key, interner)?);
    }
    jobs[idx].deps = sub;
    Ok((dep.extern_name.clone(), Ok(idx)))
}

/// One discovered file of one crate during resolution.
struct FileDisc {
    path: PathBuf,
    text: String,
    file_id: FileId,
    /// The module this file's top-level items belong to.
    module: ModuleId,
    is_root: bool,
    /// The `mod` declaration that loaded this file (none at the root).
    parent: Option<ParentDecl>,
    lexed: Option<lexer::Lexed>,
    outline: scan::Outline,
}

/// The `mod` declaration that loaded a file: where it sits, which is
/// the point that fixes textual macro inheritance (ARCH 6.1).
#[derive(Clone)]
struct ParentDecl {
    disc: usize,
    container: Vec<Sym>,
    lo: u32,
    macro_use: bool,
}

/// The seen list of the discovered files so far, for error maps.
fn seen_of(discs: &[FileDisc]) -> Vec<(PathBuf, String, FileId)> {
    discs.iter().map(|d| (d.path.clone(), d.text.clone(), d.file_id)).collect()
}

/// Creates the modules and file edges of one outline's `mod`
/// declarations, returning the inline module map of this file. New
/// file discs are appended to `discs` and queued for outline
/// processing. A declaration whose module already exists is a no-op,
/// which is what lets the same code serve the first discovery pass
/// and the macro-generated edges of later expansion rounds.
#[allow(clippy::too_many_arguments)]
fn outline_mods(
    di: usize,
    outline: &scan::Outline,
    strings: &[String],
    discs: &mut Vec<FileDisc>,
    queue: &mut Vec<usize>,
    tables: &mut ResolvedTables,
    shared: &mut SharedFiles,
    job: &CrateJob,
    interner: &Interner,
    diags: &mut Vec<Diag>,
) -> FxMap<Vec<Sym>, ModuleId> {
    let (file_path, file_module, is_root) = (discs[di].path.clone(), discs[di].module, discs[di].is_root);
    let mut inline_modules: FxMap<Vec<Sym>, ModuleId> = FxMap::default();
    inline_modules.insert(Vec::new(), file_module);
    for decl in &outline.mods {
        let enabled = match cfg::outline_enabled(&job.input.env, &decl.cfg, strings, interner, decl.span) {
            Ok(e) => e,
            Err(d) => {
                diags.push(d);
                false
            }
        };
        if !enabled {
            continue;
        }
        let parent = inline_modules.get(&decl.container).copied().unwrap_or(file_module);
        let mut child_path = tables.modules[parent.0 as usize].path.clone();
        child_path.push(decl.name);
        let existing = tables.module_by_path_in(job.root_module, &child_path);
        let child = match existing {
            Some(c) => c,
            None => {
                let vis = match decl.vis {
                    scan::OutlineVis::Private => VisKind::Priv,
                    scan::OutlineVis::Pub => VisKind::Pub,
                    scan::OutlineVis::Restricted => VisKind::Crate,
                };
                tables.add_module(parent, decl.name, vis, decl.span)
            }
        };
        tables.modules[child.0 as usize].macro_use |= decl.macro_use;
        if decl.inline {
            let mut key = decl.container.clone();
            key.push(decl.name);
            inline_modules.insert(key, child);
        } else if existing.is_none() {
            let inline_names: Vec<String> = decl.container.iter().map(|s| interner.get(*s).to_string()).collect();
            match modules::module_file(&file_path, is_root, &inline_names, interner.get(decl.name), decl.path_attr.as_deref(), decl.span) {
                Ok(f) => {
                    let fcanon = modules::canonical_string(&f);
                    let ftext = match shared.text_by_path.get(&fcanon) {
                        Some(t) => t.clone(),
                        None => match std::fs::read_to_string(&f) {
                            Ok(t) => {
                                shared.text_by_path.insert(fcanon, t.clone());
                                t
                            }
                            Err(e) => {
                                diags.push(Diag::new(
                                    "L0503",
                                    decl.span,
                                    format!("cannot read module file {}: {e}", f.display()),
                                    "Check the file exists and is readable.",
                                ));
                                continue;
                            }
                        },
                    };
                    let file_id = shared.file_id(&f, child);
                    discs.push(FileDisc {
                        path: f,
                        text: ftext,
                        file_id,
                        module: child,
                        is_root: false,
                        parent: Some(ParentDecl {
                            disc: di,
                            container: decl.container.clone(),
                            lo: decl.span.lo,
                            macro_use: decl.macro_use,
                        }),
                        lexed: None,
                        outline: scan::Outline::default(),
                    });
                    queue.push(discs.len() - 1);
                }
                Err(d) => diags.push(d),
            }
        }
    }
    inline_modules
}

/// Binds one outline's textual macro names in the macro namespace:
/// in their defining module, and `#[macro_export]` ones also at the
/// crate root. Expansion itself runs in the expander; these bindings
/// serve import resolution and path queries.
fn bind_outline_macros(
    outline: &scan::Outline,
    disc_module: ModuleId,
    inline_modules: &FxMap<Vec<Sym>, ModuleId>,
    job: &CrateJob,
    tables: &mut ResolvedTables,
    interner: &Interner,
) {
    for m in &outline.macros {
        let module = inline_modules.get(&m.container_path).copied().unwrap_or(disc_module);
        let hash = macro_hash(&job.input, &job.flat_prefix, interner, module, tables, m.name);
        let def = DefId { krate: job.input.crate_ids.local, hash };
        if tables.def_info.contains_key(&def) {
            continue;
        }
        // An exported macro defined at the crate root has one binding
        // there, and it is public: inserting the private textual
        // binding first would keep it (same target reads as no change)
        // and hide the macro from other crates.
        if m.exported && module == job.root_module {
            tables.insert(
                module,
                Namespace::Macro,
                m.name,
                Bind { target: Target::Def(def), vis: VisKind::Pub, rank: 2, def_module: module },
            );
        } else {
            tables.insert(
                module,
                Namespace::Macro,
                m.name,
                Bind { target: Target::Def(def), vis: VisKind::Priv, rank: 2, def_module: module },
            );
            if m.exported {
                tables.insert(
                    job.root_module,
                    Namespace::Macro,
                    m.name,
                    Bind { target: Target::Def(def), vis: VisKind::Pub, rank: 2, def_module: job.root_module },
                );
            }
        }
        tables.def_info.insert(def, DefInfo { kind: ResKind::Macro, flat: m.name, module, vis: VisKind::Priv });
        if job.flat_prefix.is_empty() {
            tables.flat[ns_index(Namespace::Macro)].insert(m.name, def);
        }
    }
}

/// Lexes and outlines one discovered file (the original text), creates
/// its module edges, and binds its macro names.
#[allow(clippy::too_many_arguments)]
fn process_disc_orig(
    di: usize,
    discs: &mut Vec<FileDisc>,
    queue: &mut Vec<usize>,
    tables: &mut ResolvedTables,
    shared: &mut SharedFiles,
    cache: &mut ResolveCache,
    job: &CrateJob,
    interner: &Interner,
    diags: &mut Vec<Diag>,
    needs_std: &mut bool,
) {
    let (text, file_id, module) = (discs[di].text.clone(), discs[di].file_id, discs[di].module);
    *needs_std |= crate::ty::lang::needs_std_load(&text);
    // Raw tokens and outline from the per-file cache when the text
    // stands (keyed by canonical path plus module, as in discovery).
    let file_key = format!("{}#{}", cache.canon(&discs[di].path), module.0);
    let text_hash = hash_str(&text);
    let lexed = match cache.raw(&file_key, text_hash, file_id) {
        Some(l) => l,
        None => match lex_file(&text, file_id, interner) {
            Ok(l) => {
                cache.put_raw(&file_key, text_hash, file_id, &l);
                l
            }
            Err(d) => {
                diags.push(d);
                return;
            }
        },
    };
    let outline = match cache.outline(&file_key, text_hash, file_id) {
        Some(o) => o,
        None => {
            let o = scan::outline(&lexed, interner);
            cache.put_outline(&file_key, text_hash, file_id, &o);
            o
        }
    };
    let inline = outline_mods(di, &outline, &lexed.strings.clone(), discs, queue, tables, shared, job, interner, diags);
    bind_outline_macros(&outline, module, &inline, job, tables, interner);
    discs[di].outline = outline;
    discs[di].lexed = Some(lexed);
}

/// One macro definition in this crate, located in one file's token
/// stream (the original tokens, or the expanded tokens for a
/// macro-generated definition).
struct MacroSrc {
    name: Sym,
    exported: bool,
    /// Index into the environment's owned source list.
    owned: usize,
    /// The disc (file) the definition was found in.
    disc: usize,
    /// The definition's module path from this crate's root.
    module_path: Vec<Sym>,
    /// The inline container path inside that file.
    container: Vec<Sym>,
    /// Byte offset of `macro_rules` in its file (textual order point).
    lo: u32,
}

/// The token range of one `macro_rules!` definition in a flat token
/// list, from its outline token index: through its closing group and
/// an optional `;`.
fn macro_tok_range(toks: &[crate::lexer::Token], start: usize) -> (usize, usize) {
    use crate::lexer::Tok;
    let mut i = start + 3; // macro_rules ! name
    let open = toks.get(i).map(|t| t.tok);
    let close = match open {
        Some(Tok::LParen) => Tok::RParen,
        Some(Tok::LBracket) => Tok::RBracket,
        Some(Tok::LBrace) => Tok::RBrace,
        _ => return (start, (start + 3).min(toks.len())),
    };
    let mut depth = 0usize;
    while i < toks.len() {
        match toks[i].tok {
            t if Some(t) == open => depth += 1,
            t if t == close => {
                depth -= 1;
                if depth == 0 {
                    i += 1;
                    break;
                }
            }
            Tok::Eof => break,
            _ => {}
        }
        i += 1;
    }
    if toks.get(i).map(|t| t.tok) == Some(Tok::Semi) {
        i += 1;
    }
    (start, i)
}

/// One module-level `use` naming a single name, for the macro
/// path-binding fixpoint.
#[derive(Clone)]
struct UseSite {
    module: Vec<Sym>,
    pubish: bool,
    segs: Vec<Sym>,
    leading: bool,
    alias: Sym,
    /// True for `use a::b::*`: `segs` is the glob target's written
    /// path and `alias` is unused.
    glob: bool,
}

/// The symbol a path-segment token stands for in a `use` tree.
fn use_seg_sym(tok: crate::lexer::Tok, interner: &Interner) -> Option<Sym> {
    use crate::lexer::Tok;
    Some(match tok {
        Tok::Ident(s) => s,
        Tok::SelfLower => interner.intern("self"),
        Tok::Super => interner.intern("super"),
        Tok::Crate => interner.intern("crate"),
        Tok::SelfUpper => interner.intern("Self"),
        _ => return None,
    })
}

/// Splits a `use` group `{ a, b::{c, d} }` body into its comma parts
/// (commas inside subgroups are hidden inside `Delim` trees).
fn comma_chunks(trees: &[crate::lexer::TokenTree]) -> Vec<Vec<crate::lexer::TokenTree>> {
    use crate::lexer::{Tok, TokenTree};
    let mut out: Vec<Vec<TokenTree>> = vec![Vec::new()];
    for t in trees {
        if matches!(t, TokenTree::Token(tok) if tok.tok == Tok::Comma) {
            out.push(Vec::new());
        } else if let Some(last) = out.last_mut() {
            last.push(t.clone());
        }
    }
    out.into_iter().filter(|c| !c.is_empty()).collect()
}

/// Parses the body trees of one `use` item (without `use` and `;`)
/// into single-name and glob sites under `prefix`. The expander does
/// not track a glob macro import inside one file, but a public glob
/// re-export must still seed dependent crates and other files.
fn parse_use_trees(
    trees: &[crate::lexer::TokenTree],
    prefix: &[Sym],
    leading: bool,
    module: &[Sym],
    pubish: bool,
    interner: &Interner,
    out: &mut Vec<UseSite>,
) {
    use crate::lexer::{Delim, Tok, TokenTree};
    let tok = |i: usize| match trees.get(i) {
        Some(TokenTree::Token(t)) => Some(t.tok),
        _ => None,
    };
    let mut segs: Vec<Sym> = prefix.to_vec();
    let mut leading = leading;
    let mut i = 0;
    if tok(0) == Some(Tok::PathSep) {
        leading = true;
        i = 1;
    }
    let mut alias: Option<Sym> = None;
    let mut underscore = false;
    loop {
        let Some(sym) = tok(i).and_then(|t| use_seg_sym(t, interner)) else { return };
        segs.push(sym);
        i += 1;
        match tok(i) {
            Some(Tok::PathSep) => {
                i += 1;
                match trees.get(i) {
                    Some(TokenTree::Delim(Delim::Brace, inner, _)) => {
                        for chunk in comma_chunks(inner) {
                            parse_use_trees(&chunk, &segs, leading, module, pubish, interner, out);
                        }
                        return;
                    }
                    Some(TokenTree::Token(t)) if t.tok == Tok::Star => {
                        out.push(UseSite { module: module.to_vec(), pubish, segs, leading, alias: Sym(0), glob: true });
                        return;
                    }
                    _ => continue,
                }
            }
            Some(Tok::As) => {
                match tok(i + 1) {
                    Some(Tok::Ident(s)) => alias = Some(s),
                    Some(Tok::Underscore) => underscore = true,
                    _ => return,
                }
                break;
            }
            _ => break,
        }
    }
    if underscore || segs.is_empty() {
        return;
    }
    let self_sym = interner.intern("self");
    let alias = alias
        .unwrap_or_else(|| if segs.len() > 1 && *segs.last().unwrap() == self_sym { segs[segs.len() - 2] } else { *segs.last().unwrap() });
    out.push(UseSite { module: module.to_vec(), pubish, segs, leading, alias, glob: false });
}

/// Scans one file's item-level `use` items (top level and inline
/// module bodies) from its token trees.
fn scan_use_sites(trees: &[crate::lexer::TokenTree], module: &[Sym], interner: &Interner, out: &mut Vec<UseSite>) {
    use crate::lexer::{Delim, Tok, TokenTree};
    let tok = |trees: &[TokenTree], i: usize| match trees.get(i) {
        Some(TokenTree::Token(t)) => Some(t.tok),
        _ => None,
    };
    let mut i = 0;
    let mut pubish = false;
    while i < trees.len() {
        match tok(trees, i) {
            Some(Tok::Pub) => {
                pubish = true;
                i += 1;
                if matches!(trees.get(i), Some(TokenTree::Delim(Delim::Paren, _, _))) {
                    i += 1;
                }
            }
            Some(Tok::Use) => {
                let start = i + 1;
                let mut end = start;
                while end < trees.len() && tok(trees, end) != Some(Tok::Semi) {
                    end += 1;
                }
                parse_use_trees(&trees[start..end], &[], false, module, pubish, interner, out);
                i = end + 1;
                pubish = false;
            }
            Some(Tok::Mod) => {
                if let (Some(name), Some(TokenTree::Delim(Delim::Brace, inner, _))) =
                    (tok(trees, i + 1).and_then(|t| use_seg_sym(t, interner)), trees.get(i + 2))
                {
                    let inner = inner.clone();
                    let mut sub = module.to_vec();
                    sub.push(name);
                    scan_use_sites(&inner, &sub, interner, out);
                    i += 3;
                } else {
                    i += 1;
                }
                pubish = false;
            }
            Some(_) | None => {
                // At item level a brace group belongs to an item the
                // pattern above does not open (fn body, impl, const):
                // the trees are nested, so skipping one tree skips it.
                if !matches!(tok(trees, i), Some(Tok::Pound)) {
                    pubish = false;
                }
                i += 1;
            }
        }
    }
}

/// Rewrites `$crate` in the template groups of one macro definition
/// to the defining crate's magic segment (a plain identifier token,
/// which transcription copies verbatim). Matcher groups keep their
/// tokens: `$crate` is illegal there and `compile_macro` rejects it.
fn rewrite_dollar_crate(tokens: &[crate::lexer::Token], magic: Sym) -> Vec<crate::lexer::Token> {
    use crate::lexer::{Tok, Token, TokenTree};
    fn rewrite(trees: &[TokenTree], magic: Sym) -> Vec<TokenTree> {
        let mut out = Vec::new();
        let mut i = 0;
        while i < trees.len() {
            let is_crate = matches!(trees.get(i), Some(TokenTree::Token(t)) if t.tok == Tok::Dollar)
                && matches!(trees.get(i + 1), Some(TokenTree::Token(t)) if t.tok == Tok::Crate);
            if is_crate {
                let span = match trees[i] {
                    TokenTree::Token(t) => t.span,
                    _ => unreachable!(),
                };
                out.push(TokenTree::Token(Token { tok: Tok::Ident(magic), span }));
                i += 2;
                continue;
            }
            match &trees[i] {
                TokenTree::Delim(d, inner, span) => out.push(TokenTree::Delim(*d, rewrite(inner, magic), *span)),
                t => out.push(t.clone()),
            }
            i += 1;
        }
        out
    }
    let (trees, balanced) = crate::lexer::build_trees(tokens);
    if !balanced {
        return tokens.to_vec();
    }
    // Arms at the top level of a definition body; the seed slice is
    // `macro_rules ! name <group>`, so rewrite inside that group per
    // arm: matcher group, `=>`, template group.
    let mut top = trees;
    if let Some(TokenTree::Delim(d, body, span)) = top.get(3).cloned() {
        let mut arms = Vec::new();
        let mut j = 0;
        while j < body.len() {
            match (body.get(j), body.get(j + 2)) {
                (Some(matcher @ TokenTree::Delim(..)), Some(TokenTree::Delim(td, template, tspan))) => {
                    arms.push(matcher.clone());
                    if let Some(arrow) = body.get(j + 1) {
                        arms.push(arrow.clone());
                    }
                    arms.push(TokenTree::Delim(*td, rewrite(template, magic), *tspan));
                    j += 3;
                }
                _ => {
                    arms.push(body[j].clone());
                    j += 1;
                }
            }
        }
        top[3] = TokenTree::Delim(d, arms, span);
    }
    let mut out = Vec::new();
    crate::lexer::flatten_trees(&top, &mut out);
    out
}

/// Renames the macro in one definition token slice (`macro_rules !
/// name ...`) to a re-export binding's alias, when they differ. The
/// expander registers a seed under the name its tokens define, so an
/// aliased re-export must carry the alias in its tokens.
fn rename_macro_token(tokens: &mut [crate::lexer::Token], alias: Sym) {
    use crate::lexer::Tok;
    if let Some(t) = tokens.get_mut(2)
        && let Tok::Ident(name) = t.tok
        && name != alias
    {
        t.tok = Tok::Ident(alias);
    }
}

/// The macro environment of one expansion round: every macro
/// definition visible by path in this crate, as expander seeds. Seeds
/// come from this crate's `#[macro_export]` definitions (crate root),
/// direct dependencies' exported definitions (`dep::` paths), and
/// public-single-name re-exports settled by a fixpoint over the
/// crate's `use` items (`crate::m::name` paths). Textual visibility
/// is the splice step's job (below); seeds never enter textual scope.
struct MacroEnv {
    seeds: Vec<crate::expand::MacroSeed>,
    /// Every macro source of this crate, for the exports other crates
    /// receive.
    own: Vec<OwnedMacroSource>,
    own_exported: Vec<bool>,
    /// Sources visible at this crate's root by path, under binding
    /// names (own exports plus root re-exports).
    root_sources: Vec<OwnedMacroSource>,
    /// Every source by owned index (own sources, then dependency
    /// exports), for textual splice materialization.
    owned_all: Vec<OwnedMacroSource>,
    srcs: Vec<MacroSrc>,
    /// Dependency exported sources by extern name, as owned indices.
    dep_owned: FxMap<String, Vec<usize>>,
    /// Textual macro sources inherited by each disc, in textual order.
    inherited: Vec<Vec<usize>>,
    /// Per disc: (declaration byte offset, textual sources, is an
    /// `extern crate` item) for each `#[macro_use]` file module or
    /// `#[macro_use] extern crate` in the original file: the sources
    /// join textual scope right after that item.
    after_mods: Vec<Vec<(u32, Vec<usize>, bool)>>,
    /// Per disc: extra seeds for macros this file's glob imports
    /// bring into plain-name scope (`use crate::prelude::*;`).
    glob_seeds: Vec<Vec<crate::expand::MacroSeed>>,
}

impl MacroEnv {
    /// Builds the environment from the files discovered so far (the
    /// original outlines, plus macro definitions the previous
    /// expansion round generated).
    fn build(
        job: &CrateJob,
        discs: &[FileDisc],
        expanded: &[Option<lexer::Lexed>],
        dep_exports: &[(String, Vec<OwnedMacroSource>)],
        tables: &ResolvedTables,
        interner: &Interner,
    ) -> MacroEnv {
        // All sources: this crate's definitions first, then the
        // exported definitions of direct source dependencies.
        let mut owned: Vec<OwnedMacroSource> = Vec::new();
        let mut srcs: Vec<MacroSrc> = Vec::new();
        // (module path, name) -> owned index, for textual definitions
        // a same-module re-export names.
        let mut module_defs: FxMap<(Vec<Sym>, Sym), usize> = FxMap::default();
        // One source per definition occurrence, by (disc, byte
        // offset): the same definition seen through the original and
        // the expanded outline is one source, but two definitions of
        // one name in one module are two (the later shadows).
        let mut seen_defs: FxMap<(usize, u32), ()> = FxMap::default();
        let mut own_exported: Vec<bool> = Vec::new();
        let macro_rules = interner.intern("macro_rules");
        for (di, disc) in discs.iter().enumerate() {
            let base_path = tables.modules[disc.module.0 as usize].path.clone();
            let mut collect = |outline: &scan::Outline, lexed: &lexer::Lexed, owned: &mut Vec<OwnedMacroSource>| {
                for m in &outline.macros {
                    let mut mod_path = base_path.clone();
                    mod_path.extend(m.container_path.iter().copied());
                    if seen_defs.insert((di, m.span.lo), ()).is_some() {
                        continue;
                    }
                    let key = (mod_path, m.name);
                    let (lo, hi) = macro_tok_range(&lexed.tokens, m.container.1);
                    module_defs.insert(key.clone(), owned.len());
                    srcs.push(MacroSrc {
                        name: m.name,
                        exported: m.exported,
                        owned: owned.len(),
                        disc: di,
                        module_path: key.0.clone(),
                        container: m.container_path.clone(),
                        lo: m.span.lo,
                    });
                    own_exported.push(m.exported);
                    owned.push(OwnedMacroSource {
                        name: m.name,
                        tokens: lexed.tokens[lo..hi].to_vec(),
                        strings: lexed.strings.clone(),
                        magic: job.magic,
                    });
                }
            };
            if let Some(orig) = &disc.lexed {
                collect(&disc.outline, orig, &mut owned);
            }
            if let Some(Some(exp)) = expanded.get(di)
                && exp.tokens.iter().any(|t| t.tok == crate::lexer::Tok::Ident(macro_rules))
            {
                // Only `outline.macros` feeds this collect, and a
                // macro definition needs a `macro_rules`
                // identifier token; most expanded files have none.
                let o = scan::outline(exp, interner);
                collect(&o, exp, &mut owned);
            }
        }
        let own = owned.clone();
        // Path bindings: (module path, name) -> owned index.
        let mut bindings: FxMap<(Vec<Sym>, Sym), usize> = FxMap::default();
        for s in &srcs {
            if s.exported {
                bindings.insert((Vec::new(), s.name), s.owned);
            }
        }
        let mut dep_owned: FxMap<String, Vec<usize>> = FxMap::default();
        for (extern_name, sources) in dep_exports {
            let sym = interner.intern(extern_name);
            let mut idxs = Vec::new();
            for src in sources {
                bindings.insert((vec![sym], src.name), owned.len());
                idxs.push(owned.len());
                owned.push(src.clone());
            }
            dep_owned.insert(extern_name.clone(), idxs);
        }
        // The re-export fixpoint over this crate's use items.
        // Use sites only feed that fixpoint and the glob seeds:
        // with no macro source in this crate or its dependencies
        // the bindings stay empty whatever the use items say, and
        // a stream with no `use` token has no sites. Either way
        // the token trees (the expensive part) are not built.
        let no_sources = srcs.is_empty() && dep_exports.iter().all(|(_, s)| s.is_empty());
        let mut sites: Vec<UseSite> = Vec::new();
        let mut sites_by_disc: Vec<Vec<UseSite>> = Vec::with_capacity(discs.len());
        for (di, disc) in discs.iter().enumerate() {
            let mut mine: Vec<UseSite> = Vec::new();
            if !no_sources {
                let base = tables.modules[disc.module.0 as usize].path.clone();
                if let Some(orig) = &disc.lexed
                    && orig.tokens.iter().any(|t| t.tok == crate::lexer::Tok::Use)
                {
                    let (trees, _) = crate::lexer::build_trees(&orig.tokens);
                    scan_use_sites(&trees, &base, interner, &mut mine);
                }
                if let Some(Some(exp)) = expanded.get(di)
                    && exp.tokens.iter().any(|t| t.tok == crate::lexer::Tok::Use)
                {
                    let (trees, _) = crate::lexer::build_trees(&exp.tokens);
                    scan_use_sites(&trees, &base, interner, &mut mine);
                }
            }
            sites.extend(mine.iter().cloned());
            sites_by_disc.push(mine);
        }
        let crate_sym = interner.intern("crate");
        let self_sym = interner.intern("self");
        let super_sym = interner.intern("super");
        let resolve_use = |segs: &[Sym], leading: bool, from: &[Sym], bindings: &FxMap<(Vec<Sym>, Sym), usize>| -> Option<usize> {
            let last = *segs.last()?;
            let middle = &segs[..segs.len() - 1];
            let by = |m: &[Sym]| bindings.get(&(m.to_vec(), last)).copied();
            let md = |m: &[Sym]| module_defs.get(&(m.to_vec(), last)).copied();
            if segs.len() == 1 && !leading {
                return md(from).or_else(|| by(from));
            }
            if segs[0] == crate_sym {
                let m = &middle[1.min(middle.len())..];
                return by(m);
            }
            if segs[0] == self_sym {
                let mut m = from.to_vec();
                m.extend_from_slice(&middle[1.min(middle.len())..]);
                return by(&m).or_else(|| md(&m));
            }
            if segs[0] == super_sym {
                let supers = segs.iter().take_while(|&&s| s == super_sym).count();
                let keep = from.len().saturating_sub(supers);
                let mut m: Vec<Sym> = from[..keep].to_vec();
                m.extend_from_slice(&middle[supers.min(middle.len())..]);
                return by(&m);
            }
            if leading {
                return by(middle);
            }
            let mut m = from.to_vec();
            m.extend_from_slice(middle);
            by(&m).or_else(|| by(middle)).or_else(|| md(&m))
        };
        // The bindings-space module path a glob target names.
        let resolve_glob_module = |segs: &[Sym], leading: bool, from: &[Sym], bindings: &FxMap<(Vec<Sym>, Sym), usize>| -> Vec<Sym> {
            if segs.first() == Some(&crate_sym) {
                return segs[1..].to_vec();
            }
            if segs.first() == Some(&self_sym) {
                let mut m = from.to_vec();
                m.extend_from_slice(&segs[1..]);
                return m;
            }
            if segs.first() == Some(&super_sym) {
                let supers = segs.iter().take_while(|&&s| s == super_sym).count();
                let keep = from.len().saturating_sub(supers);
                let mut m: Vec<Sym> = from[..keep].to_vec();
                m.extend_from_slice(&segs[supers..]);
                return m;
            }
            if leading {
                return segs.to_vec();
            }
            let has = |m: &[Sym]| bindings.keys().any(|(bm, _)| bm == m);
            if has(segs) {
                return segs.to_vec();
            }
            let mut m = from.to_vec();
            m.extend_from_slice(segs);
            if has(&m) {
                return m;
            }
            segs.to_vec()
        };
        loop {
            let mut changed = false;
            for site in &sites {
                if !site.pubish {
                    continue;
                }
                if site.glob {
                    let target = resolve_glob_module(&site.segs, site.leading, &site.module, &bindings);
                    let names: Vec<(Sym, usize)> =
                        bindings.iter().filter(|((m, _), _)| *m == target).map(|((_, n), src)| (*n, *src)).collect();
                    for (name, src) in names {
                        let key = (site.module.clone(), name);
                        if bindings.get(&key) != Some(&src) {
                            bindings.insert(key, src);
                            changed = true;
                        }
                    }
                    continue;
                }
                if let Some(src) = resolve_use(&site.segs, site.leading, &site.module, &bindings) {
                    let key = (site.module.clone(), site.alias);
                    if bindings.get(&key) != Some(&src) {
                        bindings.insert(key, src);
                        changed = true;
                    }
                }
            }
            if !changed {
                break;
            }
        }
        let mut seeds = Vec::with_capacity(bindings.len());
        let mut keys: Vec<&(Vec<Sym>, Sym)> = bindings.keys().collect();
        keys.sort_by(|a, b| {
            let pa: Vec<&str> = a.0.iter().map(|s| interner.get(*s)).collect();
            let pb: Vec<&str> = b.0.iter().map(|s| interner.get(*s)).collect();
            pa.cmp(&pb).then_with(|| interner.get(a.1).cmp(interner.get(b.1)))
        });
        for key in keys {
            let src = &owned[bindings[key]];
            let mut tokens = if src.magic != job.magic { rewrite_dollar_crate(&src.tokens, src.magic) } else { src.tokens.clone() };
            rename_macro_token(&mut tokens, key.1);
            seeds.push(crate::expand::MacroSeed { path: key.0.clone(), tokens, strings: src.strings.clone(), import_into: None });
        }
        // Macros visible at this crate's root by path (its own
        // `#[macro_export]` definitions plus root re-exports), under
        // their binding names: what dependent crates receive.
        let mut root_sources: Vec<OwnedMacroSource> = Vec::new();
        let mut root_keys: Vec<&(Vec<Sym>, Sym)> = bindings.keys().filter(|(m, _)| m.is_empty()).collect();
        root_keys.sort_by(|a, b| interner.get(a.1).cmp(interner.get(b.1)));
        for key in root_keys {
            let src = owned[bindings[key]].clone();
            root_sources.push(OwnedMacroSource { name: key.1, ..src });
        }
        // Glob imports in each file bring the target module's
        // path-visible macros into plain-name scope in the importing
        // module (the expander's prescan does not track globs, so the
        // worklist seeds them per file).
        let mut glob_seeds: Vec<Vec<crate::expand::MacroSeed>> = Vec::with_capacity(discs.len());
        for mine in &sites_by_disc {
            let mut extra: Vec<crate::expand::MacroSeed> = Vec::new();
            for site in mine {
                if !site.glob {
                    continue;
                }
                let target = resolve_glob_module(&site.segs, site.leading, &site.module, &bindings);
                let mut names: Vec<(Sym, usize)> =
                    bindings.iter().filter(|((m, _), _)| *m == target).map(|((_, n), src)| (*n, *src)).collect();
                names.sort_by(|a, b| interner.get(a.0).cmp(interner.get(b.0)));
                for (name, src_idx) in names {
                    let src = &owned[src_idx];
                    let mut tokens = if src.magic != job.magic { rewrite_dollar_crate(&src.tokens, src.magic) } else { src.tokens.clone() };
                    rename_macro_token(&mut tokens, name);
                    extra.push(crate::expand::MacroSeed {
                        path: target.clone(),
                        tokens,
                        strings: src.strings.clone(),
                        import_into: Some(site.module.clone()),
                    });
                }
            }
            glob_seeds.push(extra);
        }
        let (inherited, after_mods) = textual_env(job, discs, expanded, &srcs, &dep_owned, tables, interner);
        MacroEnv { seeds, own, own_exported, root_sources, owned_all: owned, srcs, dep_owned, inherited, after_mods, glob_seeds }
    }

    /// The macro sources dependent crates see at this crate's root:
    /// its `#[macro_export]` definitions plus any macro re-exported
    /// at the root by a public `use` (glob or single-name).
    fn exported_sources(&self) -> Vec<OwnedMacroSource> {
        if !self.root_sources.is_empty() {
            return self.root_sources.clone();
        }
        self.own.iter().zip(&self.own_exported).filter(|(_, e)| **e).map(|(s, _)| s.clone()).collect()
    }

    /// Splices the textual macro definitions visible in one file into
    /// its original token stream: inherited definitions just after
    /// any inner attributes (they are visible to the whole file), and
    /// each `#[macro_use]` file module's definitions right after its
    /// `mod` item (visible from that point on, as in Rust). The
    /// expander registers them in textual order and strips them from
    /// its output, so the parsed items are unaffected. Source
    /// strings are remapped into this file's string table.
    fn splice(&self, di: usize, lexed: lexer::Lexed, job: &CrateJob) -> lexer::Lexed {
        use crate::lexer::{Tok, Token};
        let start_srcs: &[usize] = self.inherited.get(di).map(Vec::as_slice).unwrap_or(&[]);
        let after: &[(u32, Vec<usize>, bool)] = self.after_mods.get(di).map(Vec::as_slice).unwrap_or(&[]);
        if start_srcs.is_empty() && after.is_empty() {
            return lexed;
        }
        let mut strings = lexed.strings.clone();
        let mut offsets: FxMap<usize, u32> = FxMap::default();
        let materialize = |idx: usize, strings: &mut Vec<String>, offsets: &mut FxMap<usize, u32>| -> Vec<Token> {
            let src = &self.owned_all[idx];
            let base = if src.magic != job.magic { rewrite_dollar_crate(&src.tokens, src.magic) } else { src.tokens.clone() };
            let offset = *offsets.entry(idx).or_insert_with(|| {
                let at = strings.len() as u32;
                strings.extend(src.strings.iter().cloned());
                at
            });
            base.iter()
                .map(|t| {
                    let mut tok = t.tok;
                    tok.shift_strings(offset);
                    Token { tok, span: t.span }
                })
                .collect()
        };
        // Insertion positions in the original token list.
        let toks = &lexed.tokens;
        let mut start_pos = 0usize;
        while toks.get(start_pos).map(|t| t.tok) == Some(Tok::Pound) && toks.get(start_pos + 1).map(|t| t.tok) == Some(Tok::Bang) {
            // One inner attribute `#![...]`: skip to its closing bracket.
            let mut depth = 0usize;
            let mut i = start_pos + 2;
            while i < toks.len() {
                match toks[i].tok {
                    Tok::LBracket => depth += 1,
                    Tok::RBracket => {
                        depth -= 1;
                        if depth == 0 {
                            i += 1;
                            break;
                        }
                    }
                    Tok::Eof => break,
                    _ => {}
                }
                i += 1;
            }
            start_pos = i;
        }
        let mut inserts: Vec<(usize, Vec<Token>)> = Vec::new();
        if !start_srcs.is_empty() {
            let mut all = Vec::new();
            for &idx in start_srcs {
                all.extend(materialize(idx, &mut strings, &mut offsets));
            }
            inserts.push((start_pos, all));
        }
        for (lo, srcs, is_extern) in after {
            let want = if *is_extern { Tok::Extern } else { Tok::Mod };
            let Some(mod_at) = toks.iter().position(|t| t.tok == want && t.span.lo == *lo) else { continue };
            let Some(semi) = toks[mod_at..].iter().position(|t| t.tok == Tok::Semi) else { continue };
            let mut all = Vec::new();
            for &idx in srcs {
                all.extend(materialize(idx, &mut strings, &mut offsets));
            }
            inserts.push((mod_at + semi + 1, all));
        }
        inserts.sort_by_key(|(pos, _)| *pos);
        let mut out: Vec<Token> = Vec::with_capacity(toks.len());
        let mut cur = 0usize;
        for (pos, add) in inserts {
            out.extend_from_slice(&toks[cur..pos.min(toks.len())]);
            cur = pos.min(toks.len());
            out.extend(add);
        }
        out.extend_from_slice(&toks[cur..]);
        lexer::Lexed { tokens: out, strings }
    }
}

/// Resolves one crate of a workspace session into the shared tables:
/// discovery, the expansion rounds of section 6.1 (cfg names, seeded
/// macro expansion, macro-generated module edges), the import
/// worklist, the path rewrite, and flattening.
fn resolve_one(
    job: &CrateJob,
    tables: &mut ResolvedTables,
    shared: &mut SharedFiles,
    cache: &mut ResolveCache,
    dep_exports: &[(String, Vec<OwnedMacroSource>)],
    interner: &Interner,
    known: &Known,
) -> Result<CrateOut, OneError> {
    let input = &job.input;
    let mut timings: Vec<(&'static str, f64)> = Vec::new();
    let mut last = std::time::Instant::now();
    macro_rules! lap {
        ($n:expr) => {{
            let now = std::time::Instant::now();
            timings.push(($n, (now - last).as_secs_f64() * 1e3));
            last = now;
        }};
    }
    let mut needs_std = false;
    let mut diags: Vec<Diag> = Vec::new();
    let root_file_id = shared.file_id(&input.root_path, job.root_module);
    let mut discs: Vec<FileDisc> = vec![FileDisc {
        path: input.root_path.clone(),
        text: input.root_text.clone(),
        file_id: root_file_id,
        module: job.root_module,
        is_root: true,
        parent: None,
        lexed: None,
        outline: scan::Outline::default(),
    }];
    let mut queue: Vec<usize> = vec![0];
    while let Some(di) = queue.pop() {
        process_disc_orig(di, &mut discs, &mut queue, tables, shared, cache, job, interner, &mut diags, &mut needs_std);
    }
    if !diags.is_empty() {
        return Err(OneError { diags, seen: seen_of(&discs), needs_std });
    }
    lap!("resolve: discovery");
    // Unknown cfg names (L0520) are checked on the original tokens of
    // every file before expansion can strip the item that carries one.
    for disc in &discs {
        if let Some(orig) = &disc.lexed
            && let Err(d) = check_cfg_names(orig, &input.env, interner)
        {
            return Err(OneError { diags: vec![d], seen: seen_of(&discs), needs_std });
        }
    }
    // Expansion rounds (6.1): expand every file with the macro
    // environment the outlines now prove, then look for module edges
    // the expansions generated; repeat until a round adds no file.
    let mut expanded: Vec<Option<lexer::Lexed>> = Vec::new();
    // Outside inputs the latest round's expansion of each file read.
    let mut file_deps: Vec<Vec<crate::expand::Dep>> = Vec::new();
    let mut menv = MacroEnv {
        seeds: Vec::new(),
        own: Vec::new(),
        own_exported: Vec::new(),
        root_sources: Vec::new(),
        owned_all: Vec::new(),
        srcs: Vec::new(),
        dep_owned: FxMap::default(),
        inherited: Vec::new(),
        after_mods: Vec::new(),
        glob_seeds: Vec::new(),
    };
    for round in 0..8 {
        expanded.resize_with(discs.len(), || None);
        menv = MacroEnv::build(job, &discs, &expanded, dep_exports, tables, interner);
        // Expansion is per file once the macro environment is built,
        // so it runs in parallel across files (as in the perf
        // landing); the first error in disc order is the answer.
        let module_paths: Vec<Vec<Sym>> = discs.iter().map(|d| tables.modules[d.module.0 as usize].path.clone()).collect();
        let indices: Vec<usize> = (0..discs.len()).collect();
        let results = par_map(&indices, |&di| -> Result<(Option<lexer::Lexed>, Vec<crate::expand::Dep>), Diag> {
            let (orig, text, path) = match &discs[di].lexed {
                Some(l) => (l.clone(), discs[di].text.clone(), discs[di].path.clone()),
                None => return Ok((None, Vec::new())),
            };
            let ects = crate::expand::ExpandCtx {
                interner,
                known,
                file_path: path.to_string_lossy().to_string(),
                src: &text,
                cfg: expand_cfg(&input.env),
                module_path: module_paths[di].clone(),
            };
            let spliced = menv.splice(di, orig, job);
            let seeds: Vec<crate::expand::MacroSeed> = match menv.glob_seeds.get(di) {
                Some(extra) if !extra.is_empty() => menv.seeds.iter().cloned().chain(extra.iter().cloned()).collect(),
                _ => menv.seeds.clone(),
            };
            crate::expand::expand_lexed_seeded_with_deps(spliced, &ects, &seeds).map(|(l, deps)| (Some(l), deps))
        });
        file_deps.resize_with(discs.len(), Vec::new);
        for (di, r) in results.into_iter().enumerate() {
            match r {
                Ok((l, deps)) => {
                    expanded[di] = l;
                    file_deps[di] = deps;
                }
                Err(d) => return Err(OneError { diags: vec![d], seen: seen_of(&discs), needs_std }),
            }
        }
        // Macro-generated module edges and macro definitions.
        // Only the outline's mods and macros are read here; a
        // stream with no `mod` token and no `macro_rules`
        // identifier has neither, so the outline is the default.
        let before = discs.len();
        let mut new_queue: Vec<usize> = Vec::new();
        let macro_rules = interner.intern("macro_rules");
        for di in 0..before {
            let Some(exp) = expanded[di].as_ref() else { continue };
            let outline = if exp.tokens.iter().any(|t| t.tok == crate::lexer::Tok::Mod || t.tok == crate::lexer::Tok::Ident(macro_rules)) {
                scan::outline(exp, interner)
            } else {
                scan::Outline::default()
            };
            let disc_module = discs[di].module;
            let inline = outline_mods(di, &outline, &exp.strings, &mut discs, &mut new_queue, tables, shared, job, interner, &mut diags);
            bind_outline_macros(&outline, disc_module, &inline, job, tables, interner);
        }
        while let Some(di) = new_queue.pop() {
            process_disc_orig(di, &mut discs, &mut new_queue, tables, shared, cache, job, interner, &mut diags, &mut needs_std);
        }
        if !diags.is_empty() {
            return Err(OneError { diags, seen: seen_of(&discs), needs_std });
        }
        // Files the expansions generated need their cfg names checked
        // and their own expansion in the next round.
        for disc in &discs[before..] {
            if let Some(orig) = &disc.lexed
                && let Err(d) = check_cfg_names(orig, &input.env, interner)
            {
                return Err(OneError { diags: vec![d], seen: seen_of(&discs), needs_std });
            }
        }
        if discs.len() == before {
            break;
        }
        if round == 7 {
            return Err(OneError {
                diags: vec![Diag::new(
                    "L0801",
                    Span::default(),
                    "macro-generated module discovery did not settle after 8 rounds".to_string(),
                    "This is a lust bug; report it.",
                )],
                seen: seen_of(&discs),
                needs_std,
            });
        }
    }
    let seen = seen_of(&discs);
    let (map, _all) = make_map(&seen);
    // Parse the expanded files in parallel, in FileId order. A
    // file whose expanded stream hashes to a cached parse clones
    // that Ast instead of parsing again; the hash runs in parallel
    // first because the cache itself is serial. A one-shot cache
    // holds no parse, so it needs no hashes (0 keys nothing).
    let mut order: Vec<usize> = (0..discs.len()).collect();
    order.sort_by_key(|&di| discs[di].file_id.0);
    let keep = !cache.one_shot;
    let exp_hashes = if keep {
        par_map(&order, |&di| match (expanded[di].as_ref(), discs[di].lexed.as_ref()) {
            (Some(l), _) | (None, Some(l)) => hash_lexed(l),
            (None, None) => hash_lexed(&lexer::Lexed { tokens: Vec::new(), strings: Vec::new() }),
        })
    } else {
        vec![0; order.len()]
    };
    // The stream each file parses from. Nothing reads the streams after
    // this phase, so a parse task moves its own out instead of copying it.
    let streams: Vec<std::sync::Mutex<Option<lexer::Lexed>>> =
        expanded.into_iter().zip(discs.iter_mut()).map(|(e, d)| std::sync::Mutex::new(e.or_else(|| d.lexed.take()))).collect();
    // Each file's works: one, or one per item segment (see below).
    let mut works: Vec<Vec<FileWork>> = Vec::with_capacity(order.len());
    let mut todo: Vec<usize> = Vec::new();
    for (pos, &di) in order.iter().enumerate() {
        let disc = &discs[di];
        let key = format!("{}#{}", cache.canon(&disc.path), disc.module.0);
        let text_hash = hash_str(&disc.text);
        let outside = reads_outside(&disc.text);
        let hit = if outside { None } else { cache.parsed(&key, text_hash, disc.file_id, exp_hashes[pos]) };
        match hit {
            Some(ast) => works.push(vec![FileWork {
                path: disc.path.clone(),
                text: disc.text.clone(),
                file_id: disc.file_id,
                ast,
                module: disc.module,
                segment: 0,
                key,
                text_hash,
                outside,
                exp_hash: exp_hashes[pos],
            }]),
            None => {
                works.push(Vec::new());
                todo.push(pos);
            }
        }
    }
    let parsed = par_map(&todo, |&pos| -> Result<(Vec<FileWork>, Option<Ast>), Diag> {
        let di = order[pos];
        let disc = &discs[di];
        let lexed = streams[di].lock().unwrap().take().unwrap_or(lexer::Lexed { tokens: Vec::new(), strings: Vec::new() });
        // A one-shot resolve parses a big file in item segments in
        // parallel, and each segment is its own work through strip,
        // register, rewrite, and flatten. The per-file caches of a
        // daemon session key whole files, so it parses whole files. On
        // any segment error the file parses again in one piece: a cut
        // can move where an error in bad text shows (an item cut before
        // its missing `;` ends at the cut), and the answer must be the
        // one-piece answer.
        let segments = if keep { vec![0..lexed.tokens.len()] } else { item_segments(&lexed.tokens, interner) };
        let asts: Vec<Ast> = if segments.len() == 1 {
            vec![parser::parse(&lexed, interner, known)?]
        } else {
            // Later segments start under the file's inner allows, as
            // the one-piece parse scopes them.
            let seed = parser::leading_allows(&lexed, interner, known);
            match par_map(&segments, |r| {
                if r.start == 0 {
                    parser::parse_items(&lexed, r.clone(), interner, known)
                } else {
                    parser::parse_items_seeded(&lexed, r.clone(), interner, known, &seed)
                }
            })
            .into_iter()
            .collect()
            {
                Ok(asts) => asts,
                Err(_) => vec![parser::parse(&lexed, interner, known)?],
            }
        };
        let outside = reads_outside(&disc.text);
        let store = if outside || !keep { None } else { Some(asts[0].clone()) };
        let key = format!("{}#{}", modules::canonical_string(&disc.path), disc.module.0);
        let text_hash = hash_str(&disc.text);
        let works = asts
            .into_iter()
            .enumerate()
            .map(|(k, ast)| FileWork {
                path: disc.path.clone(),
                text: if k == 0 { disc.text.clone() } else { String::new() },
                file_id: disc.file_id,
                ast,
                module: disc.module,
                segment: k,
                key: key.clone(),
                text_hash,
                outside,
                exp_hash: 0,
            })
            .collect();
        Ok((works, store))
    });
    for (&pos, r) in todo.iter().zip(parsed) {
        match r {
            Ok((mut ws, store)) => {
                if let Some(ast) = store {
                    cache.put_parsed(&ws[0].key, ws[0].text_hash, ws[0].file_id, exp_hashes[pos], ast);
                }
                for w in &mut ws {
                    w.exp_hash = exp_hashes[pos];
                }
                works[pos] = ws;
            }
            Err(d) => return Err(OneError { diags: vec![d], seen, needs_std }),
        }
    }
    let mut works: Vec<FileWork> = works.into_iter().flatten().collect();
    lap!("resolve: expand+parse");
    // The module of every item list, by (works index, inline path).
    let mut list_module: FxMap<ItemListKey, ModuleId> = FxMap::default();
    for (fi, w) in works.iter().enumerate() {
        list_module.insert((fi, Vec::new()), w.module);
    }
    for (fi, w) in works.iter().enumerate() {
        collect_inline_modules(&w.ast.items, fi, &[], tables, &mut list_module);
    }
    // Strip, register, and run the import worklist.
    let mut inner_diags: Vec<Diag> = Vec::new();
    let mut imports: Vec<Import> = Vec::new();
    // Adt disambiguator counts over every Adt the shared tables
    // already hold (earlier crates of this workspace included),
    // counted in one pass here instead of per Adt in register.
    let mut adt_counts: FxMap<Sym, u32> = FxMap::default();
    for info in tables.def_info.values() {
        if info.kind == ResKind::Adt {
            *adt_counts.entry(info.flat).or_insert(0) += 1;
        }
    }
    // Counts store "seen so far"; the register entry call turns the
    // first sighting into disambiguator 0, so seed with count-1 by
    // storing the next disambiguator minus one... see the entry use:
    // entry().and_modify(+1).or_insert(0) yields the stored value,
    // so a name seen k times must start at k-1 (absent when k == 0).
    adt_counts.retain(|_, c| {
        *c -= 1;
        true
    });
    // The names a file's top-level item list defines. The item segments
    // of a big file are one item list, so the set spans them: a duplicate
    // in two segments is a duplicate (see `item_segments`).
    let mut file_names: FxMap<(u8, Sym), ()> = FxMap::default();
    for (fi, w) in works.iter_mut().enumerate() {
        if w.segment == 0 {
            file_names.clear();
        }
        strip_file(w, fi, input, interner, &list_module, tables, &mut inner_diags);
        register_items(
            &mut w.ast.items,
            w.module,
            fi,
            &[],
            input,
            &job.flat_prefix,
            interner,
            tables,
            &list_module,
            &mut imports,
            &mut adt_counts,
            &mut file_names,
            &mut inner_diags,
        );
    }
    match run_imports(tables, &imports, interner) {
        Ok(ds) => inner_diags.extend(ds),
        Err(e) => inner_diags.push(Diag::new("L0506", Span::default(), e, "This is a lust bug; report it.")),
    }
    // A glob of a std module binds nothing; keep its path so the
    // rewrite pass can tell a non-prelude std type it imports (W-STD-A).
    tables.std_globs.clear();
    for imp in &imports {
        if let crate::resolve::imports::ImportKind::Glob { path } = &imp.kind
            && path.first().is_some_and(|s| matches!(interner.get(*s), "std" | "core" | "alloc"))
        {
            tables.std_globs.push((imp.module, path.clone()));
        }
    }
    if !inner_diags.is_empty() {
        return Err(OneError { diags: inner_diags, seen, needs_std });
    }
    for w in works.iter() {
        collect_assoc_vis(&w.ast, &w.ast.items, w.module, interner, tables);
        check_vis_restrictions(&w.ast.items, w.module, interner, tables, &mut inner_diags);
    }
    if !inner_diags.is_empty() {
        return Err(OneError { diags: inner_diags, seen, needs_std });
    }
    lap!("resolve: strip+register");
    // The tables are frozen now. Every file whose cached final
    // chunk was stored under this exact epoch (and expanded
    // stream) rewrites to that chunk, so its rewrite walk is
    // skipped and the chunk is taken over at flatten time.
    let epoch = tables.rewrite_epoch();
    let mut final_hits: Vec<Option<FinalChunk>> = Vec::with_capacity(works.len());
    for w in works.iter() {
        let hit = match cache.final_epoch(&w.key, w.text_hash, w.file_id) {
            Some(e) if e == epoch => cache.final_chunk(&w.key, w.text_hash, w.file_id).filter(|c| c.exp_hash == w.exp_hash),
            _ => None,
        };
        final_hits.push(hit);
    }
    lap!("resolve: epoch");
    // Rewrite paths to flat names, checking visibility. The tables
    // are frozen at this point and each work's Ast is its own (a file,
    // or an item segment of one), so the pass runs in parallel on the
    // compiler's pool; diagnostics merge back in work order. Each work
    // sits behind its own lock, taken once, so one task can own it
    // mutably. A work whose final chunk is cached is skipped.
    let rw_diags: Vec<Diag> = {
        let tables: &ResolvedTables = tables;
        let local_names = tables.local_named_set();
        let cells: Vec<(usize, std::sync::Mutex<&mut FileWork>)> = works
            .iter_mut()
            .enumerate()
            .filter(|(fi, _)| final_hits[*fi].is_none())
            .map(|(fi, w)| (fi, std::sync::Mutex::new(w)))
            .collect();
        let per_work = par_map(&cells, |(fi, cell)| {
            let mut w = cell.lock().unwrap();
            let module = w.module;
            let mut rw = Rewrite { tables, interner, list_module: &list_module, local_names: &local_names, diags: Vec::new(), gen_params: Vec::new() };
            rw.file_items(&mut w.ast, *fi, module, &[]);
            rw.diags
        });
        per_work.into_iter().flatten().collect()
    };
    if !rw_diags.is_empty() {
        return Err(OneError { diags: rw_diags, seen, needs_std });
    }
    lap!("resolve: rewrite");
    // ---- Flatten: inline module bodies splice into top-level items;
    // mod, use, and extern crate items drop. Each fn's module is
    // recorded here from its origin (file plus inline module path):
    // keying it by flat name loses impl methods, whose names are not
    // module-mangled and repeat across modules, and the checker then
    // ran method bodies in the root module (wrong bindings and field
    // visibility). Per-fn lines and body hashes ride the same pass, in
    // the flattened order collect uses.
    // One pending chunk per file: a cache hit contributes its
    // stored chunk whole; a miss is flattened here and stored at
    // the end under the current epoch.
    struct Pending {
        key: String,
        text_hash: u64,
        exp_hash: u64,
        file_id: FileId,
        cacheable: bool,
        ast: Ast,
        fn_lines: Vec<u32>,
        body_hashes: Vec<u64>,
        nested_lines: Vec<u32>,
        nested_hashes: Vec<u64>,
        fn_module_paths: Vec<Vec<Sym>>,
        nested_module_paths: Vec<Vec<Sym>>,
        /// The file's structure hash, on its first work; None on the
        /// later segments of a file.
        structure: Option<u64>,
        scan: Option<crate::driver::ast_hash::AstScans>,
    }
    // Module/import structure per file, hashed before flattening drops
    // it: the file path, then its `mod`, `use`, and `extern crate`
    // items over all its segments in order, so a file parsed in
    // segments hashes exactly as one piece.
    let structures: Vec<Option<u64>> = (0..works.len())
        .map(|k| {
            (works[k].segment == 0 && final_hits[k].is_none()).then(|| {
                use std::hash::{Hash, Hasher};
                let mut h = crate::intern::FxHasher::default();
                works[k].path.to_string_lossy().hash(&mut h);
                for w in std::iter::once(&works[k]).chain(works[k + 1..].iter().take_while(|w| w.segment > 0)) {
                    structure_items(&w.ast.items, &mut h);
                }
                h.finish()
            })
        })
        .collect();
    let mut pendings: Vec<Pending> = Vec::with_capacity(works.len());
    for ((fi, mut w), hit) in works.into_iter().enumerate().zip(final_hits) {
        if let Some(c) = hit {
            pendings.push(Pending {
                key: w.key,
                text_hash: w.text_hash,
                exp_hash: w.exp_hash,
                file_id: w.file_id,
                cacheable: false,
                ast: c.ast,
                fn_lines: c.fn_lines,
                body_hashes: c.body_hashes,
                nested_lines: c.nested_lines,
                nested_hashes: c.nested_hashes,
                fn_module_paths: c.fn_module_paths,
                nested_module_paths: c.nested_module_paths,
                structure: Some(c.structure),
                scan: Some(crate::driver::ast_hash::AstScans {
                    items: c.scan_items,
                    bodies: c.scan_bodies.into_iter().chain(c.nested_bodies).collect(),
                }),
            });
            continue;
        }
        let structure = structures[fi];
        let mut flat_items = Vec::new();
        let mut flat_mods: Vec<ModuleId> = Vec::new();
        flatten_items_mods(std::mem::take(&mut w.ast.items), w.module, fi, &[], &list_module, &mut flat_items, &mut flat_mods);
        let (mut p_lines, mut p_hashes, mut p_paths) = (Vec::new(), Vec::new(), Vec::new());
        for (item, module) in flat_items.iter().zip(flat_mods.iter()) {
            let mut push = |def: &FnDef| {
                p_lines.push(map.line_col(def.name_span).0);
                let text = map.text(def.name_span.file).unwrap_or("");
                let body_span = def.body.map(|b| w.ast.block(b).span).unwrap_or(def.name_span);
                let slice = text.get(body_span.lo as usize..body_span.hi as usize).unwrap_or("");
                p_hashes.push(hash_str(slice));
                p_paths.push(tables.modules[module.0 as usize].path.clone());
            };
            match &item.kind {
                ItemKind::Fn(d) => push(d),
                ItemKind::Impl(imp) => {
                    for d in &imp.fns {
                        push(d);
                    }
                }
                _ => {}
            }
        }
        // Nested fns (W-CORELANG body items) ride after the file's
        // top-level fns, in stmt item order, matching collect.
        let (mut n_lines, mut n_hashes, mut n_paths) = (Vec::new(), Vec::new(), Vec::new());
        for item in &w.ast.stmt_items {
            if let crate::ast::ItemKind::Fn(d) = &item.kind {
                n_lines.push(map.line_col(d.name_span).0);
                let text = map.text(d.name_span.file).unwrap_or("");
                let body_span = d.body.map(|b| w.ast.block(b).span).unwrap_or(d.name_span);
                let slice = text.get(body_span.lo as usize..body_span.hi as usize).unwrap_or("");
                n_hashes.push(hash_str(slice));
                n_paths.push(tables.modules[w.module.0 as usize].path.clone());
            }
        }
        w.ast.items = flat_items;
        pendings.push(Pending {
            cacheable: !w.outside && keep,
            key: w.key,
            text_hash: w.text_hash,
            exp_hash: w.exp_hash,
            file_id: w.file_id,
            ast: w.ast,
            fn_lines: p_lines,
            body_hashes: p_hashes,
            nested_lines: n_lines,
            nested_hashes: n_hashes,
            fn_module_paths: p_paths,
            nested_module_paths: n_paths,
            structure,
            scan: None,
        });
    }
    lap!("resolve: flatten");
    // Structural scans for the chunks that missed, in parallel
    // across files.
    let fresh_scans = par_map(&pendings, |pd| pd.scan.is_none().then(|| crate::driver::ast_hash::scan_ast_seq(&pd.ast)));
    for (pd, fresh) in pendings.iter_mut().zip(fresh_scans) {
        if pd.scan.is_none() {
            pd.scan = fresh;
        }
    }
    // Store the fresh chunks under this epoch for the next request.
    // A chunk scan lists nested bodies after its own top-level
    // bodies; split at the top-level count for storage.
    // (Segments exist only in one-shot resolves, which store nothing: a
    // stored chunk is always a whole file with its own structure hash.)
    for pd in pendings.iter().filter(|pd| pd.cacheable) {
        let Some(structure) = pd.structure else { continue };
        let scan = pd.scan.as_ref().expect("every pending chunk is scanned");
        let top = pd.fn_lines.len().min(scan.bodies.len());
        cache.put_final(
            &pd.key,
            pd.text_hash,
            pd.file_id,
            FinalChunk {
                epoch,
                exp_hash: pd.exp_hash,
                ast: pd.ast.clone(),
                fn_lines: pd.fn_lines.clone(),
                body_hashes: pd.body_hashes.clone(),
                nested_lines: pd.nested_lines.clone(),
                nested_hashes: pd.nested_hashes.clone(),
                fn_module_paths: pd.fn_module_paths.clone(),
                nested_module_paths: pd.nested_module_paths.clone(),
                structure,
                scan_items: scan.items.clone(),
                scan_bodies: scan.bodies[..top].to_vec(),
                nested_bodies: scan.bodies[top..].to_vec(),
            },
        );
    }
    // Assemble the crate outputs in file order. Module paths are
    // per-crate (every crate root has the empty path), so the map
    // holds only this job's crate: in a workspace session the other
    // crates' roots would collide on the same paths and every fn
    // would take the wrong crate's module.
    let module_by_path: FxMap<Vec<Sym>, ModuleId> = tables
        .modules
        .iter()
        .enumerate()
        .filter(|(_, m)| m.krate_root == job.root_module)
        .map(|(i, m)| (m.path.clone(), ModuleId(i as u32)))
        .collect();
    let mut chunks = Vec::with_capacity(pendings.len());
    let mut fn_lines = Vec::new();
    let mut body_hashes = Vec::new();
    let mut nested_lines: Vec<u32> = Vec::new();
    let mut nested_hashes: Vec<u64> = Vec::new();
    let mut nested_modules: Vec<ModuleId> = Vec::new();
    let mut fn_module = Vec::new();
    let mut scan_items = Vec::new();
    let mut scan_bodies = Vec::new();
    let mut nested_bodies = Vec::new();
    let mut structure = crate::intern::FxHasher::default();
    for pd in pendings {
        {
            use std::hash::Hash;
            if let Some(s) = pd.structure {
                s.hash(&mut structure);
            }
        }
        let top = pd.fn_lines.len();
        fn_lines.extend(pd.fn_lines);
        body_hashes.extend(pd.body_hashes);
        nested_lines.extend(pd.nested_lines);
        nested_hashes.extend(pd.nested_hashes);
        nested_modules.extend(pd.nested_module_paths.iter().map(|p| module_by_path.get(p).copied().unwrap_or(ROOT_MODULE)));
        fn_module.extend(pd.fn_module_paths.iter().map(|p| module_by_path.get(p).copied().unwrap_or(ROOT_MODULE)));
        let mut scan = pd.scan.expect("every pending chunk is scanned");
        scan_items.extend(scan.items);
        nested_bodies.extend(scan.bodies.drain(top.min(scan.bodies.len())..));
        scan_bodies.extend(scan.bodies);
        chunks.push(pd.ast);
    }
    let ast = Ast::concat(chunks);
    let structure_hash = {
        use std::hash::Hasher;
        structure.finish()
    };
    let scans = crate::driver::ast_hash::AstScans { items: scan_items, bodies: scan_bodies };
    lap!("resolve: chunk scan+concat");
    Ok(CrateOut {
        ast,
        fn_lines,
        body_hashes,
        fn_module,
        nested_lines,
        nested_hashes,
        nested_modules,
        structure_hash,
        seen,
        needs_std,
        exported_macros: menv.exported_sources(),
        expand_deps: file_deps.into_iter().flatten().collect(),
        timings,
        scans,
        nested_bodies,
    })
}

/// Hashes one item list's module and import structure for
/// `ResolvedCrate::structure_hash`: `mod` edges (recursing into inline
/// bodies), `use` trees, and `extern crate` items, in written order.
/// Item visibility rides in through a coarse tag, because flipping a
/// `use` or `mod` to `pub` changes re-export bindings.
fn structure_items(items: &[Item], h: &mut crate::intern::FxHasher) {
    use std::hash::Hash;
    fn tree(t: &UseTree, h: &mut crate::intern::FxHasher) {
        use std::hash::Hash;
        t.leading_colon.hash(h);
        (t.prefix.len() as u64).hash(h);
        for s in &t.prefix {
            s.name.hash(h);
        }
        match &t.kind {
            UseKind::Simple { rename } => {
                0u8.hash(h);
                rename.hash(h);
            }
            UseKind::Glob => 1u8.hash(h),
            UseKind::Group(children) => {
                2u8.hash(h);
                (children.len() as u64).hash(h);
                for c in children {
                    tree(c, h);
                }
            }
        }
    }
    for item in items {
        // Only structure items hash, visibility included (flipping a
        // `use` or `mod` to `pub` changes re-export bindings). Other
        // items hash nothing: adding a fn must not look like a
        // structure edit to the driver's mode split. Their effects
        // are in the driver's own Ast item hashes.
        let vis = |h: &mut crate::intern::FxHasher| match &item.vis {
            Vis::Private => 0u8.hash(h),
            Vis::Public => 1u8.hash(h),
            Vis::Restricted { path, .. } => {
                2u8.hash(h);
                for s in path {
                    s.name.hash(h);
                }
            }
        };
        match &item.kind {
            ItemKind::Mod(m) => {
                vis(h);
                0u8.hash(h);
                m.name.hash(h);
                match &m.body {
                    Some(body) => structure_items(body, h),
                    None => 0u8.hash(h),
                }
            }
            ItemKind::Use(u) => {
                vis(h);
                1u8.hash(h);
                tree(&u.tree, h);
            }
            ItemKind::ExternCrate(e) => {
                vis(h);
                2u8.hash(h);
                e.name.hash(h);
                e.rename.hash(h);
            }
            _ => {}
        }
    }
}

/// True when module path `a` is a prefix of `b` (an ancestor inline
/// module of it, or the same module).
fn path_prefix_of(a: &[Sym], b: &[Sym]) -> bool {
    a.len() <= b.len() && a == &b[..a.len()]
}

/// The `#[macro_use] extern crate name;` items at the top level of
/// one file, as (byte offset, extern name). Top level only, like the
/// expander's own prescan reach for extern crates.
fn extern_macro_use_events(lexed: &lexer::Lexed, interner: &Interner) -> Vec<(u32, String)> {
    use crate::lexer::Tok;
    let toks = &lexed.tokens;
    let mut out = Vec::new();
    let mut pending = false;
    let mut depth = 0usize;
    let mut i = 0;
    while i < toks.len() {
        match toks[i].tok {
            Tok::LBrace => depth += 1,
            Tok::RBrace => depth = depth.saturating_sub(1),
            Tok::Semi if depth == 0 => pending = false,
            Tok::Pound if depth == 0 => {
                let mut j = i + 1;
                if toks.get(j).map(|t| t.tok) == Some(Tok::Bang) {
                    j += 1;
                }
                if toks.get(j).map(|t| t.tok) == Some(Tok::LBracket) {
                    if let Some(Tok::Ident(s)) = toks.get(j + 1).map(|t| t.tok)
                        && interner.get(s) == "macro_use"
                    {
                        pending = true;
                    }
                    // Skip the attribute body.
                    let mut d = 0usize;
                    while j < toks.len() {
                        match toks[j].tok {
                            Tok::LBracket => d += 1,
                            Tok::RBracket => {
                                d -= 1;
                                if d == 0 {
                                    break;
                                }
                            }
                            Tok::Eof => break,
                            _ => {}
                        }
                        j += 1;
                    }
                    i = j;
                }
            }
            Tok::Extern if depth == 0 => {
                if pending
                    && toks.get(i + 1).map(|t| t.tok) == Some(Tok::Crate)
                    && let Some(Tok::Ident(name)) = toks.get(i + 2).map(|t| t.tok)
                {
                    out.push((toks[i].span.lo, interner.get(name).to_string()));
                }
                pending = false;
            }
            _ => {}
        }
        i += 1;
    }
    out
}

/// The textual macro environment of one crate (ARCH 6.1): for each
/// disc, the macro sources its whole file inherits, and the sources
/// each `#[macro_use]` file module adds after its declaration. A
/// macro is textually visible in a module after its definition point,
/// in child modules declared after it, and in the parent (from the
/// declaration point on) when the child module carries
/// `#[macro_use]`. Dependency macros enter only through
/// `#[macro_use] extern crate dep;`, which brings the dependency's
/// exported macros into textual scope at that point.
#[allow(clippy::too_many_arguments)]
fn textual_env(
    job: &CrateJob,
    discs: &[FileDisc],
    expanded: &[Option<lexer::Lexed>],
    srcs: &[MacroSrc],
    dep_owned: &FxMap<String, Vec<usize>>,
    tables: &ResolvedTables,
    interner: &Interner,
) -> (Vec<Vec<usize>>, Vec<Vec<(u32, Vec<usize>, bool)>>) {
    // With no textual macro source anywhere, every file inherits
    // nothing and no `#[macro_use]` join has sources to add: the
    // result is one empty list per disc.
    if srcs.is_empty() && dep_owned.values().all(|v| v.is_empty()) {
        return (vec![Vec::new(); discs.len()], vec![Vec::new(); discs.len()]);
    }
    struct Cx<'a> {
        job: &'a CrateJob,
        discs: &'a [FileDisc],
        decls: Vec<Vec<scan::ModDecl>>,
        extern_events: Vec<Vec<(u32, String)>>,
        srcs: &'a [MacroSrc],
        by_path: FxMap<Vec<Sym>, Vec<usize>>,
        exports_memo: FxMap<ModuleId, Vec<usize>>,
        inherited_memo: Vec<Option<Vec<usize>>>,
        dep_owned: &'a FxMap<String, Vec<usize>>,
        tables: &'a ResolvedTables,
    }
    impl Cx<'_> {
        /// The textual macros a `#[macro_use]` on module `m` exports:
        /// its own definitions plus, recursively, those of its
        /// `#[macro_use]` child modules.
        fn exports_of(&mut self, m: ModuleId) -> Vec<usize> {
            if let Some(v) = self.exports_memo.get(&m) {
                return v.clone();
            }
            let path = self.tables.modules[m.0 as usize].path.clone();
            let mut out: Vec<usize> = self.by_path.get(&path).cloned().unwrap_or_default();
            let children: Vec<ModuleId> = self
                .tables
                .modules
                .iter()
                .enumerate()
                .filter(|(_, info)| info.parent == Some(m) && info.macro_use)
                .map(|(i, _)| ModuleId(i as u32))
                .collect();
            for c in children {
                for idx in self.exports_of(c) {
                    if !out.contains(&idx) {
                        out.push(idx);
                    }
                }
            }
            self.exports_memo.insert(m, out.clone());
            out
        }

        /// The child module one `mod` declaration in disc `di` names.
        fn child_module(&self, di: usize, decl: &scan::ModDecl) -> Option<ModuleId> {
            let mut path = self.tables.modules[self.discs[di].module.0 as usize].path.clone();
            path.extend(decl.container.iter().copied());
            path.push(decl.name);
            self.tables.module_by_path_in(self.job.root_module, &path)
        }

        /// Textual macros visible at one point (container, byte
        /// offset) in one file, in textual order.
        fn textual_at(&mut self, di: usize, container: &[Sym], lo: u32) -> Vec<usize> {
            let mut out = self.inherited(di);
            let mut events: Vec<(u32, Vec<usize>)> = Vec::new();
            for s in self.srcs {
                if s.disc == di && s.lo < lo && path_prefix_of(&s.container, container) {
                    events.push((s.lo, vec![s.owned]));
                }
            }
            let decls = self.decls[di].clone();
            for decl in &decls {
                if decl.macro_use && decl.span.lo < lo && path_prefix_of(&decl.container, container) {
                    if let Some(child) = self.child_module(di, decl) {
                        events.push((decl.span.lo, self.exports_of(child)));
                    }
                }
            }
            for (elo, name) in self.extern_events[di].clone() {
                if elo < lo
                    && let Some(idxs) = self.dep_owned.get(&name)
                {
                    events.push((elo, idxs.clone()));
                }
            }
            events.sort_by_key(|(l, _)| *l);
            for (_, idxs) in events {
                for idx in idxs {
                    if !out.contains(&idx) {
                        out.push(idx);
                    }
                }
            }
            out
        }

        /// The textual macros a whole file inherits from its parent
        /// module chain at its `mod` declaration point.
        fn inherited(&mut self, di: usize) -> Vec<usize> {
            if let Some(v) = &self.inherited_memo[di] {
                return v.clone();
            }
            // Guard against a parent cycle (cannot occur in a module
            // tree, but a memo placeholder keeps the recursion total).
            self.inherited_memo[di] = Some(Vec::new());
            let out = match self.discs[di].parent.clone() {
                None => Vec::new(),
                Some(p) => self.textual_at(p.disc, &p.container, p.lo),
            };
            self.inherited_memo[di] = Some(out.clone());
            out
        }
    }
    let mut by_path: FxMap<Vec<Sym>, Vec<(u32, usize)>> = FxMap::default();
    for s in srcs {
        by_path.entry(s.module_path.clone()).or_default().push((s.lo, s.owned));
    }
    let by_path: FxMap<Vec<Sym>, Vec<usize>> = by_path
        .into_iter()
        .map(|(k, mut v)| {
            v.sort_by_key(|(lo, _)| *lo);
            (k, v.into_iter().map(|(_, o)| o).collect())
        })
        .collect();
    let mut decls: Vec<Vec<scan::ModDecl>> = Vec::with_capacity(discs.len());
    let mut extern_events: Vec<Vec<(u32, String)>> = Vec::with_capacity(discs.len());
    for (di, disc) in discs.iter().enumerate() {
        let mut ds = disc.outline.mods.clone();
        if let Some(Some(exp)) = expanded.get(di)
            && exp.tokens.iter().any(|t| t.tok == crate::lexer::Tok::Mod)
        {
            // Only the outline's mods are read here (see the same
            // gate in the expansion round loop).
            ds.extend(scan::outline(exp, interner).mods);
        }
        decls.push(ds);
        extern_events.push(match &disc.lexed {
            Some(l) => extern_macro_use_events(l, interner),
            None => Vec::new(),
        });
    }
    let mut cx = Cx {
        job,
        discs,
        decls,
        extern_events,
        srcs,
        by_path,
        exports_memo: FxMap::default(),
        inherited_memo: vec![None; discs.len()],
        dep_owned,
        tables,
    };
    let mut inherited = Vec::with_capacity(discs.len());
    for di in 0..discs.len() {
        inherited.push(cx.inherited(di));
    }
    // `#[macro_use]` file modules in the original outline: their
    // exported textual macros join the parent file after the `mod`.
    // A macro-generated `#[macro_use] mod` is not in the original
    // token stream, so it cannot be spliced; uses of its macros in
    // the same file then fail closed with an unknown-macro error.
    let mut after_mods: Vec<Vec<(u32, Vec<usize>, bool)>> = vec![Vec::new(); discs.len()];
    for (di, disc) in discs.iter().enumerate() {
        for decl in &disc.outline.mods {
            if decl.macro_use && !decl.inline {
                if let Some(child) = cx.child_module(di, decl) {
                    let idxs = cx.exports_of(child);
                    if !idxs.is_empty() {
                        after_mods[di].push((decl.span.lo, idxs, false));
                    }
                }
            }
        }
        for (elo, name) in &cx.extern_events[di] {
            if let Some(idxs) = cx.dep_owned.get(name)
                && !idxs.is_empty()
            {
                after_mods[di].push((*elo, idxs.clone(), true));
            }
        }
    }
    (inherited, after_mods)
}

/// Adds one extern crate to one crate's prelude tables, if that crate
/// has no entry with this name yet.
fn push_extern(
    tables: &mut ResolvedTables,
    local: crate::def::CrateId,
    owner: ModuleId,
    name: &str,
    is_std_lib: bool,
    root_module: Option<ModuleId>,
    unsupported: Option<String>,
) {
    if tables.extern_by_name(owner, name).is_some() {
        return;
    }
    let hash = def::item_hash(crate::def::StableCrateHash(hash_str(name) | 1), &[], def::DefKind::Module, name, 0);
    tables.externs.push(ExternInfo {
        name: name.to_string(),
        def: DefId { krate: local, hash },
        is_std_lib,
        owner,
        root_module,
        unsupported,
    });
}

/// A macro def's stable hash: the crate flat prefix, module path
/// segments, and the name. Nothing else computes macro hashes, and the
/// prefix keeps two crates' same-named macros apart in one session.
fn macro_hash(
    input: &OneInput,
    flat_prefix: &str,
    interner: &Interner,
    module: ModuleId,
    tables: &ResolvedTables,
    name: Sym,
) -> DefPathHash {
    let mut path: Vec<&str> = Vec::new();
    if !flat_prefix.is_empty() {
        path.push(flat_prefix);
    }
    path.extend(tables.modules[module.0 as usize].path.iter().map(|s| interner.get(*s)));
    def::item_hash(input.crate_ids.stable, &path, def::DefKind::Macro, interner.get(name), 0)
}

/// FxHash of a string, for body hashes and extern ids.
fn hash_str(s: &str) -> u64 {
    use std::hash::{Hash, Hasher};
    let mut h = crate::intern::FxHasher::default();
    s.hash(&mut h);
    h.finish() | 1
}

/// Records the module of each inline item list in one file's items.
fn collect_inline_modules(items: &[Item], fi: usize, prefix: &[Sym], tables: &ResolvedTables, out: &mut FxMap<ItemListKey, ModuleId>) {
    let parent_mod = out.get(&(fi, prefix.to_vec())).copied();
    let parent_path: Vec<Sym> = parent_mod.map(|m| tables.modules[m.0 as usize].path.clone()).unwrap_or_default();
    let root = parent_mod.map(|m| tables.root_of(m)).unwrap_or(ROOT_MODULE);
    for item in items {
        if let ItemKind::Mod(m) = &item.kind {
            let mut key = prefix.to_vec();
            key.push(m.name);
            let mut full = parent_path.clone();
            full.push(m.name);
            if let Some(id) = tables.module_by_path_in(root, &full) {
                out.insert((fi, key.clone()), id);
                if let Some(body) = &m.body {
                    collect_inline_modules(body, fi, &key, tables, out);
                }
            }
        }
    }
}

/// True when an attribute list names `name` as its one-segment path.
fn has_attr(attrs: &[Attr], name: &str, interner: &Interner) -> bool {
    attrs.iter().any(|a| a.path.len() == 1 && interner.get(a.path[0].name) == name)
}

/// The `#[path = "..."]` value in an attribute list, when written. The
/// parser stores the `= lit` tail as raw token trees, or as an `Eq`
/// expression for the parenthesized form; both reduce to the string.
fn path_attr_value(attrs: &[Attr], ast: &Ast, interner: &Interner) -> Option<String> {
    for a in attrs {
        if a.path.len() != 1 || interner.get(a.path[0].name) != "path" {
            continue;
        }
        match &a.input {
            AttrInput::Eq(e) => {
                if let Expr::Str(i) = ast.expr(*e) {
                    return ast.strings.get(*i as usize).cloned();
                }
            }
            AttrInput::List(_, trees) => {
                for t in trees {
                    if let crate::lexer::TokenTree::Token(tok) = t
                        && let crate::lexer::Tok::Str(i, _) = tok.tok
                    {
                        return ast.strings.get(i as usize).cloned();
                    }
                }
            }
            AttrInput::None => {}
        }
    }
    None
}

/// Step 1 of the loop for one file: expand `cfg_attr`, strip cfg'd-out
/// items, fields, variants, and methods, and apply module inner
/// attribute flags (`no_implicit_prelude`, a crate-level cfg). Match
/// arm cfg is handled in the rewrite walk, where arms are visited.
fn strip_file(
    w: &mut FileWork,
    fi: usize,
    input: &OneInput,
    interner: &Interner,
    list_module: &FxMap<ItemListKey, ModuleId>,
    tables: &mut ResolvedTables,
    diags: &mut Vec<Diag>,
) {
    let strings = w.ast.strings.clone();
    let mut inner: Vec<Attr> = w.ast.inner_attrs.clone();
    if let Err(d) = cfg::expand_cfg_attr(&input.env, &mut inner, &strings, interner) {
        diags.push(d);
    }
    let module = w.module;
    if has_attr(&inner, "no_implicit_prelude", interner) {
        tables.modules[module.0 as usize].no_prelude = true;
    }
    match cfg::attrs_enabled(&input.env, &inner, &strings, interner) {
        Ok(false) => {
            // A crate- or module-level cfg turned the whole file off.
            w.ast.items.clear();
            return;
        }
        Ok(true) => {}
        Err(d) => diags.push(d),
    }
    let mut items = std::mem::take(&mut w.ast.items);
    strip_items(&mut items, fi, &[], w, input, interner, list_module, tables, diags);
    w.ast.items = items;
}

/// The recursive half of `strip_file` over one item list.
fn strip_items(
    items: &mut Vec<Item>,
    fi: usize,
    prefix: &[Sym],
    w: &FileWork,
    input: &OneInput,
    interner: &Interner,
    list_module: &FxMap<ItemListKey, ModuleId>,
    tables: &mut ResolvedTables,
    diags: &mut Vec<Diag>,
) {
    let strings = &w.ast.strings;
    let mut keep = Vec::with_capacity(items.len());
    for mut item in items.drain(..) {
        if let Err(d) = cfg::expand_cfg_attr(&input.env, &mut item.attrs, strings, interner) {
            diags.push(d);
        }
        match cfg::attrs_enabled(&input.env, &item.attrs, strings, interner) {
            Ok(true) => {}
            Ok(false) => continue,
            Err(d) => {
                diags.push(d);
                continue;
            }
        }
        // A `cfg` in the inner attributes of an inline `mod`, `impl`, or
        // `trait` body turns the whole item off, like a file-level cfg.
        let item_inner: Option<&mut Vec<Attr>> = match &mut item.kind {
            ItemKind::Mod(m) => Some(&mut m.inner_attrs),
            ItemKind::Impl(i) => Some(&mut i.inner_attrs),
            ItemKind::Trait(t) => Some(&mut t.inner_attrs),
            _ => None,
        };
        if let Some(inner) = item_inner {
            if let Err(d) = cfg::expand_cfg_attr(&input.env, inner, strings, interner) {
                diags.push(d);
            }
            match cfg::attrs_enabled(&input.env, inner, strings, interner) {
                Ok(true) => {}
                Ok(false) => continue,
                Err(d) => {
                    diags.push(d);
                    continue;
                }
            }
        }
        match &mut item.kind {
            ItemKind::Struct(s) => {
                if let VariantFields::Struct(fs) | VariantFields::Tuple(fs) = &mut s.fields {
                    strip_fields(fs, input, strings, interner, diags);
                }
            }
            ItemKind::Enum(e) => {
                e.variants.retain_mut(|v| {
                    if let Err(d) = cfg::expand_cfg_attr(&input.env, &mut v.attrs, strings, interner) {
                        diags.push(d);
                    }
                    match cfg::attrs_enabled(&input.env, &v.attrs, strings, interner) {
                        Ok(on) => {
                            if on && let VariantFields::Struct(fs) | VariantFields::Tuple(fs) = &mut v.fields {
                                strip_fields(fs, input, strings, interner, diags);
                            }
                            on
                        }
                        Err(d) => {
                            diags.push(d);
                            false
                        }
                    }
                });
            }
            ItemKind::Impl(imp) => {
                imp.fns.retain_mut(|f| {
                    if let Err(d) = cfg::expand_cfg_attr(&input.env, &mut f.attrs, strings, interner) {
                        diags.push(d);
                    }
                    matches!(cfg::attrs_enabled(&input.env, &f.attrs, strings, interner), Ok(true))
                });
            }
            ItemKind::Mod(m) => {
                // The module's real visibility comes from the AST (the
                // outline could not read a restricted path).
                let mut key = prefix.to_vec();
                key.push(m.name);
                if let Some(&child) = list_module.get(&(fi, key.clone())) {
                    let vis = vis_from_ast(&item.vis, interner);
                    tables.modules[child.0 as usize].vis = vis;
                    if has_attr(&item.attrs, "no_implicit_prelude", interner) || has_attr(&m.inner_attrs, "no_implicit_prelude", interner) {
                        tables.modules[child.0 as usize].no_prelude = true;
                    }
                    if let Some(body) = &mut m.body {
                        strip_items(body, fi, &key, w, input, interner, list_module, tables, diags);
                    }
                } else if m.body.is_some() {
                    // A cfg-stripped inline module (its own cfg ran in
                    // discovery): drop the whole item.
                    continue;
                }
            }
            _ => {}
        }
        keep.push(item);
    }
    *items = keep;
}

/// Strips cfg'd-out fields from one field list.
fn strip_fields(fs: &mut Vec<FieldDef>, input: &OneInput, strings: &[String], interner: &Interner, diags: &mut Vec<Diag>) {
    fs.retain_mut(|f| {
        if let Err(d) = cfg::expand_cfg_attr(&input.env, &mut f.attrs, strings, interner) {
            diags.push(d);
        }
        match cfg::attrs_enabled(&input.env, &f.attrs, strings, interner) {
            Ok(on) => on,
            Err(d) => {
                diags.push(d);
                false
            }
        }
    });
}

/// The flat name of a def in a module: the crate's flat prefix (empty
/// for the selected crate, a stable-hash prefix for a source
/// dependency), then the module path joined with `$`, then the name.
/// The selected crate's root keeps plain names, as before.
fn flat_name(tables: &ResolvedTables, flat_prefix: &str, module: ModuleId, name: Sym, interner: &Interner) -> Sym {
    let path = &tables.modules[module.0 as usize].path;
    if flat_prefix.is_empty() && path.is_empty() {
        return name;
    }
    let mut s = String::from(flat_prefix);
    for seg in path {
        s.push_str(interner.get(*seg));
        s.push('$');
    }
    s.push_str(interner.get(name));
    interner.intern(&s)
}

/// Records the source path text of one renamed def in
/// `ResolvedTables::display_names`, for diagnostics: the module path
/// and name joined with `::`, prefixed with the crate name for a
/// source dependency (whose flat name carries only a crate hash).
/// Root defs of the selected crate keep their plain name and need no
/// entry. Display only; never a lookup key.
fn record_display(tables: &mut ResolvedTables, input: &OneInput, flat_prefix: &str, module: ModuleId, flat: Sym, name: Sym, interner: &Interner) {
    if flat == name {
        return;
    }
    let mut s = String::new();
    if !flat_prefix.is_empty() {
        s.push_str(&input.crate_name);
        s.push_str("::");
    }
    for seg in &tables.modules[module.0 as usize].path.clone() {
        s.push_str(interner.get(*seg));
        s.push_str("::");
    }
    s.push_str(interner.get(name));
    let display = interner.intern(&s);
    tables.display_names.insert(flat, display);
}

/// Step 3 input: registers every defined name in one item list, renames
/// defs to their flat names, and collects the module's imports. Module
/// bindings register first (same sweep): a `mod` item's name is a
/// type-namespace binding to the child module.
#[allow(clippy::too_many_arguments)]
fn register_items(
    items: &mut [Item],
    module: ModuleId,
    fi: usize,
    prefix: &[Sym],
    input: &OneInput,
    flat_prefix: &str,
    interner: &Interner,
    tables: &mut ResolvedTables,
    list_module: &FxMap<ItemListKey, ModuleId>,
    imports: &mut Vec<Import>,
    // Same-flat-name Adt counts so far, across the workspace tables
    // in registration order: the disambiguator source, without
    // rescanning every recorded def per Adt (quadratic at scale).
    adt_counts: &mut FxMap<Sym, u32>,
    // Names this item list defines, per namespace (empty at the start of
    // a list; a file's item segments share one). Two local definitions
    // of one name in one namespace are a duplicate (rustc E0428), even
    // when both hash to the same target (two fns) or to a module the
    // module tree already holds (two `mod` items): the binding insert
    // alone cannot see those. One report per duplicate item.
    seen: &mut FxMap<(u8, Sym), ()>,
    diags: &mut Vec<Diag>,
) {
    let check_dup = |seen: &mut FxMap<(u8, Sym), ()>, ns: Namespace, name: Sym, span: Span, reported: &mut bool, diags: &mut Vec<Diag>| {
        if seen.insert((ns_index(ns) as u8, name), ()).is_some() && !*reported {
            *reported = true;
            diags.push(Diag::new(
                "L0106",
                span,
                format!("`{}` is defined more than once", interner.get(name)),
                "Rename one of the definitions.",
            ));
        }
    };
    // Adt disambiguators count same-flat-name Adts in one pass order,
    // matching collect (which counts by name over the whole crate).
    for item in items.iter_mut() {
        let vis = || vis_from_ast(&item.vis, interner);
        let bind = |tables: &mut ResolvedTables, ns: Namespace, name: Sym, target: Target, vis: VisKind| {
            tables.insert(module, ns, name, Bind { target, vis, rank: 2, def_module: module });
        };
        let mut reported = false;
        match &mut item.kind {
            ItemKind::Mod(m) => {
                check_dup(seen, Namespace::Type, m.name, m.name_span, &mut reported, diags);
                let mut key = prefix.to_vec();
                key.push(m.name);
                if let Some(&child) = list_module.get(&(fi, key.clone())) {
                    tables.module_defs[child.0 as usize] = DefId {
                        krate: input.crate_ids.local,
                        hash: def::item_hash(
                            input.crate_ids.stable,
                            &[],
                            def::DefKind::Module,
                            interner.get(flat_name(tables, flat_prefix, module, m.name, interner)),
                            0,
                        ),
                    };
                    bind(tables, Namespace::Type, m.name, Target::Module(child), vis());
                    if let Some(body) = &mut m.body {
                        register_items(
                            body,
                            child,
                            fi,
                            &key,
                            input,
                            flat_prefix,
                            interner,
                            tables,
                            list_module,
                            imports,
                            adt_counts,
                            &mut FxMap::default(),
                            diags,
                        );
                    }
                }
            }
            ItemKind::Fn(f) => {
                check_dup(seen, Namespace::Value, f.name, f.name_span, &mut reported, diags);
                let flat = flat_name(tables, flat_prefix, module, f.name, interner);
                record_display(tables, input, flat_prefix, module, flat, f.name, interner);
                let def = DefId { krate: input.crate_ids.local, hash: def::free_fn_hash(input.crate_ids.stable, &[], interner.get(flat)) };
                bind(tables, Namespace::Value, f.name, Target::Def(def), vis());
                tables.def_info.insert(def, DefInfo { kind: ResKind::Fn, flat, module, vis: vis() });
                tables.flat[ns_index(Namespace::Value)].insert(flat, def);
                f.name = flat;
            }
            ItemKind::Struct(s) => {
                // A braced struct has no constructor value: its name lives
                // only in the type namespace. Unit and tuple structs also
                // name their constructor in the value namespace.
                let has_ctor = !matches!(s.fields, VariantFields::Struct(_));
                check_dup(seen, Namespace::Type, s.name, s.name_span, &mut reported, diags);
                if has_ctor {
                    check_dup(seen, Namespace::Value, s.name, s.name_span, &mut reported, diags);
                }
                let flat = flat_name(tables, flat_prefix, module, s.name, interner);
                record_display(tables, input, flat_prefix, module, flat, s.name, interner);
                let disamb = *adt_counts.entry(flat).and_modify(|c| *c += 1).or_insert(0);
                let def = DefId {
                    krate: input.crate_ids.local,
                    hash: def::item_hash(input.crate_ids.stable, &[], def::DefKind::Adt, interner.get(flat), disamb),
                };
                bind(tables, Namespace::Type, s.name, Target::Def(def), vis());
                if has_ctor {
                    bind(tables, Namespace::Value, s.name, Target::Def(def), vis());
                }
                record_adt(tables, def, flat, module, vis(), &s.fields, interner);
                s.name = flat;
            }
            ItemKind::Enum(e) => {
                check_dup(seen, Namespace::Type, e.name, e.name_span, &mut reported, diags);
                let flat = flat_name(tables, flat_prefix, module, e.name, interner);
                record_display(tables, input, flat_prefix, module, flat, e.name, interner);
                let disamb = *adt_counts.entry(flat).and_modify(|c| *c += 1).or_insert(0);
                let def = DefId {
                    krate: input.crate_ids.local,
                    hash: def::item_hash(input.crate_ids.stable, &[], def::DefKind::Adt, interner.get(flat), disamb),
                };
                bind(tables, Namespace::Type, e.name, Target::Def(def), vis());
                tables.def_info.insert(def, DefInfo { kind: ResKind::Adt, flat, module, vis: vis() });
                tables.variants.insert(def, e.variants.iter().map(|v| v.name).collect());
                tables.flat[ns_index(Namespace::Type)].insert(flat, def);
                // Enum variant fields have no visibility of their own
                // in Rust: they take the enum's visibility.
                for v in &e.variants {
                    if let VariantFields::Struct(fs) = &v.fields {
                        let entry = tables.field_vis.entry(def).or_insert_with(|| (module, FxMap::default()));
                        for f in fs {
                            entry.1.insert(f.name, vis());
                        }
                    }
                }
                e.name = flat;
            }
            ItemKind::Const(c) => {
                tables.const_init_module.insert(c.span, module);
                if let Some(name) = c.name {
                    check_dup(seen, Namespace::Value, name, c.name_span, &mut reported, diags);
                    let flat = flat_name(tables, flat_prefix, module, name, interner);
                    record_display(tables, input, flat_prefix, module, flat, name, interner);
                    let def = DefId {
                        krate: input.crate_ids.local,
                        hash: def::item_hash(input.crate_ids.stable, &[], def::DefKind::Const, interner.get(flat), 0),
                    };
                    bind(tables, Namespace::Value, name, Target::Def(def), vis());
                    tables.def_info.insert(def, DefInfo { kind: ResKind::Const, flat, module, vis: vis() });
                    tables.flat[ns_index(Namespace::Value)].insert(flat, def);
                    c.name = Some(flat);
                }
            }
            ItemKind::Static(s) => {
                tables.const_init_module.insert(s.span, module);
                check_dup(seen, Namespace::Value, s.name, s.name_span, &mut reported, diags);
                let flat = flat_name(tables, flat_prefix, module, s.name, interner);
                record_display(tables, input, flat_prefix, module, flat, s.name, interner);
                let def = DefId {
                    krate: input.crate_ids.local,
                    hash: def::item_hash(input.crate_ids.stable, &[], def::DefKind::Static, interner.get(flat), 0),
                };
                bind(tables, Namespace::Value, s.name, Target::Def(def), vis());
                tables.def_info.insert(def, DefInfo { kind: ResKind::Static, flat, module, vis: vis() });
                tables.flat[ns_index(Namespace::Value)].insert(flat, def);
                s.name = flat;
            }
            ItemKind::Type(a) => {
                check_dup(seen, Namespace::Type, a.name, a.name_span, &mut reported, diags);
                let flat = flat_name(tables, flat_prefix, module, a.name, interner);
                record_display(tables, input, flat_prefix, module, flat, a.name, interner);
                let def = DefId {
                    krate: input.crate_ids.local,
                    hash: def::item_hash(input.crate_ids.stable, &[], def::DefKind::TypeAlias, interner.get(flat), 0),
                };
                bind(tables, Namespace::Type, a.name, Target::Def(def), vis());
                tables.def_info.insert(def, DefInfo { kind: ResKind::Alias, flat, module, vis: vis() });
                tables.flat[ns_index(Namespace::Type)].insert(flat, def);
                a.name = flat;
            }
            ItemKind::Trait(t) => {
                for c in &t.consts {
                    tables.const_init_module.insert(c.span, module);
                }
                check_dup(seen, Namespace::Type, t.name, t.name_span, &mut reported, diags);
                let flat = flat_name(tables, flat_prefix, module, t.name, interner);
                record_display(tables, input, flat_prefix, module, flat, t.name, interner);
                // The ordinal counts same-flat-name traits in
                // walk order, matching collect's trait defs.
                let disamb = tables.def_info.values().filter(|i| i.kind == ResKind::Trait && i.flat == flat).count() as u32;
                let def = DefId {
                    krate: input.crate_ids.local,
                    hash: def::item_hash(input.crate_ids.stable, &[], def::DefKind::Trait, interner.get(flat), disamb),
                };
                bind(tables, Namespace::Type, t.name, Target::Def(def), vis());
                tables.def_info.insert(def, DefInfo { kind: ResKind::Trait, flat, module, vis: vis() });
                tables.flat[ns_index(Namespace::Type)].insert(flat, def);
                t.name = flat;
            }
            ItemKind::Impl(imp) => {
                // Associated fn visibility, once the self type resolves
                // in this module. The rewrite pass resolves the path
                // properly; here a one-segment or resolvable path is
                // enough to key the table. Associated consts record
                // their defining module for the const evaluator.
                for c in &imp.consts {
                    tables.const_init_module.insert(c.span, module);
                }
            }
            ItemKind::Use(u) => {
                flatten_use(&u.tree, module, vis(), imports, interner);
            }
            ItemKind::ExternCrate(e) => {
                let bind_name = e.rename.unwrap_or(e.name);
                if bind_name != interner.intern("_") {
                    check_dup(seen, Namespace::Type, bind_name, e.span, &mut reported, diags);
                    let target = if e.name == interner.intern("self") {
                        Some(Target::Module(tables.root_of(module)))
                    } else {
                        tables.extern_by_name(module, interner.get(e.name)).map(|i| tables.extern_target(i))
                    };
                    if let Some(target) = target {
                        bind(tables, Namespace::Type, bind_name, target, vis());
                    }
                }
            }
            ItemKind::Union(u) => {
                check_dup(seen, Namespace::Type, u.name, u.name_span, &mut reported, diags);
            }
            _ => {}
        }
    }
}

/// Records one struct's def info and field visibility.
fn record_adt(
    tables: &mut ResolvedTables,
    def: DefId,
    flat: Sym,
    module: ModuleId,
    vis: VisKind,
    fields: &VariantFields,
    interner: &Interner,
) {
    tables.def_info.insert(def, DefInfo { kind: ResKind::Adt, flat, module, vis });
    tables.flat[ns_index(Namespace::Type)].insert(flat, def);
    // Only a unit or tuple struct names a constructor value.
    if !matches!(fields, VariantFields::Struct(_)) {
        tables.flat[ns_index(Namespace::Value)].insert(flat, def);
    }
    if let VariantFields::Struct(fs) = fields {
        let mut map = FxMap::default();
        for f in fs {
            map.insert(f.name, vis_from_ast(&f.vis, interner));
        }
        tables.field_vis.insert(def, (module, map));
    }
    if let VariantFields::Tuple(fs) = fields {
        tables.tuple_field_vis.insert(def, (module, fs.iter().map(|f| vis_from_ast(&f.vis, interner)).collect()));
    }
}

/// Reports every written restricted visibility in `items` (at `module`)
/// that names no enclosing module (`ResolvedTables::restriction_ok`):
/// on items, struct fields, and inherent impl items, recursing into
/// inline modules as `collect_assoc_vis` does.
fn check_vis_restrictions(items: &[Item], module: ModuleId, interner: &Interner, tables: &ResolvedTables, diags: &mut Vec<Diag>) {
    let check = |v: &Vis, diags: &mut Vec<Diag>| {
        if let Vis::Restricted { span, .. } = v
            && !tables.restriction_ok(&vis_from_ast(v, interner), module, interner)
        {
            diags.push(Diag::new(
                "L0511",
                *span,
                "this visibility names no enclosing module",
                "Write `pub(crate)`, or `pub(in path)` with a path from `crate`, `self`, or `super` to an enclosing module.",
            ));
        }
    };
    for item in items {
        check(&item.vis, diags);
        match &item.kind {
            ItemKind::Struct(s) => {
                if let VariantFields::Tuple(fs) | VariantFields::Struct(fs) = &s.fields {
                    for f in fs {
                        check(&f.vis, diags);
                    }
                }
            }
            ItemKind::Impl(imp) if imp.trait_ref.is_none() => {
                for f in &imp.fns {
                    check(&f.vis, diags);
                }
                for c in &imp.consts {
                    check(&c.vis, diags);
                }
            }
            ItemKind::Mod(m) => {
                if let Some(body) = &m.body {
                    let mut full = tables.modules[module.0 as usize].path.clone();
                    full.push(m.name);
                    if let Some(child) = tables.module_by_path_in(tables.root_of(module), &full) {
                        check_vis_restrictions(body, child, interner, tables, diags);
                    }
                }
            }
            _ => {}
        }
    }
}

/// Fills `assoc_vis` from every impl block whose self type resolves.
fn collect_assoc_vis(ast: &Ast, items: &[Item], module: ModuleId, interner: &Interner, tables: &mut ResolvedTables) {
    for item in items {
        match &item.kind {
            ItemKind::Impl(imp) => {
                // Trait impl methods take the trait's visibility, not the
                // (absent) written one; only inherent impls record here.
                if imp.trait_ref.is_none()
                    && let TyExpr::Path(segs) = ast.ty(imp.self_ty)
                {
                    let names: Vec<Sym> = segs.iter().map(|s| s.name).collect();
                    if let PathRes::Done(Target::Def(def)) =
                        tables.resolve_path(module, &names, Namespace::Type, PathMode::Lexical, false, interner)
                    {
                        let entry = tables.assoc_vis.entry(def).or_default();
                        for f in &imp.fns {
                            entry.insert(f.name, (vis_from_ast(&f.vis, interner), module));
                        }
                        for c in &imp.consts {
                            entry.insert(c.name, (vis_from_ast(&c.vis, interner), module));
                        }
                    }
                }
            }
            ItemKind::Mod(m) => {
                if let Some(body) = &m.body {
                    // Inline bodies were registered under their module;
                    // the path lookup finds it by name path.
                    let mut full = tables.modules[module.0 as usize].path.clone();
                    full.push(m.name);
                    if let Some(child) = tables.module_by_path_in(tables.root_of(module), &full) {
                        collect_assoc_vis(ast, body, child, interner, tables);
                    }
                }
            }
            _ => {}
        }
    }
}

// ---------- The rewrite pass ----------
//
// Every written path resolves here, in its module (plus lexical scopes
// in bodies). A proven path becomes its flat name; an ambiguous or
// private one is a diagnostic (L0507, L0510); an unproven one is left
// written, so collect and check report it with their own codes. A path
// into a non-std extern crate is L0505: cross-crate item resolution is
// not supported yet, and a false accept would be worse.

/// One lexical frame in a body walk.
#[derive(Default)]
struct Frame {
    locals: Vec<Sym>,
    /// Function-local imports: (name, namespace index) to target.
    imports: FxMap<(Sym, usize), LocalBind>,
    /// Function-local `use std::... [as Name]` imports, in the
    /// shape of `ResolvedTables::std_aliases`.
    std_imports: FxMap<(Sym, usize), Vec<Sym>>,
    /// Names bound at explicit rank in this frame, by an explicit `use`
    /// or a nested item: a second explicit binding of one name in one
    /// namespace is a duplicate, where a glob binding is not.
    explicit: Vec<(Sym, usize)>,
}

#[derive(Clone, Copy)]
enum LocalBind {
    Target(Target),
    Ambiguous,
}

struct Rewrite<'a> {
    tables: &'a ResolvedTables,
    interner: &'a Interner,
    list_module: &'a FxMap<ItemListKey, ModuleId>,
    /// Every name some module defines locally, built once over the
    /// frozen tables (`ResolvedTables::local_named_set`).
    local_names: &'a FxMap<Sym, ()>,
    diags: Vec<Diag>,
    /// The type and const params (name, is const) of the item being
    /// rewritten, after its impl's or trait's for a method. As in rustc,
    /// a param shadows module items and imports for a path's first
    /// segment, so such paths stay as written; check resolves them
    /// against the item's generics.
    gen_params: Vec<(Sym, bool)>,
}

impl Rewrite<'_> {
    /// Rewrites one file's top-level items (recursing into inline mods).
    fn file_items(&mut self, ast: &mut Ast, fi: usize, module: ModuleId, prefix: &[Sym]) {
        let mut items = std::mem::take(&mut ast.items);
        self.items(ast, &mut items, fi, module, prefix);
        ast.items = items;
    }

    /// Rewrites the trait paths in one bound list.
    fn bounds(&mut self, ast: &mut Ast, bounds: &mut Vec<crate::ast::TraitBound>, span: Span, module: ModuleId) {
        for b in bounds.iter_mut() {
            if let crate::ast::TraitBound::Trait { trait_ref, .. } = b {
                self.rewrite_path(&mut trait_ref.path, Namespace::Type, span, module, &[], ast);
            }
        }
    }

    /// Pushes one item's type and const params for the paths inside it;
    /// returns the length to truncate back to when the item ends.
    fn push_params(&mut self, g: &crate::ast::Generics) -> usize {
        let mark = self.gen_params.len();
        for p in &g.params {
            match p {
                crate::ast::GenericParam::Type { name, .. } => self.gen_params.push((*name, false)),
                crate::ast::GenericParam::Const { name, .. } => self.gen_params.push((*name, true)),
                crate::ast::GenericParam::Lifetime { .. } => {}
            }
        }
        mark
    }

    /// Rewrites one item's generic parameter bounds, defaults,
    /// and where clause (trait paths name traits in this module).
    fn generics(&mut self, ast: &mut Ast, g: &mut crate::ast::Generics, w: &mut crate::ast::WhereClause, module: ModuleId) {
        for p in g.params.iter_mut() {
            match p {
                crate::ast::GenericParam::Type { bounds, default, span, .. } => {
                    self.bounds(ast, bounds, *span, module);
                    if let Some(d) = *default {
                        self.ty(ast, d, module, &[]);
                    }
                }
                crate::ast::GenericParam::Const { ty, .. } => {
                    let ty = *ty;
                    self.ty(ast, ty, module, &[]);
                }
                crate::ast::GenericParam::Lifetime { .. } => {}
            }
        }
        for pred in w.preds.iter_mut() {
            if let crate::ast::WherePred::Type { ty, bounds, .. } = pred {
                let ty = *ty;
                self.ty(ast, ty, module, &[]);
                self.bounds(ast, bounds, w.span, module);
            }
        }
    }

    fn items(&mut self, ast: &mut Ast, items: &mut Vec<Item>, fi: usize, module: ModuleId, prefix: &[Sym]) {
        for item in items.iter_mut() {
            match &mut item.kind {
                ItemKind::Fn(f) => {
                    let mut def = std::mem::replace(f, dummy_fn());
                    self.fn_def(ast, &mut def, module);
                    *f = def;
                }
                ItemKind::Struct(s) => {
                    let mark = self.push_params(&s.generics);
                    self.generics(ast, &mut s.generics, &mut s.where_clause, module);
                    let fields = match &mut s.fields {
                        VariantFields::Struct(fs) | VariantFields::Tuple(fs) => fs.iter_mut().map(|f| f.ty).collect::<Vec<_>>(),
                        VariantFields::Unit => Vec::new(),
                    };
                    for t in fields {
                        self.ty(ast, t, module, &[]);
                    }
                    self.gen_params.truncate(mark);
                }
                ItemKind::Enum(e) => {
                    let mark = self.push_params(&e.generics);
                    self.generics(ast, &mut e.generics, &mut e.where_clause, module);
                    let mut tys = Vec::new();
                    let mut discs = Vec::new();
                    for v in &mut e.variants {
                        if let VariantFields::Struct(fs) | VariantFields::Tuple(fs) = &v.fields {
                            tys.extend(fs.iter().map(|f| f.ty));
                        }
                        if let Some(d) = v.discriminant {
                            discs.push(d);
                        }
                    }
                    for t in tys {
                        self.ty(ast, t, module, &[]);
                    }
                    // Discriminants cannot use the enum's params (rustc
                    // rejects them there), so they resolve as before.
                    self.gen_params.truncate(mark);
                    let mut scopes = vec![Frame::default()];
                    for d in discs {
                        self.expr(ast, d, module, &mut scopes);
                    }
                }
                ItemKind::Impl(imp) => {
                    let mark = self.push_params(&imp.generics);
                    self.generics(ast, &mut imp.generics, &mut imp.where_clause, module);
                    if let Some(tr) = &mut imp.trait_ref {
                        let span = imp.span;
                        self.rewrite_path(&mut tr.path, Namespace::Type, span, module, &[], ast);
                    }
                    self.ty(ast, imp.self_ty, module, &[]);
                    for at in imp.types.iter_mut() {
                        self.bounds(ast, &mut at.bounds, at.span, module);
                        self.generics(ast, &mut at.generics, &mut at.where_clause, module);
                        if let Some(d) = at.default {
                            self.ty(ast, d, module, &[]);
                        }
                    }
                    let const_tys: Vec<crate::ast::TyId> = imp.consts.iter().map(|c| c.ty).collect();
                    for t in const_tys {
                        self.ty(ast, t, module, &[]);
                    }
                    let mut fns = std::mem::take(&mut imp.fns);
                    for f in &mut fns {
                        self.fn_def(ast, f, module);
                    }
                    imp.fns = fns;
                    self.gen_params.truncate(mark);
                }
                ItemKind::Trait(t) => {
                    let mark = self.push_params(&t.generics);
                    self.generics(ast, &mut t.generics, &mut t.where_clause, module);
                    self.bounds(ast, &mut t.bounds, t.span, module);
                    for at in t.types.iter_mut() {
                        self.bounds(ast, &mut at.bounds, at.span, module);
                        self.generics(ast, &mut at.generics, &mut at.where_clause, module);
                        if let Some(d) = at.default {
                            self.ty(ast, d, module, &[]);
                        }
                    }
                    let const_tys: Vec<crate::ast::TyId> = t.consts.iter().map(|c| c.ty).collect();
                    for ty in const_tys {
                        self.ty(ast, ty, module, &[]);
                    }
                    let mut fns = std::mem::take(&mut t.fns);
                    for f in &mut fns {
                        self.fn_def(ast, f, module);
                    }
                    t.fns = fns;
                    self.gen_params.truncate(mark);
                }
                ItemKind::Const(c) => {
                    self.ty(ast, c.ty, module, &[]);
                    if let Some(v) = c.value {
                        let mut scopes = vec![Frame::default()];
                        self.expr(ast, v, module, &mut scopes);
                    }
                }
                ItemKind::Static(s) => {
                    self.ty(ast, s.ty, module, &[]);
                    if let Some(v) = s.value {
                        let mut scopes = vec![Frame::default()];
                        self.expr(ast, v, module, &mut scopes);
                    }
                }
                ItemKind::Type(a) => {
                    let mark = self.push_params(&a.generics);
                    self.generics(ast, &mut a.generics, &mut a.where_clause, module);
                    self.ty(ast, a.ty, module, &[]);
                    self.gen_params.truncate(mark);
                }
                ItemKind::Mod(m) => {
                    let mut key = prefix.to_vec();
                    key.push(m.name);
                    if let (Some(body), Some(&child)) = (&mut m.body, self.list_module.get(&(fi, key.clone()))) {
                        self.items(ast, body, fi, child, &key);
                    }
                }
                _ => {}
            }
        }
    }

    /// Rewrites one fn's signature types and body.
    fn fn_def(&mut self, ast: &mut Ast, def: &mut FnDef, module: ModuleId) {
        let mark = self.push_params(&def.generics);
        self.generics(ast, &mut def.generics, &mut def.where_clause, module);
        for p in &def.params {
            let t = p.ty;
            self.ty(ast, t, module, &[]);
        }
        if let Some(t) = def.ret {
            self.ty(ast, t, module, &[]);
        }
        if let Some(body) = def.body {
            let mut scopes = vec![Frame::default()];
            let mut frame = Frame::default();
            for p in &def.params {
                match p.pat {
                    Some(pat) => self.pat_bindings(ast, pat, &mut frame.locals),
                    None => frame.locals.push(p.name),
                }
            }
            scopes.push(frame);
            self.block(ast, body, module, &mut scopes);
        }
        self.gen_params.truncate(mark);
    }

    /// Collects the binding names a pattern introduces.
    fn pat_bindings(&self, ast: &Ast, id: PatId, out: &mut Vec<Sym>) {
        match ast.pat(id) {
            Pat::Binding { name, .. } => out.push(*name),
            Pat::At { name, inner, .. } => {
                out.push(*name);
                self.pat_bindings(ast, *inner, out);
            }
            Pat::TupleStruct { elems, .. } | Pat::Tuple(elems) | Pat::Or(elems) => {
                for e in elems {
                    self.pat_bindings(ast, *e, out);
                }
            }
            Pat::Struct { fields, .. } => {
                for (_, f) in fields {
                    self.pat_bindings(ast, *f, out);
                }
            }
            Pat::Slice { prefix, middle, suffix } => {
                for e in prefix.iter().chain(suffix) {
                    self.pat_bindings(ast, *e, out);
                }
                if let Some(m) = middle {
                    self.pat_bindings(ast, *m, out);
                }
            }
            Pat::Ref { inner, .. } | Pat::Paren(inner) => self.pat_bindings(ast, *inner, out),
            _ => {}
        }
    }

    /// True when `name` is a local in any open frame.
    fn is_local(scopes: &[Frame], name: Sym) -> bool {
        scopes.iter().rev().any(|f| f.locals.contains(&name))
    }

    /// Resolves a path with lexical scopes first. `Done` from a local
    /// variable is reported as Absent with the `local` flag set through
    /// the return: callers leave the path written.
    fn resolve(&self, segs: &[Sym], ns: Namespace, module: ModuleId, scopes: &[Frame]) -> (PathRes, bool) {
        if segs.len() == 1 && ns != Namespace::Type && Self::is_local(scopes, segs[0]) {
            return (PathRes::Absent, true);
        }
        // Function-local imports answer for the first segment.
        if !segs.is_empty() {
            let first = segs[0];
            let plain = self.interner.get(first);
            if !matches!(plain, "crate" | "self" | "super" | "Self") {
                for frame in scopes.iter().rev() {
                    if let Some(b) = frame.imports.get(&(first, ns_index(ns))) {
                        return match b {
                            LocalBind::Ambiguous => (PathRes::Ambiguous, false),
                            LocalBind::Target(t) => {
                                if segs.len() == 1 {
                                    (PathRes::Done(*t), false)
                                } else {
                                    match self.tables.walk_from(module, *t, &segs[1..], ns, self.interner) {
                                        PathRes::Partial(t2, rest) => (PathRes::Partial(t2, rest + 1), false),
                                        other => (other, false),
                                    }
                                }
                            }
                        };
                    }
                }
            }
        }
        (self.tables.resolve_path(module, segs, ns, PathMode::Lexical, false, self.interner), false)
    }

    /// Applies a resolution to a written path in place. `span` is the
    /// path's own span for diagnostics.
    fn apply(&mut self, segs: &mut Vec<PathSeg>, res: PathRes, span: Span, module: ModuleId) {
        match res {
            PathRes::Done(Target::Def(def)) => {
                if let Some(info) = self.tables.def_info.get(&def) {
                    let args = segs.last().map(|s| s.args.clone()).unwrap_or_default();
                    *segs = vec![PathSeg { name: info.flat, args }];
                }
            }
            PathRes::Done(Target::Variant(def, variant)) => {
                if let Some(info) = self.tables.def_info.get(&def) {
                    // Written generic args stay on their segment
                    // (`E::<u8>::V`, `V::<u8>`): the checker reads them.
                    let n = segs.len();
                    let variant_args = segs.last().map(|s| s.args.clone()).unwrap_or_default();
                    let enum_args = if n >= 2 { segs[n - 2].args.clone() } else { Default::default() };
                    *segs = vec![PathSeg { name: info.flat, args: enum_args }, PathSeg { name: variant, args: variant_args }];
                }
            }
            PathRes::Done(Target::Module(_)) => {
                // A module as a value or type is an error the checker
                // reports; leave the path written.
            }
            PathRes::Done(Target::Extern(i)) => {
                let e = &self.tables.externs[i as usize];
                if let Some(why) = &e.unsupported {
                    self.diags.push(unsupported_diag(why, span));
                } else if !e.is_std_lib {
                    self.diags.push(crate::diag::not_yet("L0505", span, "items from other crates"));
                }
            }
            PathRes::Partial(Target::Def(def), rest) => {
                if rest + 1 == segs.len() {
                    if let Some(info) = self.tables.def_info.get(&def) {
                        let item_seg = segs[rest].clone();
                        // Associated fn visibility (variants take the
                        // enum's vis, already checked by resolution).
                        if let Some(methods) = self.tables.assoc_vis.get(&def)
                            && let Some((vis, def_mod)) = methods.get(&item_seg.name)
                            && !self.tables.visible(vis, *def_mod, module, self.interner)
                        {
                            self.diags.push(private_diag(self.interner.get(item_seg.name), span));
                        }
                        // The def segment keeps its written generic
                        // arguments (`W::<u8>::item`): the checker
                        // reads them as the Self type's arguments.
                        let mut head = segs[rest.saturating_sub(1)].clone();
                        head.name = info.flat;
                        *segs = vec![head, item_seg];
                    }
                }
            }
            PathRes::Partial(Target::Variant(..), _) => {}
            PathRes::Partial(Target::Extern(i), _) => {
                let e = &self.tables.externs[i as usize];
                if let Some(why) = &e.unsupported {
                    self.diags.push(unsupported_diag(why, span));
                } else if !e.is_std_lib {
                    self.diags.push(crate::diag::not_yet("L0505", span, "items from other crates"));
                }
            }
            PathRes::Partial(Target::Module(_), _) => {}
            PathRes::Ambiguous => {
                let name = segs.last().map(|s| self.interner.get(s.name).to_string()).unwrap_or_default();
                self.diags.push(ambiguous_diag(&name, span));
            }
            PathRes::Private => {
                let name = segs.last().map(|s| self.interner.get(s.name).to_string()).unwrap_or_default();
                self.diags.push(private_diag(&name, span));
            }
            PathRes::Prelude | PathRes::Absent => {}
        }
    }

    /// Rewrites a struct-literal or pattern path. A variant brought in
    /// by `use E::*` or `use E::V` binds in the value namespace, so
    /// probe it first; a plain struct name takes the type path as before.
    fn rewrite_ctor_path(&mut self, segs: &mut Vec<PathSeg>, span: Span, module: ModuleId, scopes: &[Frame], ast: &mut Ast) {
        let names: Vec<Sym> = segs.iter().map(|s| s.name).collect();
        let (res, local) = self.resolve(&names, Namespace::Value, module, scopes);
        if !local && matches!(res, PathRes::Done(Target::Variant(..))) {
            self.rewrite_path(segs, Namespace::Value, span, module, scopes, ast);
        } else {
            self.rewrite_path(segs, Namespace::Type, span, module, scopes, ast);
        }
    }

    /// Expands a path whose first segment is bound by a std import
    /// (`use std::option::Option as O2`, `use std::mem as m`) back
    /// to the canonical written std path. Function-local target
    /// imports and explicit module bindings already resolved by
    /// `resolve` keep the name; a glob binding (rank 1) loses to
    /// the explicit std import, as in Rust. The asked namespace
    /// wins, with the others as a fallback for the paths that probe
    /// two namespaces (variant constructors in patterns).
    fn expand_std_alias(&self, segs: &mut Vec<PathSeg>, names: &[Sym], ns: Namespace, module: ModuleId, scopes: &[Frame]) -> bool {
        let Some(&first) = names.first() else { return false };
        if matches!(self.interner.get(first), "crate" | "self" | "super" | "Self") {
            return false;
        }
        let asked = if names.len() > 1 { Namespace::Type } else { ns };
        let asked_idx = ns_index(asked);
        if scopes.iter().rev().any(|f| f.imports.contains_key(&(first, asked_idx))) {
            return false;
        }
        if matches!(self.tables.lookup(module, asked, first), Some(BindState::One(b)) if b.rank >= 2) {
            return false;
        }
        let mut order = [asked_idx; 3];
        let mut n_order = 1;
        for idx in [ns_index(Namespace::Type), ns_index(Namespace::Value), ns_index(Namespace::Macro)] {
            if !order[..n_order].contains(&idx) {
                order[n_order] = idx;
                n_order += 1;
            }
        }
        let alias = scopes
            .iter()
            .rev()
            .flat_map(|f| order[..n_order].iter().filter_map(move |&idx| f.std_imports.get(&(first, idx))))
            .next()
            .or_else(|| {
                order[..n_order]
                    .iter()
                    .filter_map(|&idx| self.tables.std_aliases.get(&(module, idx as u8, first)).map(|(_, p)| p))
                    .next()
            });
        let Some(alias) = alias else { return false };
        // A module import does not shadow a primitive type in a type
        // position: `use std::str;` keeps `&str` the primitive.
        if names.len() == 1
            && ns == Namespace::Type
            && crate::ty::lang::is_primitive_type_name(self.interner.get(first))
            && crate::ty::lang::std_is_module_path(&alias.iter().map(|s| self.interner.get(*s)).collect::<Vec<_>>())
        {
            return false;
        }
        let mut out: Vec<PathSeg> = alias.iter().map(|s| PathSeg::plain(*s)).collect();
        // Turbofish on the imported name belongs on the aliased item.
        if let Some(last) = out.last_mut() {
            last.args = segs[0].args.clone();
        }
        out.extend(segs.iter().skip(1).cloned());
        *segs = out;
        true
    }

    /// Rewrites one written path (segments borrowed out of the arena by
    /// the caller, then put back through `set`).
    fn rewrite_path(&mut self, segs: &mut Vec<PathSeg>, ns: Namespace, span: Span, module: ModuleId, scopes: &[Frame], ast: &mut Ast) {
        // Generic arguments hold types and const exprs of their own.
        let mut tys = Vec::new();
        let mut consts = Vec::new();
        for s in segs.iter() {
            collect_arg_tys(&s.args, &mut tys);
            collect_arg_consts(&s.args, &mut consts);
        }
        for t in tys {
            self.ty(ast, t, module, scopes);
        }
        // A const argument's paths resolve like an array length's:
        // in this module, with no locals in scope.
        for e in consts {
            let mut scopes = vec![Frame::default()];
            self.expr(ast, e, module, &mut scopes);
        }
        let names: Vec<Sym> = segs.iter().map(|s| s.name).collect();
        // A leading `::` arrives as a marker segment (parser). Resolve
        // through the extern prelude, and drop the marker when the path
        // stays written (std compat reads plain `std::...`).
        if names.first().is_some_and(|n| self.interner.get(*n) == "::") {
            let res = self.tables.resolve_path(module, &names[1..], ns, PathMode::Lexical, true, self.interner);
            match res {
                PathRes::Partial(Target::Extern(i), _) | PathRes::Done(Target::Extern(i)) if self.tables.externs[i as usize].is_std_lib => {
                    segs.remove(0);
                }
                _ => self.apply(segs, res, span, module),
            }
            return;
        }
        let (res, local) = self.resolve(&names, ns, module, scopes);
        if !local {
            // A generic param of the item shadows module items and
            // imports: a type or const param in a type path, a const
            // param as a value, a type param before `::` in a value path
            // (`T::default()`). Check resolves the path as written.
            if let Some(&(_, is_const)) = self.gen_params.iter().rev().find(|(n, _)| Some(n) == names.first())
                && match ns {
                    Namespace::Type => true,
                    Namespace::Value => (names.len() == 1) == is_const,
                    _ => false,
                }
            {
                return;
            }
            if self.expand_std_alias(segs, &names, ns, module, scopes) {
                return;
            }
            // Lexical scope (section 1.3): an unqualified name that only
            // another module defines is not found here, even though the
            // merged flat tables could answer it. Names no module
            // defines (primitives, builtins) fall through as before.
            // A non-prelude std type lust knows by name needs a `use`
            // in this module or fn body, as in Rust (W-STD-A). An
            // explicit one expanded above; a glob is the other way in.
            if res == PathRes::Absent
                && let Some(&first) = names.first()
                && crate::ty::lang::needs_std_use(self.interner.get(first))
                && !self.local_names.contains_key(&first)
                && !self.tables.std_glob_imports(module, self.interner.get(first), self.interner)
            {
                let n = self.interner.get(first).to_string();
                let (m, _, _) = crate::ty::lang::STD_IMPORTED_TYPES.iter().find(|t| t.2 == n).map(|t| (t.1, 0, 0)).unwrap_or(("rc", 0, 0));
                self.diags.push(Diag::new(
                    "L0102",
                    span,
                    format!("cannot find type `{n}` in this scope"),
                    format!("Import it: `use std::{m}::{n};`."),
                ));
                return;
            }
            if res == PathRes::Absent && names.first().is_some_and(|n| self.local_names.contains_key(n)) {
                // A bare path in a type position may name a const
                // item: a const generic argument the parser read as
                // a type (`Arr<N>`). Rust allows only a
                // single-segment path there (multi-segment const
                // paths need braces), so only those rewrite as the
                // const they name; collect/check kind-check the
                // position, and a const name in a true type
                // position still rejects there.
                if ns == Namespace::Type && names.len() == 1 {
                    let (vres, _) = self.resolve(&names, Namespace::Value, module, scopes);
                    if let PathRes::Done(Target::Def(def)) = vres
                        && self.tables.def_info.get(&def).is_some_and(|i| i.kind == ResKind::Const)
                    {
                        self.apply(segs, vres, span, module);
                        return;
                    }
                }
                let first = self.interner.get(names[0]).to_string();
                self.diags.push(if ns == Namespace::Type {
                    Diag::new(
                        "L0102",
                        span,
                        format!("cannot find type `{first}` in this scope"),
                        "Import it with `use`, or write its module path.",
                    )
                } else {
                    Diag::new(
                        "L0101",
                        span,
                        format!("cannot find value `{first}` in this scope"),
                        "Import it with `use`, or write its module path.",
                    )
                });
                return;
            }
            self.apply(segs, res, span, module);
        }
    }

    /// Rewrites the type at `id`, recursing into compound types.
    /// Body callers pass their frames so a function-local `use`
    /// binds in type positions too; item signatures pass none.
    fn ty(&mut self, ast: &mut Ast, id: TyId, module: ModuleId, scopes: &[Frame]) {
        match ast.ty(id) {
            TyExpr::Path(_) => {
                let span = ast.ty_span(id);
                let TyExpr::Path(mut segs) = std::mem::replace(&mut ast.tys[id.0 as usize], TyExpr::Unit) else { return };
                self.rewrite_path(&mut segs, Namespace::Type, span, module, scopes, ast);
                ast.tys[id.0 as usize] = TyExpr::Path(segs);
            }
            TyExpr::Ref { inner, .. } => {
                let inner = *inner;
                self.ty(ast, inner, module, scopes);
            }
            TyExpr::Tuple(ts) => {
                let ts = ts.clone();
                for t in ts {
                    self.ty(ast, t, module, scopes);
                }
            }
            TyExpr::Slice(inner) | TyExpr::Paren(inner) | TyExpr::Ptr { inner, .. } => {
                let inner = *inner;
                self.ty(ast, inner, module, scopes);
            }
            TyExpr::Array { inner, len } => {
                let (inner, len) = (*inner, *len);
                self.ty(ast, inner, module, scopes);
                let mut scopes = vec![Frame::default()];
                self.expr(ast, len, module, &mut scopes);
            }
            TyExpr::Dyn { .. } | TyExpr::ImplTrait { .. } => {
                let span = ast.ty_span(id);
                let taken = std::mem::replace(&mut ast.tys[id.0 as usize], TyExpr::Unit);
                let mut taken = taken;
                match &mut taken {
                    TyExpr::Dyn { bounds, .. } | TyExpr::ImplTrait { bounds } => self.bounds(ast, bounds, span, module),
                    _ => unreachable!(),
                }
                ast.tys[id.0 as usize] = taken;
            }
            TyExpr::QPath { .. } => {
                let span = ast.ty_span(id);
                let TyExpr::QPath { self_ty, trait_path, segs } = std::mem::replace(&mut ast.tys[id.0 as usize], TyExpr::Unit) else {
                    return;
                };
                let (mut trait_path, segs) = (trait_path, segs);
                self.ty(ast, self_ty, module, scopes);
                self.rewrite_path(&mut trait_path, Namespace::Type, span, module, scopes, ast);
                ast.tys[id.0 as usize] = TyExpr::QPath { self_ty, trait_path, segs };
            }
            TyExpr::FnPtr { inputs, ret, .. } => {
                let ins: Vec<TyId> = inputs.iter().map(|p| p.ty).collect();
                let ret = *ret;
                for t in ins {
                    self.ty(ast, t, module, scopes);
                }
                if let Some(r) = ret {
                    self.ty(ast, r, module, scopes);
                }
            }
            _ => {}
        }
    }

    /// Rewrites one block: statements in order, with `let` bindings and
    /// function-local `use` scopes.
    fn block(&mut self, ast: &mut Ast, id: BlockId, module: ModuleId, scopes: &mut Vec<Frame>) {
        scopes.push(Frame::default());
        let stmts = std::mem::take(&mut ast.blocks[id.0 as usize].stmts);
        let mut out = Vec::with_capacity(stmts.len());
        for stmt in stmts {
            match stmt {
                Stmt::Let { pat, ty, init, els, attrs, span } => {
                    if let Some(t) = ty {
                        self.ty(ast, t, module, scopes);
                    }
                    if let Some(e) = init {
                        self.expr(ast, e, module, scopes);
                    }
                    self.pat(ast, pat, module, scopes);
                    let mut names = Vec::new();
                    self.pat_bindings(ast, pat, &mut names);
                    if let Some(frame) = scopes.last_mut() {
                        frame.locals.extend(names);
                    }
                    if let Some(b) = els {
                        self.block(ast, b, module, scopes);
                    }
                    out.push(Stmt::Let { pat, ty, init, els, attrs, span });
                }
                Stmt::Expr { expr, semi, attrs } => {
                    self.expr(ast, expr, module, scopes);
                    out.push(Stmt::Expr { expr, semi, attrs });
                }
                Stmt::Item(idx) => {
                    self.stmt_item(ast, idx, module, scopes);
                    out.push(Stmt::Item(idx));
                }
                Stmt::Macro { call, semi } => out.push(Stmt::Macro { call, semi }),
            }
        }
        ast.blocks[id.0 as usize].stmts = out;
        if let Some(tail) = ast.blocks[id.0 as usize].tail {
            self.expr(ast, tail, module, scopes);
        }
        scopes.pop();
    }

    /// Resolves one statement item. Only `use` reaches here today (the
    /// parser rejects other body items); its bindings scope to the rest
    /// of the block.
    fn stmt_item(&mut self, ast: &mut Ast, idx: u32, module: ModuleId, scopes: &mut Vec<Frame>) {
        let Some(item) = ast.stmt_items.get(idx as usize) else { return };
        // A nested item binds its name in this block at explicit rank, so
        // an explicit `use` of the same name in the block (either order)
        // is a duplicate. Item-to-item duplicates also fire here; collect
        // checks them again for entry points that skip this pass.
        {
            let item_name = match &item.kind {
                ItemKind::Fn(def) => Some((def.name, def.name_span)),
                ItemKind::Const(c) => c.name.map(|n| (n, c.name_span)),
                ItemKind::Static(s) => Some((s.name, s.name_span)),
                _ => None,
            };
            if let Some((name, span)) = item_name
                && let Some(frame) = scopes.last_mut()
            {
                let key = (name, ns_index(Namespace::Value));
                if frame.explicit.contains(&key) {
                    self.diags.push(Diag::new(
                        "L0106",
                        span,
                        format!("`{}` is defined more than once", self.interner.get(name)),
                        "Rename one of the definitions.",
                    ));
                } else {
                    frame.explicit.push(key);
                }
            }
        }
        let ItemKind::Use(u) = &item.kind else { return };
        let tree = u.tree.clone();
        let span = item.span;
        let mut flat = Vec::new();
        flatten_use(&tree, module, VisKind::Priv, &mut flat, self.interner);
        let self_sym = self.interner.intern("self");
        let crate_sym = self.interner.intern("crate");
        let super_sym = self.interner.intern("super");
        let self_ty = self.interner.intern("Self");
        let kw = |s: Sym| s == crate_sym || s == self_sym || s == super_sym;
        for imp in flat {
            match imp.kind {
                ImportKind::BadLeading { .. } => {
                    self.diags.push(Diag::new(
                        "L0506",
                        span,
                        "the crate root in a `use` path can only be used in start position",
                        "Move the leading `::` to the start of the whole import, or remove it.",
                    ));
                }
                ImportKind::CheckPath { path } => {
                    if path.is_empty() {
                        continue;
                    }
                    let ok = matches!(
                        self.tables.resolve_module_path(module, &path, imp.leading_colon, self.interner),
                        PathRes::Done(_)
                    ) || matches!(
                        self.tables.resolve_path(module, &path, Namespace::Type, PathMode::Use, imp.leading_colon, self.interner),
                        PathRes::Done(Target::Def(adt)) if self.tables.variants.contains_key(&adt)
                    );
                    if !ok {
                        self.diags.push(Diag::new(
                            "L0506",
                            span,
                            format!(
                                "unresolved import `{}`",
                                path.iter().map(|s| self.interner.get(*s)).collect::<Vec<_>>().join("::")
                            ),
                            "Check the path: every segment must name a module or item that is visible here.",
                        ));
                    }
                }
                ImportKind::Single { path, name } => {
                    if path.len() == 1 {
                        self.check_local_single_use(&path, name, imp.leading_colon, module, span, scopes);
                        continue;
                    }
                    // `use super::super as x;` and kin: the whole path is
                    // module keywords, the rename binds that module.
                    if *path.last().unwrap() != self_sym && name != *path.last().unwrap() && path.iter().all(|&s| kw(s)) {
                        match self.tables.resolve_module_path(module, &path, imp.leading_colon, self.interner) {
                            PathRes::Done(Target::Module(src)) => {
                                let bn = crate::resolve::imports::import_bind_name(name, Target::Module(src), self.interner);
                                if insert_local(scopes, bn, Namespace::Type, LocalBind::Target(Target::Module(src)), 2)
                                    && self.interner.get(name) != "_"
                                {
                                    self.push_local_dup(span, name);
                                }
                            }
                            PathRes::Done(Target::Extern(_)) => {}
                            _ => self.push_unresolved_use(span, &path),
                        }
                        continue;
                    }
                    // A trailing `self` binds the module (or enum) named
                    // by the prefix, under the segment before it.
                    if *path.last().unwrap() == self_sym {
                        let mod_path = &path[..path.len() - 1];
                        if name == self_sym && !matches!(mod_path.last(), Some(&c) if !kw(c) && c != self_ty) {
                            self.diags.push(Diag::new(
                                "L0506",
                                span,
                                "this import needs to be explicitly named",
                                "Add a rename, such as `use self as here;`.",
                            ));
                            continue;
                        }
                        let bind_name = if name == self_sym { *mod_path.last().unwrap() } else { name };
                        // A std module (`use std::rc::{self, Rc}`) binds as a
                        // std alias, as `use std::rc;` does.
                        if mod_path.len() > 1
                            && let PathRes::Done(Target::Extern(i)) | PathRes::Partial(Target::Extern(i), _) =
                                self.tables.resolve_module_path(module, mod_path, imp.leading_colon, self.interner)
                            && self.tables.externs[i as usize].is_std_lib
                            && self.tables.externs[i as usize].unsupported.is_none()
                        {
                            if self.interner.get(bind_name) != "_" && insert_local_std(scopes, bind_name, Namespace::Type, mod_path.to_vec()) {
                                self.push_local_dup(span, bind_name);
                            }
                            continue;
                        }
                        let target = match self.tables.resolve_module_path(module, mod_path, imp.leading_colon, self.interner) {
                            PathRes::Done(t) => Some(t),
                            _ => match self
                                .tables
                                .resolve_path(module, mod_path, Namespace::Type, PathMode::Use, imp.leading_colon, self.interner)
                            {
                                PathRes::Done(Target::Def(adt)) if self.tables.variants.contains_key(&adt) => {
                                    Some(Target::Def(adt))
                                }
                                _ => None,
                            },
                        };
                        match target {
                            Some(t) => {
                                let bn = crate::resolve::imports::import_bind_name(bind_name, t, self.interner);
                                if insert_local(scopes, bn, Namespace::Type, LocalBind::Target(t), 2)
                                    && self.interner.get(bind_name) != "_"
                                {
                                    self.push_local_dup(span, bind_name);
                                }
                            }
                            None => self.push_unresolved_use(span, &path),
                        }
                        continue;
                    }
                    match self.tables.resolve_module_path(module, &path[..path.len() - 1], imp.leading_colon, self.interner) {
                        PathRes::Done(Target::Module(src)) => {
                            let last = *path.last().unwrap();
                            let mut any = false;
                            let mut dup = false;
                            for ns in [Namespace::Type, Namespace::Value, Namespace::Macro] {
                                match self.tables.lookup(src, ns, last) {
                                    Some(BindState::One(b)) if self.tables.visible(&b.vis, b.def_module, module, self.interner) => {
                                        any = true;
                                        let bn = crate::resolve::imports::import_bind_name(name, b.target, self.interner);
                                        dup |= insert_local(scopes, bn, ns, LocalBind::Target(b.target), 2);
                                    }
                                    Some(BindState::Ambiguous) => {
                                        any = true;
                                        dup |= insert_local(scopes, name, ns, LocalBind::Ambiguous, 2);
                                    }
                                    _ => {}
                                }
                            }
                            if dup && self.interner.get(name) != "_" {
                                self.diags.push(Diag::new(
                                    "L0106",
                                    span,
                                    format!("`{}` is defined more than once", self.interner.get(name)),
                                    "Rename one of the imports with `as`, or remove one.",
                                ));
                            }
                            if !any {
                                self.diags.push(Diag::new(
                                    "L0506",
                                    span,
                                    format!(
                                        "unresolved import `{}`",
                                        path.iter().map(|s| self.interner.get(*s)).collect::<Vec<_>>().join("::")
                                    ),
                                    "Check the path: every segment must name a module or item that is visible here.",
                                ));
                            }
                        }
                        PathRes::Done(Target::Extern(i)) => {
                            if self.tables.externs[i as usize].is_std_lib
                                && self.tables.externs[i as usize].unsupported.is_none()
                                && self.interner.get(name) != "_"
                                && let Some(nss) = crate::resolve::imports::std_import_namespaces(self.interner, &path)
                            {
                                let mut dup = false;
                                for ns in nss {
                                    dup |= insert_local_std(scopes, name, ns, path.clone());
                                }
                                if dup {
                                    self.push_local_dup(span, name);
                                }
                            }
                        }
                        _ => {
                            self.diags.push(Diag::new(
                                "L0506",
                                span,
                                format!(
                                    "unresolved import `{}`",
                                    path.iter().map(|s| self.interner.get(*s)).collect::<Vec<_>>().join("::")
                                ),
                                "Check the path: every segment must name a module or item that is visible here.",
                            ));
                        }
                    }
                }
                ImportKind::Glob { path } => {
                    if path.is_empty() {
                        self.diags.push(Diag::new(
                            "L0506",
                            span,
                            "cannot glob-import all possible crates",
                            "Name the module before the `*`, such as `use a::*;`.",
                        ));
                        continue;
                    }
                    // `use a::E::*;` in a body imports the variants.
                    if let PathRes::Done(Target::Def(adt)) =
                        self.tables.resolve_path(module, &path, Namespace::Type, PathMode::Use, imp.leading_colon, self.interner)
                        && self.tables.variants.contains_key(&adt)
                    {
                        for v in self.tables.variants[&adt].clone() {
                            insert_local(scopes, v, Namespace::Value, LocalBind::Target(Target::Variant(adt, v)), 1);
                        }
                        continue;
                    }
                    match self.tables.resolve_module_path(module, &path, imp.leading_colon, self.interner) {
                        // A glob of a std module brings the non-prelude
                        // std types lust knows by name, below any
                        // explicit binding of the frame (W-STD-A).
                        PathRes::Done(Target::Extern(i)) => {
                            if self.tables.externs[i as usize].is_std_lib
                                && let Some(frame) = scopes.last_mut()
                            {
                                let p: Vec<&str> = path.iter().map(|s| self.interner.get(*s)).collect();
                                for &(_, _, n) in crate::ty::lang::STD_IMPORTED_TYPES {
                                    if crate::ty::lang::std_glob_imports(&p, n) {
                                        let name = self.interner.intern(n);
                                        let mut full = path.clone();
                                        full.push(name);
                                        frame.std_imports.entry((name, ns_index(Namespace::Type))).or_insert(full);
                                    }
                                }
                            }
                        }
                        PathRes::Done(Target::Module(src)) => {
                        let mut entries = Vec::new();
                        for ns in [Namespace::Type, Namespace::Value, Namespace::Macro] {
                            for (name, state) in &self.tables.maps[src.0 as usize][ns_index(ns)] {
                                match state {
                                    BindState::One(b) if self.tables.visible(&b.vis, b.def_module, module, self.interner) => {
                                        entries.push((*name, ns, LocalBind::Target(b.target)));
                                    }
                                    BindState::Ambiguous => entries.push((*name, ns, LocalBind::Ambiguous)),
                                    _ => {}
                                }
                            }
                        }
                        for (name, ns, bind) in entries {
                            insert_local(scopes, name, ns, bind, 1);
                        }
                        }
                        _ => self.push_unresolved_use(span, &path),
                    }
                }
            }
        }
    }

    /// The L0506 diagnostic for a function-local `use` that does not
    /// resolve, matching the module-level fixpoint message.
    fn push_unresolved_use(&mut self, span: Span, path: &[Sym]) {
        self.diags.push(Diag::new(
            "L0506",
            span,
            format!("unresolved import `{}`", path.iter().map(|s| self.interner.get(*s)).collect::<Vec<_>>().join("::")),
            "Check the path: every segment must name a module or item that is visible here.",
        ));
    }

    /// The L0106 diagnostic for a repeated function-local import name.
    fn push_local_dup(&mut self, span: Span, name: Sym) {
        self.diags.push(Diag::new(
            "L0106",
            span,
            format!("`{}` is defined more than once", self.interner.get(name)),
            "Rename one of the imports with `as`, or remove one.",
        ));
    }

    /// Checks a one-segment function-local import (`use a;`, `use self;`,
    /// `use crate as x;`). These bind nothing the later walk needs (the
    /// name reads through the module tables), but a bad one is still an
    /// error in rustc, so it is validated and only that. A renamed
    /// std crate root (`use std as s;`) is the exception: it records
    /// a local std alias.
    fn check_local_single_use(&mut self, path: &[Sym], name: Sym, leading: bool, module: ModuleId, span: Span, scopes: &mut [Frame]) {
        let seg = path[0];
        let self_sym = self.interner.intern("self");
        let crate_sym = self.interner.intern("crate");
        let super_sym = self.interner.intern("super");
        if seg == crate_sym || seg == self_sym || seg == super_sym {
            if name == seg {
                self.diags.push(Diag::new(
                    "L0506",
                    span,
                    "this import needs to be explicitly named",
                    "Add a rename, such as `use self as here;`.",
                ));
            } else if !matches!(self.tables.resolve_module_path(module, path, leading, self.interner), PathRes::Done(_)) {
                self.push_unresolved_use(span, path);
            }
            return;
        }
        if let PathRes::Done(Target::Extern(i)) =
            self.tables.resolve_path(module, path, Namespace::Type, PathMode::Use, leading, self.interner)
        {
            if self.tables.externs[i as usize].is_std_lib
                && self.tables.externs[i as usize].unsupported.is_none()
                && self.interner.get(name) != "_"
                && insert_local_std(scopes, name, Namespace::Type, path.to_vec())
            {
                self.push_local_dup(span, name);
            }
            return;
        }
        let mut saw_private = false;
        for ns in [Namespace::Type, Namespace::Value, Namespace::Macro] {
            match self.tables.resolve_path(module, path, ns, PathMode::Use, leading, self.interner) {
                PathRes::Done(_) | PathRes::Partial(..) | PathRes::Prelude => return,
                PathRes::Private => saw_private = true,
                _ => {}
            }
        }
        if saw_private {
            self.diags.push(private_diag(self.interner.get(seg), span));
        } else {
            self.push_unresolved_use(span, path);
        }
    }

    /// A pattern binding name that resolves to a const, a unit
    /// struct, or an imported variant is a path pattern in Rust, not
    /// a fresh binding; one that resolves to a static is an error
    /// (L0633). Returns the replacement path pattern when it applies.
    fn binding_pat(&mut self, name: Sym, span: Span, module: ModuleId, scopes: &[Frame]) -> Option<Pat> {
        let (res, local) = self.resolve(&[name], Namespace::Value, module, scopes);
        if local {
            return None;
        }
        match res {
            PathRes::Done(Target::Def(def)) => match self.tables.def_info.get(&def) {
                Some(info) if info.kind == ResKind::Static => None,
                Some(info) if matches!(info.kind, ResKind::Const | ResKind::Adt) => Some(Pat::Path(vec![PathSeg::plain(info.flat)])),
                _ => None,
            },
            PathRes::Done(Target::Variant(def, variant)) => {
                self.tables.def_info.get(&def).map(|info| Pat::Path(vec![PathSeg::plain(info.flat), PathSeg::plain(variant)]))
            }
            PathRes::Ambiguous => {
                self.diags.push(ambiguous_diag(self.interner.get(name), span));
                None
            }
            PathRes::Private => {
                self.diags.push(private_diag(self.interner.get(name), span));
                None
            }
            _ => None,
        }
    }

    /// Rewrites one pattern's paths.
    fn pat(&mut self, ast: &mut Ast, id: PatId, module: ModuleId, scopes: &[Frame]) {
        let span = ast.pat_span(id);
        match std::mem::replace(&mut ast.pats[id.0 as usize], Pat::Wild) {
            Pat::Binding { name, mutable, by_ref } => {
                let replacement = if !mutable && !by_ref { self.binding_pat(name, span, module, scopes) } else { None };
                ast.pats[id.0 as usize] = replacement.unwrap_or(Pat::Binding { name, mutable, by_ref });
            }
            Pat::Path(mut segs) => {
                self.rewrite_path(&mut segs, Namespace::Value, span, module, scopes, ast);
                ast.pats[id.0 as usize] = Pat::Path(segs);
            }
            Pat::TupleStruct { path: mut s, elems } => {
                self.rewrite_ctor_path(&mut s, span, module, scopes, ast);
                for e in &elems {
                    self.pat(ast, *e, module, scopes);
                }
                ast.pats[id.0 as usize] = Pat::TupleStruct { path: s, elems };
            }
            Pat::Struct { path: mut s, fields, rest } => {
                self.rewrite_ctor_path(&mut s, span, module, scopes, ast);
                for (_, f) in &fields {
                    self.pat(ast, *f, module, scopes);
                }
                ast.pats[id.0 as usize] = Pat::Struct { path: s, fields, rest };
            }
            node => {
                // Child patterns and expressions first, then the node
                // goes back unchanged.
                match &node {
                    Pat::Lit(e) => {
                        let e = *e;
                        let mut sc = scopes.to_vec_shallow();
                        self.expr(ast, e, module, &mut sc);
                    }
                    Pat::Or(elems) | Pat::Tuple(elems) => {
                        for e in elems {
                            self.pat(ast, *e, module, scopes);
                        }
                    }
                    Pat::Range { lo, hi, .. } => {
                        let mut sc = scopes.to_vec_shallow();
                        if let Some(e) = lo {
                            self.expr(ast, *e, module, &mut sc);
                        }
                        if let Some(e) = hi {
                            self.expr(ast, *e, module, &mut sc);
                        }
                    }
                    Pat::At { inner, .. } | Pat::Ref { inner, .. } | Pat::Paren(inner) => {
                        let inner = *inner;
                        self.pat(ast, inner, module, scopes);
                    }
                    Pat::Slice { prefix, middle, suffix } => {
                        for e in prefix.iter().chain(suffix) {
                            self.pat(ast, *e, module, scopes);
                        }
                        if let Some(m) = middle {
                            self.pat(ast, *m, module, scopes);
                        }
                    }
                    _ => {}
                }
                ast.pats[id.0 as usize] = node;
            }
        }
    }

    /// Rewrites one expression subtree.
    /// One `if`/`while` condition with `let`s: operands of `&&` in order,
    /// each `let`'s scrutinee in the scopes so far, then a frame with its
    /// bindings pushed for what follows (the caller pops them).
    fn let_chain(&mut self, ast: &mut Ast, e: ExprId, module: ModuleId, scopes: &mut Vec<Frame>) {
        match &ast.exprs[e.0 as usize] {
            Expr::Binary { op: BinOp::And, lhs, rhs } => {
                let (lhs, rhs) = (*lhs, *rhs);
                self.let_chain(ast, lhs, module, scopes);
                self.let_chain(ast, rhs, module, scopes);
            }
            Expr::Let { pat, scrut } => {
                let (pat, scrut) = (*pat, *scrut);
                self.expr(ast, scrut, module, scopes);
                self.pat(ast, pat, module, scopes);
                let mut frame = Frame::default();
                self.pat_bindings(ast, pat, &mut frame.locals);
                scopes.push(frame);
            }
            _ => self.expr(ast, e, module, scopes),
        }
    }

    fn expr(&mut self, ast: &mut Ast, id: ExprId, module: ModuleId, scopes: &mut Vec<Frame>) {
        let span = ast.expr_span(id);
        // Nodes that carry a path are swapped out whole, rewritten, and
        // put back (the path rewrite needs `ast` for generic-arg types).
        if matches!(ast.exprs[id.0 as usize], Expr::Path(_)) {
            let Expr::Path(mut segs) = std::mem::replace(&mut ast.exprs[id.0 as usize], Expr::Unit) else { return };
            self.rewrite_path(&mut segs, Namespace::Value, span, module, scopes, ast);
            ast.exprs[id.0 as usize] = Expr::Path(segs);
            return;
        }
        if matches!(ast.exprs[id.0 as usize], Expr::StructLit { .. }) {
            let Expr::StructLit { path: mut segs, fields, update } = std::mem::replace(&mut ast.exprs[id.0 as usize], Expr::Unit) else {
                return;
            };
            self.rewrite_ctor_path(&mut segs, span, module, scopes, ast);
            for (_, _, e) in &fields {
                let e = *e;
                self.expr(ast, e, module, scopes);
            }
            if let Some(u) = update {
                self.expr(ast, u, module, scopes);
            }
            ast.exprs[id.0 as usize] = Expr::StructLit { path: segs, fields, update };
            return;
        }
        // A closure's params scope over its body: all of them in one
        // frame, pushed before the body (a param named like an item, such
        // as an imported fn, resolved to the item before).
        if let Expr::Closure { params, ret, body, .. } = &ast.exprs[id.0 as usize] {
            let (pats, ret, body): (Vec<PatId>, Option<TyId>, ExprId) = (params.iter().map(|p| p.pat).collect(), *ret, *body);
            if let Some(t) = ret {
                self.ty(ast, t, module, scopes);
            }
            let mut frame = Frame::default();
            for pat in pats {
                self.pat(ast, pat, module, scopes);
                self.pat_bindings(ast, pat, &mut frame.locals);
            }
            scopes.push(frame);
            self.expr(ast, body, module, scopes);
            scopes.pop();
            return;
        }
        // `if let` and `while let` (let chains too): each `let` binds over
        // the later conditions and the body, not the `else` branch (the
        // bindings scoped over nothing before, so a body name like an
        // imported fn resolved to the fn).
        if let Expr::If { cond, then, els } = &ast.exprs[id.0 as usize]
            && has_let(ast, *cond)
        {
            let (cond, then, els) = (*cond, *then, *els);
            let depth = scopes.len();
            self.let_chain(ast, cond, module, scopes);
            self.block(ast, then, module, scopes);
            scopes.truncate(depth);
            if let Some(e) = els {
                self.expr(ast, e, module, scopes);
            }
            return;
        }
        if let Expr::While { cond, body, .. } = &ast.exprs[id.0 as usize]
            && has_let(ast, *cond)
        {
            let (cond, body) = (*cond, *body);
            let depth = scopes.len();
            self.let_chain(ast, cond, module, scopes);
            self.block(ast, body, module, scopes);
            scopes.truncate(depth);
            return;
        }
        match ast.exprs[id.0 as usize].kind_children() {
            ExprKids { blocks, exprs, pats_with_scope, ty } => {
                if let Some(t) = ty {
                    self.ty(ast, t, module, scopes);
                }
                for e in exprs {
                    self.expr(ast, e, module, scopes);
                }
                for (pat, body) in pats_with_scope {
                    self.pat(ast, pat, module, scopes);
                    let mut frame = Frame::default();
                    self.pat_bindings(ast, pat, &mut frame.locals);
                    scopes.push(frame);
                    match body {
                        ScopeBody::Block(b) => self.block(ast, b, module, scopes),
                        ScopeBody::Expr(e) => self.expr(ast, e, module, scopes),
                        ScopeBody::None => {}
                    }
                    scopes.pop();
                }
                for b in blocks {
                    self.block(ast, b, module, scopes);
                }
            }
        }
    }
}

/// True when an `if`/`while` condition holds a `let` (directly or in a
/// `&&` chain).
fn has_let(ast: &Ast, e: ExprId) -> bool {
    match ast.expr(e) {
        Expr::Let { .. } => true,
        Expr::Binary { op: BinOp::And, lhs, rhs } => has_let(ast, *lhs) || has_let(ast, *rhs),
        _ => false,
    }
}

/// The generic-argument const expr ids under one segment's args.
fn collect_arg_consts(args: &GenericArgs, out: &mut Vec<crate::ast::ExprId>) {
    if let GenericArgs::Angle(args) = args {
        for a in args {
            match a {
                GenericArg::Const(e) => out.push(*e),
                GenericArg::Binding { kind: BindingKind::EqConst(e), .. } => out.push(*e),
                _ => {}
            }
        }
    }
}

/// The generic-argument type ids under one segment's args.
fn collect_arg_tys(args: &GenericArgs, out: &mut Vec<TyId>) {
    match args {
        GenericArgs::Angle(args) => {
            for a in args {
                match a {
                    GenericArg::Type(t) => out.push(*t),
                    GenericArg::Binding { kind: BindingKind::EqTy(t), .. } => out.push(*t),
                    _ => {}
                }
            }
        }
        GenericArgs::Parenthesized { inputs, output } => {
            out.extend(inputs.iter().copied());
            out.extend(output.iter().copied());
        }
        GenericArgs::None => {}
    }
}

/// Inserts one function-local import binding with a rank: an explicit
/// import (2) beats a glob (1); two globs with different targets are
/// ambiguous.
/// Inserts one function-local import binding. Returns true when an
/// explicit (rank 2) import rebinds a name an earlier explicit local
/// import already bound in this frame: a duplicate import (E0252).
/// Records one function-local std import alias at explicit rank.
/// Returns true when the name was already bound explicitly in
/// this frame and namespace (the caller reports a duplicate).
fn insert_local_std(scopes: &mut [Frame], name: Sym, ns: Namespace, path: Vec<Sym>) -> bool {
    let Some(frame) = scopes.last_mut() else { return false };
    let key = (name, ns_index(ns));
    if frame.explicit.contains(&key) {
        return true;
    }
    frame.explicit.push(key);
    frame.std_imports.insert(key, path);
    false
}

fn insert_local(scopes: &mut [Frame], name: Sym, ns: Namespace, bind: LocalBind, rank: u8) -> bool {
    let Some(frame) = scopes.last_mut() else { return false };
    let key = (name, ns_index(ns));
    let dup = rank >= 2 && frame.explicit.contains(&key);
    if rank >= 2 && !dup {
        frame.explicit.push(key);
    }
    match (frame.imports.get(&key), bind) {
        (Some(LocalBind::Target(old)), LocalBind::Target(new)) if *old != new && rank <= 1 => {
            frame.imports.insert(key, LocalBind::Ambiguous);
        }
        (Some(_), _) if rank <= 1 => {}
        _ => {
            frame.imports.insert(key, bind);
        }
    }
    dup
}

