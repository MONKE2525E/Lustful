// The outline worklist driver (docs/ARCH.md section 6.1): per crate, cfg
// stripping, module loading, import resolution, and macro expansion are
// one loop, not separate phases. W-RESOLVE owns the loop and the cfg,
// module, and import steps; W-MACRO owns expansion. Expansion runs per
// file at lex time through `expand::expand_lexed`, with this crate's
// real cfg environment (section 1.6) fed into the expander's facts, so
// its item strip and `cfg!` agree with the strip below. The frozen
// call-level interface (`expand::expand_call`) takes over when the
// parser keeps macro calls as nodes; today a `mod` item generated by a
// macro in an already-discovered file is not discovered as a new file
// edge (the loop re-registers its items, but file discovery ran on the
// unexpanded outline).
//
// Output shape: one merged Ast for collect. Defs outside the root module
// carry module-mangled flat names (`a$b$name`, never a legal Rust
// identifier; `ResolvedTables::display_names` keeps the source path of
// each, so flat names never reach program output or diagnostics), and
// every path the resolver can prove is rewritten to the
// flat name (one segment, or two for `Type::assoc`), so collect and
// check keep their flat tables while the binding tables here hold the
// real module semantics. DefIds are computed with the same formulas
// collect uses on the flat names, so slot keys and def ids agree by
// construction (the mangled name carries the module path in the hash).
