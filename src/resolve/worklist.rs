/// True when a crate root file needs the resolver: any `mod`, `use`,
/// `const`/`static`/`type` item keyword, `#[cfg`, `#[path`, `macro_rules`,
/// or an `include!` call in its token stream. Token-exact (strings and comments
/// never count); a `use` of `std` alone also routes here, which costs a
/// full rebuild but keeps one code path for imports and cfg.
///
/// A big file is lexed in pieces in parallel (see `route_pieces`); the
/// answer is the same as one serial lex.
pub fn needs_resolve(root_text: &str, interner: &Interner) -> bool {
    route_root(root_text, interner).0
}

/// `needs_resolve`, plus the root's token list when the answer is yes:
/// exactly a serial lex at file 0, base 0, which is how discovery lexes a
/// single-file crate root. The driver seeds the resolve cache with it
/// (`ResolveCache::seed_root`), so the root is not lexed twice.
pub fn route_root(root_text: &str, interner: &Interner) -> (bool, Option<lexer::Lexed>) {
    if let Some(pieces) = route_pieces(root_text) {
        let answers = par_map(&pieces, |&(a, b)| {
            let lexed = lexer::lex(&root_text[a..b], FileId(0), a as u32, interner).ok()?;
            piece_cut_ok(&lexed, b, root_text.len()).then(|| (needs_resolve_lexed(&lexed, interner), lexed))
        });
        if let Some(answers) = answers.into_iter().collect::<Option<Vec<(bool, lexer::Lexed)>>>() {
            let yes = answers.iter().any(|(y, _)| *y);
            return (yes, yes.then(|| join_lexed(answers.into_iter().map(|(_, l)| l).collect())));
        }
    }
    let Ok(lexed) = lexer::lex(root_text, FileId(0), 0, interner) else { return (false, None) };
    let yes = needs_resolve_lexed(&lexed, interner);
    (yes, yes.then_some(lexed))
}

/// Cut points for lexing a big file in parallel: about four pieces per
/// thread (`pool::threads`), each cut right after a line that ends in `}` or `;`. Each piece
/// lexes on its own, and `piece_cut_ok` checks that every cut really
/// falls between tokens; on any doubt the caller lexes serially (a cut
/// inside a string or comment leaves its start unterminated, so that
/// piece fails to lex or fails the check). The routing test of a piece
/// needs no context from its neighbors: a leading `::` triggers with no
/// previous token as it does after `}` or `;`, and no lookahead reaches
/// past a trailing `}` or `;`. None for a small file.
fn route_pieces(text: &str) -> Option<Vec<(usize, usize)>> {
    const MIN_PIECE: usize = 16 * 1024;
    let target = (text.len() / (crate::pool::threads() * 4)).max(MIN_PIECE);
    if text.len() < 2 * target {
        return None;
    }
    let b = text.as_bytes();
    let mut pieces = Vec::new();
    let mut start = 0;
    let mut at = target;
    while at < b.len() {
        match b[at..].iter().position(|&c| c == b'\n') {
            Some(k) => {
                let nl = at + k;
                if nl > start && matches!(b[nl - 1], b'}' | b';') && nl + 1 < b.len() {
                    pieces.push((start, nl + 1));
                    start = nl + 1;
                    at = start + target;
                } else {
                    at = nl + 1;
                }
            }
            None => break,
        }
    }
    pieces.push((start, b.len()));
    Some(pieces)
}

/// True when a piece lexed from `text[..b]` of a file of length `len` may
/// join its neighbors: the last piece always may; any other must end with
/// its own `}` or `;` right before the newline at its end. Then the serial
/// lexer is between tokens there too, in its start state, and no token or
/// lookahead crosses the cut.
fn piece_cut_ok(lexed: &lexer::Lexed, b: usize, len: usize) -> bool {
    let n = lexed.tokens.len();
    b == len
        || (n >= 2
            && matches!(lexed.tokens[n - 2].tok, lexer::Tok::RBrace | lexer::Tok::Semi)
            && lexed.tokens[n - 2].span.hi as usize == b - 1)
}

/// Lexes one file. A big file lexes in parallel pieces (`route_pieces`)
/// that join into exactly the tokens and string table of one serial lex;
/// when any piece fails its cut check or does not lex, the serial lex
/// runs, so errors are the serial ones.
fn lex_file(text: &str, file: FileId, interner: &Interner) -> Result<lexer::Lexed, Diag> {
    if let Some(pieces) = route_pieces(text) {
        let parts = par_map(&pieces, |&(a, b)| {
            let l = lexer::lex(&text[a..b], file, a as u32, interner).ok()?;
            piece_cut_ok(&l, b, text.len()).then_some(l)
        });
        if let Some(parts) = parts.into_iter().collect::<Option<Vec<_>>>() {
            return Ok(join_lexed(parts));
        }
    }
    lexer::lex(text, file, 0, interner)
}

/// Joins piece lexes in order: one final `Eof`, and string-table indexes
/// (`Tok::shift_strings`) moved past the strings of earlier pieces.
fn join_lexed(parts: Vec<lexer::Lexed>) -> lexer::Lexed {
    let mut out = lexer::Lexed { tokens: Vec::with_capacity(parts.iter().map(|p| p.tokens.len()).sum()), strings: Vec::new() };
    let last = parts.len() - 1;
    for (k, mut part) in parts.into_iter().enumerate() {
        let base = out.strings.len() as u32;
        if k < last {
            part.tokens.pop();
        }
        out.tokens.extend(part.tokens.into_iter().map(|mut t| {
            t.tok.shift_strings(base);
            t
        }));
        out.strings.append(&mut part.strings);
    }
    out
}

/// Item-aligned ranges of a file's parse stream (its expanded tokens when it
/// has macros) for parsing one big file in parallel (one-shot resolves
/// only; see the parse phase). A cut sits between a `}` or `;` at bracket
/// depth zero and a token that `starts_item` says can only begin an item
/// there. Cutting stops at the first unbalanced closer.
///
/// Why a segment parse equals the parse in place (`parser::parse_items`):
/// expansion runs on the whole file before this, so no macro is left to
/// expand across a cut; a `;` or `}` at depth zero followed by an item start
/// ends an item, so every range holds whole items, and an item parse reads
/// only its own tokens; between items the parser keeps no state but a
/// deferred error, which fails its segment. Any segment error makes the
/// caller parse the whole file again, so a cut never changes a diagnostic.
///
/// One range for a file under about 200 KB (the parse phase already runs
/// files in parallel, and segments of a small file would only nest), and
/// for a file with an inner attribute anywhere (`#` then `!` as tokens):
/// strip reads a file-level cfg from the first item, and the parser takes
/// `#!` only before any item.
fn item_segments(toks: &[lexer::Token], interner: &Interner) -> Vec<std::ops::Range<usize>> {
    use crate::lexer::Tok;
    const MIN_SEGMENT: usize = 4096;
    if toks.len() < 16 * MIN_SEGMENT || toks.windows(2).any(|w| w[0].tok == Tok::Pound && w[1].tok == Tok::Bang) {
        return vec![0..toks.len()];
    }
    let union = interner.intern("union");
    let target = (toks.len() / (crate::pool::threads() * 4)).max(MIN_SEGMENT);
    let mut out = Vec::new();
    let (mut start, mut depth) = (0usize, 0i64);
    for i in 0..toks.len().saturating_sub(1) {
        match toks[i].tok {
            Tok::LParen | Tok::LBracket | Tok::LBrace => depth += 1,
            Tok::RParen | Tok::RBracket | Tok::RBrace => depth -= 1,
            _ => {}
        }
        if depth < 0 {
            break;
        }
        if depth == 0 && i + 1 - start >= target && matches!(toks[i].tok, Tok::RBrace | Tok::Semi) && starts_item(toks, i + 1, union) {
            out.push(start..i + 1);
            start = i + 1;
        }
    }
    out.push(start..toks.len());
    out
}

/// True when `toks[i]` can only begin an item where `item_segments` cuts:
/// right after a `}` or `;` at bracket depth zero of a file's top level.
/// Rule for this list: a token may enter it only if it cannot continue a
/// top-level item there. An item goes on after such a `}` only inside a
/// `const` or `static` value (`= { 1 } + 2;`), where none of these can come
/// next. A missing start only loses a cut.
fn starts_item(toks: &[lexer::Token], i: usize, union: Sym) -> bool {
    use crate::lexer::Tok;
    let next = toks.get(i + 1).map(|t| t.tok);
    match toks[i].tok {
        Tok::Pound
        | Tok::Pub
        | Tok::Fn
        | Tok::Struct
        | Tok::Enum
        | Tok::Impl
        | Tok::Trait
        | Tok::Mod
        | Tok::Use
        | Tok::Const
        | Tok::Static
        | Tok::Type
        | Tok::Extern
        | Tok::Unsafe
        | Tok::Async => true,
        // `union U` (a contextual keyword), and a macro call `name!` or `path::name!`.
        Tok::Ident(s) => (s == union && matches!(next, Some(Tok::Ident(_)))) || is_macro_call(toks, i),
        Tok::SelfUpper | Tok::Crate | Tok::Super | Tok::SelfLower | Tok::PathSep => is_macro_call(toks, i),
        _ => false,
    }
}

/// True when `toks[i..]` is a macro call head: a path (`a::b`, a leading
/// `::` allowed) then `!`.
fn is_macro_call(toks: &[lexer::Token], mut i: usize) -> bool {
    use crate::lexer::Tok;
    if toks.get(i).map(|t| t.tok) == Some(Tok::PathSep) {
        i += 1;
    }
    loop {
        if !matches!(toks.get(i).map(|t| t.tok), Some(Tok::Ident(_) | Tok::SelfUpper | Tok::Crate | Tok::Super | Tok::SelfLower)) {
            return false;
        }
        match toks.get(i + 1).map(|t| t.tok) {
            Some(Tok::Bang) => return true,
            Some(Tok::PathSep) => i += 2,
            _ => return false,
        }
    }
}

/// The lexed form of `needs_resolve`, for callers that already lexed.
pub fn needs_resolve_lexed(lexed: &lexer::Lexed, interner: &Interner) -> bool {
    use crate::lexer::Tok;
    // Symbols, not texts: this reads every identifier token of the root.
    let (macro_rules, include) = (interner.intern("macro_rules"), interner.intern("include"));
    let toks = &lexed.tokens;
    for (i, t) in toks.iter().enumerate() {
        match t.tok {
            Tok::Mod | Tok::Use | Tok::Static | Tok::Extern | Tok::Crate | Tok::Super => return true,
            Tok::PathSep => {
                // A leading `::` (not a segment join): the token before
                // it is not a path segment end.
                let prev = if i == 0 { None } else { Some(toks[i - 1].tok) };
                if !matches!(
                    prev,
                    Some(Tok::Ident(_)) | Some(Tok::SelfUpper) | Some(Tok::Gt) | Some(Tok::Crate) | Some(Tok::Super) | Some(Tok::SelfLower)
                ) {
                    return true;
                }
            }
            Tok::Const if matches!(toks.get(i + 1).map(|t| t.tok), Some(Tok::Ident(_)) | Some(Tok::Underscore)) => return true,
            Tok::Type => return true,
            Tok::Pound => {
                // `#[cfg`, `#[cfg_attr`, `#[path`, `#[macro_use`, inner forms too.
                let mut j = i + 1;
                if toks.get(j).map(|t| t.tok) == Some(Tok::Bang) {
                    j += 1;
                }
                if toks.get(j).map(|t| t.tok) == Some(Tok::LBracket)
                    && let Some(Tok::Ident(s)) = toks.get(j + 1).map(|t| t.tok)
                    && matches!(interner.get(s), "cfg" | "cfg_attr" | "path" | "macro_use" | "macro_export" | "no_implicit_prelude")
                {
                    return true;
                }
            }
            Tok::Ident(s) if s == macro_rules => return true,
            // An `include!` can introduce items and macro definitions
            // other chunks would not see (added for W-MACRO).
            Tok::Ident(s) if s == include && matches!(toks.get(i + 1).map(|t| t.tok), Some(Tok::Bang)) => return true,
            _ => {}
        }
    }
    false
}

/// One file during resolution, or one item segment of a big file (see
