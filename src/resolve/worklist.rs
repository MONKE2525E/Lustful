/// Shallow copy of the scope stack for sub-walks that must not leak
/// bindings (literal-pattern expressions). Frames are small.
trait ShallowScopes {
    fn to_vec_shallow(&self) -> Vec<Frame>;
}

impl ShallowScopes for [Frame] {
    fn to_vec_shallow(&self) -> Vec<Frame> {
        self.iter().map(|f| Frame { locals: f.locals.clone(), imports: f.imports.clone() }).collect()
    }
}

/// Which child nodes an expression has, grouped by how the walk treats
/// them. Pattern-plus-body pairs get a scope frame from the pattern.
struct ExprKids {
    blocks: Vec<BlockId>,
    exprs: Vec<ExprId>,
    pats_with_scope: Vec<(PatId, ScopeBody)>,
    ty: Option<TyId>,
}

enum ScopeBody {
    Block(BlockId),
    Expr(ExprId),
    None,
}

/// Child enumeration for the rewrite walk, over the expression forms the
/// parser produces. Match arms: the walk needs arms one by one (each
/// arm's guard and body see the arm pattern's bindings), so Match is
/// expanded here into scrutinee plus one scoped pair per arm.
trait KindChildren {
    fn kind_children(&self) -> ExprKids;
}

impl KindChildren for Expr {
    fn kind_children(&self) -> ExprKids {
        let mut k = ExprKids { blocks: Vec::new(), exprs: Vec::new(), pats_with_scope: Vec::new(), ty: None };
        match self {
            Expr::Int(..)
            | Expr::Bool(_)
            | Expr::Str(_)
            | Expr::Char(_)
            | Expr::Unit
            | Expr::SelfValue
            | Expr::Float(_)
            | Expr::Underscore => {}
            Expr::Path(_) | Expr::StructLit { .. } => {}
            Expr::OffsetOf { ty, .. } => k.ty = Some(*ty),
            Expr::Block(b) | Expr::UnsafeBlock(b) | Expr::ConstBlock(b) => k.blocks.push(*b),
            Expr::LabeledBlock { body, .. } | Expr::AsyncBlock { body, .. } => k.blocks.push(*body),
            Expr::If { cond, then, els } => {
                k.exprs.push(*cond);
                k.blocks.push(*then);
                if let Some(e) = els {
                    k.exprs.push(*e);
                }
            }
            Expr::While { cond, body, .. } => {
                k.exprs.push(*cond);
                k.blocks.push(*body);
            }
            Expr::Loop { body, .. } => k.blocks.push(*body),
            Expr::For { pat, iter, body, .. } => {
                k.exprs.push(*iter);
                k.pats_with_scope.push((*pat, ScopeBody::Block(*body)));
            }
            Expr::Match { scrut, arms } => {
                k.exprs.push(*scrut);
                for a in arms {
                    if let Some(g) = a.guard {
                        k.pats_with_scope.push((a.pat, ScopeBody::Expr(g)));
                    }
                    k.pats_with_scope.push((a.pat, ScopeBody::Expr(a.body)));
                }
            }
            Expr::Call { callee, args } => {
                k.exprs.push(*callee);
                k.exprs.extend(args.iter().copied());
            }
            Expr::MethodCall { recv, args, .. } => {
                k.exprs.push(*recv);
                k.exprs.extend(args.iter().copied());
            }
            Expr::Field { base, .. } | Expr::TupleField { base, .. } => k.exprs.push(*base),
            Expr::Index { base, index } => {
                k.exprs.push(*base);
                k.exprs.push(*index);
            }
            Expr::Binary { lhs, rhs, .. } | Expr::Assign { lhs, rhs } | Expr::AssignOp { lhs, rhs, .. } => {
                k.exprs.push(*lhs);
                k.exprs.push(*rhs);
            }
            Expr::Unary { expr, .. } | Expr::Ref { expr, .. } | Expr::Deref(expr) | Expr::Try(expr) | Expr::Await(expr) => {
                k.exprs.push(*expr)
            }
            Expr::Cast { expr, ty } => {
                k.exprs.push(*expr);
                k.ty = Some(*ty);
            }
            Expr::Range { lo, hi, .. } => {
                if let Some(e) = lo {
                    k.exprs.push(*e);
                }
                if let Some(e) = hi {
                    k.exprs.push(*e);
                }
            }
            Expr::Break { value, .. } => {
                if let Some(e) = value {
                    k.exprs.push(*e);
                }
            }
            Expr::Continue(_) => {}
            Expr::Return(e) => {
                if let Some(e) = e {
                    k.exprs.push(*e);
                }
            }
            Expr::Macro { args, .. } => k.exprs.extend(args.iter().copied()),
            Expr::Tuple(es) | Expr::Array(es) => k.exprs.extend(es.iter().copied()),
            Expr::ArrayRepeat { value, len } => {
                k.exprs.push(*value);
                k.exprs.push(*len);
            }
            Expr::Closure { params, ret, body, .. } => {
                for p in params {
                    if let Some(t) = p.ty {
                        let _ = t;
                    }
                    k.pats_with_scope.push((p.pat, ScopeBody::None));
                }
                if let Some(r) = ret {
                    k.ty = Some(*r);
                }
                k.exprs.push(*body);
            }
            Expr::Let { pat, scrut } => {
                k.exprs.push(*scrut);
                k.pats_with_scope.push((*pat, ScopeBody::None));
            }
            Expr::QPath { .. } | Expr::MacroCall(_) => {}
        }
        k
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::def::{CrateIds, LOCAL_CRATE, stable_crate_hash};
    use crate::driver::graph::Reads;
    use crate::intern::{Interner, Known};
    use crate::protocol::ProfileFlags;

    fn resolve(files: &[(&str, &str)], crate_name: &str) -> Result<ResolvedCrate, ResolveError> {
        let dir = std::env::temp_dir().join(format!("lust-worklist-test-{}-{}", std::process::id(), crate_name));
        let _ = std::fs::remove_dir_all(&dir);
        for (rel, text) in files {
            let p = dir.join(rel);
            std::fs::create_dir_all(p.parent().unwrap()).unwrap();
            std::fs::write(&p, text).unwrap();
        }
        let interner = Interner::default();
        let known = Known::new(&interner);
        let root = dir.join("main.rs");
        let input = CrateInput {
            root_path: root.clone(),
            root_text: std::fs::read_to_string(&root).unwrap(),
            env: CfgEnv::new("", &[], false, ProfileFlags::DEV),
            crate_ids: CrateIds { local: LOCAL_CRATE, stable: stable_crate_hash(&format!("pkg:{crate_name}"), "bin", crate_name, false) },
            crate_name: crate_name.into(),
            externs: Vec::new(),
        };
        // The interner must outlive the tables' Syms only for lookups in
        // the test; leak it (tests are short-lived).
        let interner: &'static Interner = Box::leak(Box::new(interner));
        let known: &'static Known = Box::leak(Box::new(known));
        resolve_crate(&input, interner, known)
    }

    /// The per-file cache is transparent: a second resolve with the
    /// same cache (one shared interner, as in a daemon session) gives
    /// the same crate, an edit to one file is seen, and deleting a
    /// module file still errors instead of serving the cached stream.
    #[test]
    fn resolve_cache_is_transparent() {
        let dir = std::env::temp_dir().join(format!("lust-worklist-cache-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("main.rs"), "mod a;\nmod b;\nfn main() { println!(\"{}\", a::v() + b::v()); }").unwrap();
        std::fs::write(dir.join("a.rs"), "pub fn v() -> i64 { 1 }").unwrap();
        std::fs::write(dir.join("b.rs"), "pub fn v() -> i64 { 2 }").unwrap();
        let interner: &'static Interner = Box::leak(Box::new(Interner::default()));
        let known: &'static Known = Box::leak(Box::new(Known::new(interner)));
        let input = |dir: &std::path::Path| CrateInput {
            root_path: dir.join("main.rs"),
            root_text: std::fs::read_to_string(dir.join("main.rs")).unwrap(),
            env: CfgEnv::new("", &[], false, ProfileFlags::DEV),
            crate_ids: CrateIds { local: LOCAL_CRATE, stable: stable_crate_hash("pkg:cachetest", "bin", "cachetest", false) },
            crate_name: "cachetest".into(),
            externs: Vec::new(),
        };
        let mut cache = ResolveCache::new();
        let first = resolve_crate_cached(&input(&dir), interner, known, &mut cache).ok().expect("first resolves");
        let second = resolve_crate_cached(&input(&dir), interner, known, &mut cache).ok().expect("cached resolves");
        assert_eq!(first.fn_lines, second.fn_lines);
        assert_eq!(first.body_hashes, second.body_hashes);
        assert_eq!(first.structure_hash, second.structure_hash);
        assert_eq!(first.ast.items.len(), second.ast.items.len());
        // An edit to one file changes exactly its body hash.
        std::fs::write(dir.join("b.rs"), "pub fn v() -> i64 { 3 }").unwrap();
        let third = resolve_crate_cached(&input(&dir), interner, known, &mut cache).ok().expect("edited resolves");
        let changed: Vec<usize> = (0..first.body_hashes.len()).filter(|&i| first.body_hashes[i] != third.body_hashes[i]).collect();
        assert_eq!(changed.len(), 1, "only the edited file's fn rehashes");
        // A deleted module file is an error, never a cached stream.
        std::fs::remove_file(dir.join("b.rs")).unwrap();
        assert!(resolve_crate_cached(&input(&dir), interner, known, &mut cache).is_err(), "missing file errors");
        let _ = std::fs::remove_dir_all(&dir);
    }

    /// The same file in two crates gets two DefIds (section 1.2): AST
    /// and defs are per (crate, module), never shared by file.
    #[test]
    fn shared_file_two_crates_two_def_ids() {
        let files: &[(&str, &str)] = &[("main.rs", "mod s;\nfn main() { println!(\"{}\", s::v()); }"), ("s.rs", "pub fn v() -> i64 { 1 }")];
        let a = resolve(files, "crate_a").ok().expect("crate a resolves");
        let b = resolve(files, "crate_b").ok().expect("crate b resolves");
        let defs = |r: &ResolvedCrate| {
            let mut v: Vec<u64> = r.tables.def_info.keys().map(|d| d.hash.0).collect();
            v.sort_unstable();
            v
        };
        assert!(!defs(&a).is_empty());
        assert_ne!(defs(&a), defs(&b), "same file, different crates, different defs");
    }

    /// The explicit-through-glob example of section 1.3 resolves, and a
    /// glob collision is stored ambiguous without error until used:
    /// both crates resolve here, and the binding answer differs
    /// (Def for the pinned crate, Ambiguous for the colliding one).
    #[test]
    fn glob_bindings_pin_and_ambiguity() {
        let pinned: &[(&str, &str)] = &[
            ("main.rs", "mod checker;\nmod prelude;\nuse prelude::Kind;\nfn main() { println!(\"{}\", 1); }"),
            ("prelude.rs", "pub use crate::checker::Kind;"),
            ("checker.rs", "pub mod mapper;\npub use mapper::*;"),
            ("checker/mapper.rs", "pub enum Kind { A }"),
        ];
        let r = resolve(pinned, "pin");
        assert!(r.is_ok(), "pinned resolves: {:?}", r.err().map(|e| e.diags.len()));

        let colliding: &[(&str, &str)] = &[
            ("main.rs", "mod a;\nmod b;\nuse a::*;\nuse b::*;\nfn main() { println!(\"{}\", 1); }"),
            ("a.rs", "pub fn v() -> i64 { 1 }"),
            ("b.rs", "pub fn v() -> i64 { 2 }"),
        ];
        let r = resolve(colliding, "collide").ok().expect("unused collision resolves");
        let interner = Interner::default();
        let name = interner.intern("v");
        // The tables were built with a leaked interner in `resolve`;
        // Sym values differ across interners, so ask through the flat
        // index state instead: the root map holds the ambiguity.
        let _ = name;
        let ambiguous =
            r.tables.maps.first().is_some_and(|maps| maps.iter().any(|m| m.values().any(|s| matches!(s, BindState::Ambiguous))));
        assert!(ambiguous, "glob collision stored ambiguous, no error while unused");
        let _reads = Reads::new();
    }
}

/// Moves inline module bodies into the flat item list, dropping mod,
/// use, and extern crate items (their bindings live in the tables).
/// Flattens one file's items for the merged Ast, recording the module
/// each surviving item came from in `out_mods` (parallel to `out`).
/// Inline module bodies splice in with their child module from
/// `list_module`; mod, use, and extern crate items drop.
fn flatten_items_mods(
    items: Vec<Item>,
    module: ModuleId,
    fi: usize,
    prefix: &[Sym],
    list_module: &FxMap<ItemListKey, ModuleId>,
    out: &mut Vec<Item>,
    out_mods: &mut Vec<ModuleId>,
) {
    for item in items {
        match item.kind {
            ItemKind::Mod(m) => {
                if let Some(body) = m.body {
                    let mut key = prefix.to_vec();
                    key.push(m.name);
                    let child = list_module.get(&(fi, key.clone())).copied().unwrap_or(module);
                    flatten_items_mods(body, child, fi, &key, list_module, out, out_mods);
                }
            }
            ItemKind::Use(_) | ItemKind::ExternCrate(_) => {}
            _ => {
                out.push(item);
                out_mods.push(module);
            }
        }
    }
}
